LOG_MODULE_REGISTER(tls_credentials_keygen, CONFIG_TLS_CREDENTIALS_LOG_LEVEL);

BUILD_ASSERT(IS_ENABLED(CONFIG_TLS_CREDENTIALS_KEYGEN_SECP256R1) ||
		     IS_ENABLED(CONFIG_TLS_CREDENTIALS_KEYGEN_SECP384R1),
	     "Enable at least one key type");

static int crypto_init(void)
{
	psa_status_t status = psa_crypto_init();

	if (status != PSA_SUCCESS) {
		LOG_ERR("psa_crypto_init failed, status: %d", status);
		return -EIO;
	}

	return 0;
}

static bool key_exists(psa_key_id_t key_id)
{
	psa_key_attributes_t attr = PSA_KEY_ATTRIBUTES_INIT;
	bool exists = psa_get_key_attributes(key_id, &attr) == PSA_SUCCESS;

	psa_reset_key_attributes(&attr);

	return exists;
}

/* Key ID registered for the tag, without checking that the key exists. Returns -ENOENT if there
 * is no registration, -EPERM if the key was not generated by this library, or another negative
 * errno if the registration cannot be read.
 */
static int registered_key_id_get(sec_tag_t tag, psa_key_id_t *key_id)
{
	size_t len = sizeof(*key_id);
	int err;

	err = tls_credential_get(tag, TLS_CREDENTIAL_PRIVATE_KEY_PSA, key_id, &len);
	if (err == -EFBIG) {
		return -EPERM;
	} else if (err) {
		return err;
	}

	if (len != sizeof(*key_id) || !tls_credential_keygen_store_id_is_own(*key_id)) {
		return -EPERM;
	}

	return 0;
}

/* Returns 0 if the tag has no private key, -EEXIST if it has one, or another negative errno. */
static int private_key_check(sec_tag_t tag)
{
	static const enum tls_credential_type types[] = {
		TLS_CREDENTIAL_PRIVATE_KEY,
		TLS_CREDENTIAL_PRIVATE_KEY_PSA,
	};

	for (size_t i = 0; i < ARRAY_SIZE(types); i++) {
		size_t len = 0;
		int err = tls_credential_get(tag, types[i], NULL, &len);

		if (err == 0 || err == -EFBIG) {
			return -EEXIST;
		} else if (err != -ENOENT) {
			return err;
		}
	}

	return 0;
}

/* True only if PSA reports that no key has the key ID, not for other errors. */
static bool key_missing(psa_key_id_t key_id)
{
	psa_key_attributes_t attr = PSA_KEY_ATTRIBUTES_INIT;
	psa_status_t status = psa_get_key_attributes(key_id, &attr);

	psa_reset_key_attributes(&attr);

	return status == PSA_ERROR_INVALID_HANDLE || status == PSA_ERROR_DOES_NOT_EXIST;
}

/* Remove a registration of an own key ID without a key, which a power loss in
 * tls_credential_keygen_generate() leaves. Must be called with the credentials locked.
 */
static int stale_registration_remove(sec_tag_t tag)
{
	psa_key_id_t key_id;

	if (registered_key_id_get(tag, &key_id) != 0 || !key_missing(key_id)) {
		return 0;
	}

	LOG_WRN("Removing the registration of missing key 0x%08x for sec tag %d", key_id, tag);

	return tls_credential_delete(tag, TLS_CREDENTIAL_PRIVATE_KEY_PSA);
}

/* The tag iteration returns no tags if the credentials are not loaded, so check that the
 * credentials can be read before the key IDs in use are collected.
 */
static int credentials_readable(void)
{
	size_t len = 0;
	int err = tls_credential_get(0, TLS_CREDENTIAL_PRIVATE_KEY_PSA, NULL, &len);

	return (err == 0 || err == -ENOENT || err == -EFBIG) ? 0 : err;
}

/* Allocate a key ID from the key store, which gets the key IDs that are in use. Must be called
 * with the credentials locked.
 */
static int free_key_id_get(sec_tag_t tag, enum tls_credential_keygen_type type,
			   psa_key_id_t *key_id)
{
	psa_key_id_t used[CONFIG_TLS_MAX_CREDENTIALS_NUMBER];
	size_t used_count = 0;
	psa_key_id_t id;
	int err;

	err = credentials_readable();
	if (err) {
		return err;
	}

	for (sec_tag_t t = credential_next_tag_get(TLS_SEC_TAG_NONE); t != TLS_SEC_TAG_NONE;
	     t = credential_next_tag_get(t)) {
		err = registered_key_id_get(t, &id);
		if (err == 0) {
			if (used_count == ARRAY_SIZE(used)) {
				return -ENOMEM;
			}
			used[used_count++] = id;
		} else if (err != -ENOENT && err != -EPERM) {
			return err;
		}
	}

	return tls_credential_keygen_store_id_alloc(tag, type, used, used_count, key_id);
}

static bool key_id_in(psa_key_id_t key_id, const psa_key_id_t *ids, size_t count)
{
	for (size_t i = 0; i < count; i++) {
		if (ids[i] == key_id) {
			return true;
		}
	}

	return false;
}

int tls_credential_keygen_store_id_pick(size_t count, psa_key_id_t (*key_id_at)(size_t index),
					const psa_key_id_t *used, size_t used_count,
					psa_key_id_t *key_id)
{
	psa_key_id_t id;

	for (size_t i = 0; i < count; i++) {
		id = key_id_at(i);
		if (key_id_in(id, used, used_count)) {
			continue;
		}

		/* Never destroy a key that is not registered: it cannot be recovered. */
		if (key_exists(id)) {
			continue;
		}

		*key_id = id;
		return 0;
	}

	return -ENOSPC;
}

static int key_attributes_set(psa_key_attributes_t *attr, enum tls_credential_keygen_type type)
{
	switch (type) {
	case TLS_CREDENTIAL_KEYGEN_ECDSA_SECP256R1:
		if (!IS_ENABLED(CONFIG_TLS_CREDENTIALS_KEYGEN_SECP256R1)) {
			return -ENOTSUP;
		}
		psa_set_key_bits(attr, 256);
		break;
	case TLS_CREDENTIAL_KEYGEN_ECDSA_SECP384R1:
		if (!IS_ENABLED(CONFIG_TLS_CREDENTIALS_KEYGEN_SECP384R1)) {
			return -ENOTSUP;
		}
		psa_set_key_bits(attr, 384);
		break;
	default:
		return -EINVAL;
	}

	psa_set_key_type(attr, PSA_KEY_TYPE_ECC_KEY_PAIR(PSA_ECC_FAMILY_SECP_R1));
	/* Any hash, so that TLS can choose the signature algorithm. No PSA_KEY_USAGE_EXPORT, so
	 * the private key cannot be read back. A JWT signer checks its signature with
	 * psa_verify_message().
	 */
	psa_set_key_algorithm(attr, PSA_ALG_ECDSA(PSA_ALG_ANY_HASH));
	psa_set_key_usage_flags(attr, PSA_KEY_USAGE_SIGN_HASH | PSA_KEY_USAGE_SIGN_MESSAGE |
				      PSA_KEY_USAGE_VERIFY_MESSAGE);

	return tls_credential_keygen_store_attr_set(type, attr);
}

int tls_credential_keygen_generate(sec_tag_t tag, enum tls_credential_keygen_type type)
{
	psa_key_attributes_t attr = PSA_KEY_ATTRIBUTES_INIT;
	psa_key_id_t key_id;
	psa_status_t status;
	int err;

	err = crypto_init();
	if (err) {
		return err;
	}

	credentials_lock();

	err = key_attributes_set(&attr, type);
	if (err) {
		goto unlock;
	}

	err = stale_registration_remove(tag);
	if (err) {
		goto unlock;
	}

	err = private_key_check(tag);
	if (err) {
		goto unlock;
	}

	err = free_key_id_get(tag, type, &key_id);
	if (err) {
		LOG_ERR("No free key ID, error: %d", err);
		goto unlock;
	}

	/* Register first, so that a power loss leaves a registration without a key, not a key
	 * without a registration.
	 */
	err = tls_credential_add(tag, TLS_CREDENTIAL_PRIVATE_KEY_PSA, &key_id, sizeof(key_id));
	if (err) {
		LOG_ERR("Failed to register the key for sec tag %d, error: %d", tag, err);
		goto unlock;
	}

	psa_set_key_id(&attr, key_id);
	status = psa_generate_key(&attr, &key_id);
	if (status != PSA_SUCCESS) {
		LOG_ERR("psa_generate_key failed, status: %d", status);
		(void)tls_credential_delete(tag, TLS_CREDENTIAL_PRIVATE_KEY_PSA);
		err = -EIO;
		goto unlock;
	}

	LOG_INF("Generated key 0x%08x for sec tag %d", key_id, tag);

unlock:
	credentials_unlock();
	psa_reset_key_attributes(&attr);

	return err;
}

int tls_credential_keygen_delete(sec_tag_t tag)
{
	psa_key_id_t key_id;
	psa_status_t status;
	int err;

	err = crypto_init();
	if (err) {
		return err;
	}

	credentials_lock();

	err = registered_key_id_get(tag, &key_id);
	if (err) {
		goto unlock;
	}

	/* Remove the registration first. If the key cannot be destroyed, it is left over and its
	 * key ID is not used again.
	 */
	err = tls_credential_delete(tag, TLS_CREDENTIAL_PRIVATE_KEY_PSA);
	if (err) {
		LOG_ERR("Failed to remove the registration for sec tag %d, error: %d", tag, err);
		goto unlock;
	}

	status = psa_destroy_key(key_id);
	if (status != PSA_SUCCESS && status != PSA_ERROR_INVALID_HANDLE) {
		LOG_ERR("psa_destroy_key failed, status: %d", status);
		err = -EIO;
		goto unlock;
	}

	LOG_INF("Deleted key 0x%08x for sec tag %d", key_id, tag);

unlock:
	credentials_unlock();

	return err;
}

/* Must be called with the credentials locked. */
static int key_id_get_locked(sec_tag_t tag, psa_key_id_t *key_id)
{
	psa_key_id_t id;
	int err;

	err = registered_key_id_get(tag, &id);
	if (err) {
		return err;
	}

	if (!key_exists(id)) {
		return -ENOENT;
	}

	*key_id = id;

	return 0;
}

int tls_credential_keygen_key_id_get(sec_tag_t tag, psa_key_id_t *key_id)
{
	int err;

	if (key_id == NULL) {
		return -EINVAL;
	}

	err = crypto_init();
	if (err) {
		return err;
	}

	credentials_lock();
	err = key_id_get_locked(tag, key_id);
	credentials_unlock();

	return err;
}

static mbedtls_md_type_t md_type_get(const psa_key_attributes_t *attr)
{
	if (psa_get_key_type(attr) != PSA_KEY_TYPE_ECC_KEY_PAIR(PSA_ECC_FAMILY_SECP_R1)) {
		return MBEDTLS_MD_NONE;
	}

	switch (psa_get_key_bits(attr)) {
	case 256:
		return MBEDTLS_MD_SHA256;
	case 384:
		return MBEDTLS_MD_SHA384;
	default:
		return MBEDTLS_MD_NONE;
	}
}

/* Wrap the key of the tag as an opaque PK. Must be called with the credentials locked. */
static int pk_wrap(sec_tag_t tag, mbedtls_pk_context *pk, psa_key_attributes_t *attr)
{
	psa_key_id_t key_id;
	int ret;

	ret = key_id_get_locked(tag, &key_id);
	if (ret) {
		return ret;
	}

	if (psa_get_key_attributes(key_id, attr) != PSA_SUCCESS) {
		return -ENOENT;
	}

	ret = mbedtls_pk_wrap_psa(pk, mbedtls_svc_key_id_make(0, key_id));
	if (ret != 0) {
		LOG_ERR("mbedtls_pk_wrap_psa failed: -0x%04x", (unsigned int)-ret);
		return -EIO;
	}

	return 0;
}

/* The DER writers of Mbed TLS write at the end of the buffer, so move the result to the front. */
static int der_result(int ret, uint8_t *out, size_t out_size, size_t *out_len)
{
	if (ret < 0) {
		LOG_ERR("DER writing failed: -0x%04x", (unsigned int)-ret);
		return -EIO;
	}

	*out_len = (size_t)ret;
	memmove(out, out + out_size - *out_len, *out_len);

	return 0;
}

int tls_credential_keygen_csr(sec_tag_t tag, const char *subject, uint8_t *out, size_t out_size,
			      size_t *out_len)
{
	psa_key_attributes_t attr = PSA_KEY_ATTRIBUTES_INIT;
	mbedtls_x509write_csr csr;
	mbedtls_pk_context pk;
	mbedtls_md_type_t md;
	int ret;

	if (subject == NULL || out == NULL || out_len == NULL) {
		return -EINVAL;
	}

	ret = crypto_init();
	if (ret) {
		return ret;
	}

	mbedtls_pk_init(&pk);
	mbedtls_x509write_csr_init(&csr);
	credentials_lock();

	/* PSA makes the signature of the CSR, so the private key is never exported. */
	ret = pk_wrap(tag, &pk, &attr);
	if (ret) {
		goto cleanup;
	}

	md = md_type_get(&attr);
	if (md == MBEDTLS_MD_NONE) {
		ret = -ENOTSUP;
		goto cleanup;
	}

	mbedtls_x509write_csr_set_md_alg(&csr, md);

	ret = mbedtls_x509write_csr_set_subject_name(&csr, subject);
	if (ret != 0) {
		LOG_ERR("Invalid CSR subject name: -0x%04x", (unsigned int)-ret);
		ret = -EINVAL;
		goto cleanup;
	}

	mbedtls_x509write_csr_set_key(&csr, &pk);

	ret = mbedtls_x509write_csr_der(&csr, out, out_size);

	/* For an opaque key, Mbed TLS reports a public key that does not fit as bad input data,
	 * so that error is a small buffer only if the buffer can be too small.
	 */
	if (ret == PSA_ERROR_BUFFER_TOO_SMALL ||
	    (ret == MBEDTLS_ERR_PK_BAD_INPUT_DATA &&
	     out_size < TLS_CREDENTIAL_KEYGEN_CSR_SIZE(strlen(subject)))) {
		ret = -EFBIG;
	} else {
		ret = der_result(ret, out, out_size, out_len);
	}

cleanup:
	credentials_unlock();
	mbedtls_x509write_csr_free(&csr);
	mbedtls_pk_free(&pk);
	psa_reset_key_attributes(&attr);

	return ret;
}

int tls_credential_keygen_pubkey_get(sec_tag_t tag, uint8_t *out, size_t out_size,
				     size_t *out_len)
{
	uint8_t buf[TLS_CREDENTIAL_KEYGEN_PUBKEY_MAX_SIZE];
	psa_key_attributes_t attr = PSA_KEY_ATTRIBUTES_INIT;
	mbedtls_pk_context pk;
	size_t len;
	int ret;

	if (out == NULL || out_len == NULL) {
		return -EINVAL;
	}

	ret = crypto_init();
	if (ret) {
		return ret;
	}

	mbedtls_pk_init(&pk);
	credentials_lock();

	ret = pk_wrap(tag, &pk, &attr);
	if (ret) {
		goto cleanup;
	}

	ret = der_result(mbedtls_pk_write_pubkey_der(&pk, buf, sizeof(buf)), buf, sizeof(buf),
			 &len);
	if (ret) {
		goto cleanup;
	}

	if (len > out_size) {
		ret = -EFBIG;
		goto cleanup;
	}

	memcpy(out, buf, len);
	*out_len = len;

cleanup:
	credentials_unlock();
	mbedtls_pk_free(&pk);
	psa_reset_key_attributes(&attr);

	return ret;
}

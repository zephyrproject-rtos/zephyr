#ifndef ZEPHYR_SUBSYS_USB_HOST_CLASS_USBH_SCSI_H_
#define ZEPHYR_SUBSYS_USB_HOST_CLASS_USBH_SCSI_H_

/* SCSI command opcodes, named after SPC and SBC */
#define SCSI_TST_U_RDY       0x00U
#define SCSI_REQUEST_SENSE   0x03U
#define SCSI_INQUIRY         0x12U
#define SCSI_MODE_SENSE6     0x1AU
#define SCSI_START_STOP_UNIT 0x1BU
#define SCSI_READ_CAPACITY   0x25U
#define SCSI_READ10          0x28U
#define SCSI_WRITE10         0x2AU
#define SCSI_SYNC_CACHE10    0x35U

#define SCSI_TST_U_RDY_CDB_LEN       6U
#define SCSI_REQUEST_SENSE_CDB_LEN   6U
#define SCSI_INQUIRY_CDB_LEN         6U
#define SCSI_MODE_SENSE6_CDB_LEN     6U
#define SCSI_START_STOP_UNIT_CDB_LEN 6U
#define SCSI_READ_CAPACITY_CDB_LEN   10U
#define SCSI_RW10_CDB_LEN            10U
#define SCSI_SYNC_CACHE10_CDB_LEN    10U

#define SCSI_MAX_CDB_SIZE 16U

#define SCSI_INQUIRY_RESP_LEN       36U
#define SCSI_READ_CAPACITY_RESP_LEN 8U
#define SCSI_REQUEST_SENSE_RESP_LEN 18U
#define SCSI_MODE_SENSE6_HDR_LEN    4U

#define SCSI_INQUIRY_PDT_MASK     0x1FU
#define SCSI_INQUIRY_PDT_DIRECT   0x00U
#define SCSI_INQUIRY_RMB          BIT(7)
#define SCSI_MODE_SENSE_ALL_PAGES 0x3FU
#define SCSI_MODE_SENSE_WP        BIT(7)
#define SCSI_START_STOP_START     BIT(0)

/* Fixed format sense data */
#define SCSI_SENSE_RESP_CODE_MASK 0x7FU
#define SCSI_SENSE_RESP_CURRENT   0x70U
#define SCSI_SENSE_RESP_DEFERRED  0x71U
#define SCSI_SENSE_KEY_MASK       0x0FU

#define SCSI_SENSE_NOT_READY       0x02U
#define SCSI_SENSE_ILLEGAL_REQUEST 0x05U
#define SCSI_SENSE_UNIT_ATTENTION  0x06U
#define SCSI_SENSE_DATA_PROTECT    0x07U

#define SCSI_ASC_LUN_NOT_READY      0x04U
#define SCSI_ASCQ_INIT_CMD_REQUIRED 0x02U
#define SCSI_ASC_INVALID_OPCODE     0x20U
#define SCSI_ASC_MEDIUM_MAY_CHANGED 0x28U
#define SCSI_ASC_MEDIUM_NOT_PRESENT 0x3AU

#endif /* ZEPHYR_SUBSYS_USB_HOST_CLASS_USBH_SCSI_H_ */

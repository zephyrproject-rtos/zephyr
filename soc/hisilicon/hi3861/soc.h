#define HI3861_GLB_WDT_RST_SEL_WDG     BIT(0)

#define HI3861_CLDO_CLKEN_REG          (HI3861_CLDO_CTL_BASE + 0x30)
#define HI3861_CLDO_CLKEN_TIMER0       BIT(6)
#define HI3861_CLDO_CLKEN_TIMER1       BIT(7)
#define HI3861_UART_MAC80M_CLKEN_REG   (HI3861_W_CTL_BASE + 0x40)
#define HI3861_UART_MAC80M_CLKEN_UART2 BIT(6)
#define HI3861_UART_MAC80M_CLKEN_BUS2  BIT(9)

#define HI3861_PMU_UDSLEEP_BUTTON_CTRL_REG   (HI3861_PMU_CMU_CTL_BASE + 0x020)
#define HI3861_PMU_WLAN_STA0_ALLOW_SLEEP_REG (HI3861_PMU_CMU_CTL_BASE + 0x900)

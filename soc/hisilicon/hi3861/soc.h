#define HI3861_PMU_WLAN_AP0_ALLOW_SLEEP_REG  (HI3861_PMU_CMU_CTL_BASE + 0x908)
#define HI3861_PMU_WLAN_PF_ALLOW_SLEEP_REG   (HI3861_PMU_CMU_CTL_BASE + 0x90c)
#define HI3861_PMU_WLAN_HOST_ALLOW_SLEEP_REG (HI3861_PMU_CMU_CTL_BASE + 0x910)
#define HI3861_PMU_WLAN_SLP_EVT_EN_REG       (HI3861_PMU_CMU_CTL_BASE + 0x920)
#define HI3861_PMU_WLAN_SLP_EVT_CLR_REG      (HI3861_PMU_CMU_CTL_BASE + 0x924)
#define HI3861_PMU_WLAN_SLP_INT_CLR_REG      (HI3861_PMU_CMU_CTL_BASE + 0x934)
#define HI3861_PMU_WLAN_WKUP_EVT_CLR_REG     (HI3861_PMU_CMU_CTL_BASE + 0x944)
#define HI3861_PMU_WLAN_WKUP_INT_CLR_REG     (HI3861_PMU_CMU_CTL_BASE + 0x954)

#define HI3861_IOCFG_GPIO3_SELECT_REG (HI3861_IOCFG_BASE + 0x610)
#define HI3861_IOCFG_GPIO4_SELECT_REG (HI3861_IOCFG_BASE + 0x614)
#define HI3861_IOCFG_GPIO3_UART0_TX   1
#define HI3861_IOCFG_GPIO4_UART0_RX   2

#define HI3861_CSR_CACHE_CONTROL0 0x7c0
#define HI3861_CSR_CACHE_CONTROL1 0x7c1
#define HI3861_CSR_INTPRI0        0xbc0
#define HI3861_CSR_INTPRI1        0xbc1
#define HI3861_CSR_INTPRI2        0xbc2
#define HI3861_CSR_INTPRI3        0xbc3
#define HI3861_CSR_INTPRI4        0xbc4

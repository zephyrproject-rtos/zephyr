"""Generate an AURIX pin function devicetree include from a data sheet.

Reads the port function tables of an AURIX data sheet (PDF) and writes one
/omit-if-no-ref/ node per pin function in the format of the
infineon,aurix-pinctrl binding:

- every alternate output function (O1 to O15) of a pin, with output-enable;
  general-purpose output (O0), reserved slots and outputs under hardware
  control (Ctrl. column "O" without a number) are left out,
- every input whose data sheet symbol ends in the peripheral input select
  letter (A to H, followed by N or P for LVDS pairs), for the modules listed
  in INPUT_SIGNALS; the select goes into the function field (A = 0 to H = 7).

Inputs without a select, with numeric selects (GTM TIM, ERAY, ...) and the
inputs of other modules are counted and reported but not generated.

The tables of one package are selected by a page range, for example:

    gen_pinctrl.py TC37xAA_DS_v1.1.pdf 113-193 \\
        dts/tricore/infineon/tc3x/tc375tp-pinctrl.dtsi

With --check the output file is compared instead of written. Requires pypdf.
"""

import argparse
import collections
import hashlib
import re
import sys
from pathlib import Path

try:
    import pypdf
except ImportError:
    sys.exit("gen_pinctrl.py needs pypdf: pip install pypdf")

# Input signals whose last letter (before N/P of LVDS pairs) is the input select
INPUT_SIGNALS = re.compile(
    r"(ASCLIN\d+_A(RX|CTS)"
    r"|CAN\d+_RXD|CANXL\d+_RXD"
    r"|QSPI\d+_(MRST|MTSR|SCLK|SLSI)"
    r"|I2C\d+_(SCL|SDA)"
    r"|SENT\d*_SENT\d+|PSI5_RX\d+|PSI5S\d*_RX"
    r"|GETH\d*(_P[\dX])?_(COL|CRS|CRSDV|MDIO|RCTL|REFCLK|RXCLK|RXD\d*|RXDV|RXER|TXCLK)"
    r"|LETH\d+_P\d+_(COL|CRS|ED|MDIO|MII_RMII_RXD\d+|MII_RXD\d+|MII_RXDV|MII_RXER"
    r"|REFCLK|RMII_CRSDV|RXCLK|RXD|TXCLK)"
    r"|GPT\d+_(T\d+IN|T\d+EUD|CAPIN)"
    r"|CCU\d+_(CC\d+IN|CCPOS\d+|CTRAP|T\d+HR)"
    r"|EDSADC_(DSCIN\d+|DSDIN\d+|ITR\d+|SGN)"
    r"|SCU_E_REQ\d+|SCU_EMGSTOP_PORT_"
    r"|XSPI\d+_(RXD\d+|RWDS))"
    r"(?P<sel>[A-H])(?P<lvds>[NP]?)"
)

PIN_ROW = re.compile(
    r"(?:[A-Z]{0,2}\d+) (?:AN\d+ ?/ ?)?P(?P<port>\d+)\.(?P<pin>\d+)"
    r"(?: ?/ ?[A-Z0-9_]+)? I (?P<buf>[A-Z]+).*"
)
OUTPUT_ROW = re.compile(r"(?P<sym>\S+) O ?(?P<num>\d+)(?:\s.*)?")
RESERVED_ROW = re.compile(r"(—|-) ?O ?\d+(?:\s.*)?")
HW_OUTPUT_ROW = re.compile(r"(?P<sym>[A-Z][A-Z0-9_]+) O(?:\s.*)?")
INPUT_ROW = re.compile(r"(?P<sym>[A-Z][A-Z0-9_]*_[A-Z0-9_]+)(?: (?P<desc>.*))?")
SYMBOL = re.compile(r"[A-Z][A-Z0-9_]+")
WRAPPED = re.compile(r"[A-Z0-9_]{1,4}")
TIMING_SUFFIX = re.compile(r"_F$")

HEADER = """\
/*
 * SPDX-FileCopyrightText: Copyright (c) 2024 Infineon Technologies AG,
 * SPDX-FileCopyrightText: or an affiliate of Infineon Technologies AG. All rights reserved.
 * SPDX-FileCopyrightText: Copyright (c) 2026 Linumiz
 *
 * SPDX-License-Identifier: Apache-2.0
 */

/*
 * Generated by soc/infineon/aurix/tools/gen_pinctrl.py from the port function
 * tables of {source}, pages {pages}
 * (sha256 {digest}).
 *
 * Do not edit this file manually: regenerate it with the script.
 */

#include <zephyr/dt-bindings/pinctrl/infineon-aurix-pinctrl.h>

&pinctrl {{
"""


def table_lines(pdf, first, last):
    """Text lines of the given pages, stripped."""
    reader = pypdf.PdfReader(pdf)
    if not 1 <= first <= last <= len(reader.pages):
        sys.exit(f"{pdf}: page range {first}-{last} outside 1-{len(reader.pages)}")
    lines = []
    for page in reader.pages[first - 1 : last]:
        lines.extend(line.strip() for line in (page.extract_text() or "").splitlines())
    return [line for line in lines if line]


def parse(lines):
    """Return ({pin: {"out": {num: sym}, "in": [sym]}}, Counter of skipped inputs)."""
    pins = {}
    cur = None
    i = 0

    while i < len(lines):
        line = lines[i]
        i += 1

        m = PIN_ROW.fullmatch(line)
        if m:
            cur = (int(m["port"]), int(m["pin"]))
            if cur in pins:
                sys.exit(f"P{cur[0]}.{cur[1]}: pin row seen twice")
            pins[cur] = {"out": {}, "in": []}
            continue
        if cur is None:
            continue

        # A symbol wrapped onto the next line, e.g. "LETH0_P2_MII_RMII_RXD" + "0C ..."
        if SYMBOL.fullmatch(line) and i < len(lines):
            head, _, rest = lines[i].partition(" ")
            if WRAPPED.fullmatch(head) and not OUTPUT_ROW.fullmatch(lines[i]):
                line = line + head + (" " + rest if rest else "")
                i += 1

        if RESERVED_ROW.fullmatch(line):
            continue

        m = OUTPUT_ROW.fullmatch(line)
        if m:
            num = int(m["num"])
            sym = TIMING_SUFFIX.sub("", m["sym"])
            if num > 15:
                sys.exit(f"P{cur[0]}.{cur[1]}: output O{num} out of range")
            if num in pins[cur]["out"]:
                sys.exit(f"P{cur[0]}.{cur[1]}: output O{num} listed twice")
            pins[cur]["out"][num] = sym
            continue

        if HW_OUTPUT_ROW.fullmatch(line):
            continue

        m = INPUT_ROW.fullmatch(line)
        # Description continuations start in lower case ("or LETH0_P2_...")
        if m and (m["desc"] is None or m["desc"][:1].isupper()):
            pins[cur]["in"].append(TIMING_SUFFIX.sub("", m["sym"]))

    return pins


def functions(pins):
    """Return ({label: (port, pin, func, output)}, Counter of skipped inputs)."""
    result = {}
    skipped = collections.Counter()

    def add(label, entry):
        if label in result and result[label] != entry:
            sys.exit(f"{label}: two different functions with the same name")
        result[label] = entry

    for (port, pin), p in sorted(pins.items()):
        # Every pin with outputs lists its general-purpose output as O0 first
        if p["out"] and p["out"].get(0) not in (f"P{port:02d}.{pin}", f"P{port}.{pin}"):
            sys.exit(f"P{port}.{pin}: no general-purpose output O0, table not parsed correctly")

        names = collections.Counter(p["out"].values())
        for num, sym in sorted(p["out"].items()):
            if num == 0:
                continue
            label = f"{sym.lower()}_p{port}_{pin}"
            if names[sym] > 1:
                label += f"_o{num}"
            add(label, (port, pin, num, True))

        for sym in p["in"]:
            m = INPUT_SIGNALS.fullmatch(sym)
            if m is None:
                skipped[re.match(r"[A-Z]+", sym)[0]] += 1
                continue
            add(f"{sym.lower()}_p{port}_{pin}", (port, pin, "ABCDEFGH".index(m["sel"]), False))

    return result, skipped


def render(funcs, source, pages, digest):
    out = [HEADER.format(source=source, pages=pages, digest=digest)]

    for i, label in enumerate(sorted(funcs)):
        port, pin, func, output = funcs[label]
        if i:
            out.append("\n")
        out.append(f"\t/omit-if-no-ref/ {label}: {label} {{\n")
        out.append(f"\t\tpinmux = <AURIX_PINMUX({port}, {pin}, {func})>;\n")
        if output:
            out.append("\t\toutput-enable;\n")
        out.append("\t};\n")

    out.append("};\n")

    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0], allow_abbrev=False)
    parser.add_argument("datasheet", type=Path, help="AURIX data sheet (PDF)")
    parser.add_argument("pages", help="pages of the package's port tables, e.g. 113-193")
    parser.add_argument("output", type=Path, help="pinctrl dtsi to write")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()

    m = re.fullmatch(r"(\d+)-(\d+)", args.pages)
    if m is None:
        sys.exit(f"bad page range {args.pages}")

    pins = parse(table_lines(args.datasheet, int(m[1]), int(m[2])))
    funcs, skipped = functions(pins)
    digest = hashlib.sha256(args.datasheet.read_bytes()).hexdigest()
    text = render(funcs, args.datasheet.name, args.pages, digest)

    outputs = sum(1 for f in funcs.values() if f[3])
    print(
        f"{len(pins)} pins, {outputs} output and {len(funcs) - outputs} input functions; "
        f"inputs not generated: {dict(sorted(skipped.items()))}"
    )

    if args.check:
        if not args.output.is_file() or args.output.read_text() != text:
            sys.exit(f"{args.output}: out of date, regenerate it with {Path(__file__).name}")
        return

    args.output.write_text(text)


if __name__ == "__main__":
    main()

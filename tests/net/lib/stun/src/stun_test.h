static inline void put16(uint8_t *p, uint16_t v)
{
	p[0] = (uint8_t)(v >> 8);
	p[1] = (uint8_t)v;
}

static inline void put32(uint8_t *p, uint32_t v)
{
	put16(p, (uint16_t)(v >> 16));
	put16(p + 2, (uint16_t)v);
}

static inline void fill_txid(uint8_t txid[STUN_TXID_SIZE], uint8_t first)
{
	for (int i = 0; i < STUN_TXID_SIZE; i++) {
		txid[i] = (uint8_t)(first + i);
	}
}

static inline void ensure_psa(void)
{
	zassert_equal(psa_crypto_init(), PSA_SUCCESS, "PSA init");
}

/* --- Socket addresses --- */
static inline void sa_v4(struct net_sockaddr *sa, uint8_t a, uint8_t b, uint8_t c, uint8_t d,
			 uint16_t port)
{
	struct net_sockaddr_in *sin4 = net_sin(sa);

	memset(sa, 0, sizeof(*sa));
	sin4->sin_family = NET_AF_INET;
	sin4->sin_port = net_htons(port);
	sin4->sin_addr.s4_addr[0] = a;
	sin4->sin_addr.s4_addr[1] = b;
	sin4->sin_addr.s4_addr[2] = c;
	sin4->sin_addr.s4_addr[3] = d;
}

static inline bool sa_is_v4(const struct net_sockaddr *sa, uint8_t a, uint8_t b, uint8_t c,
			    uint8_t d, uint16_t port)
{
	const struct net_sockaddr_in *sin4 = net_sin(sa);
	const uint8_t want[4] = {a, b, c, d};

	return sin4->sin_family == NET_AF_INET && sin4->sin_port == net_htons(port) &&
	       memcmp(sin4->sin_addr.s4_addr, want, sizeof(want)) == 0;
}


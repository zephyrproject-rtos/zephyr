/* --- Raw assembler: shapes the builder cannot produce (wrong attribute
 * lengths, unknown types, duplicates, attributes in the wrong place). ---
 */
struct raw_msg {
	uint8_t buf[1200];
	size_t len;   /* bytes written, including anything past the length field */
	size_t attrs; /* attribute-area size the header Length advertises */
};

static inline void raw_init(struct raw_msg *r, uint16_t type, uint8_t txid_fill)
{
	memset(r, 0, sizeof(*r));
	put16(r->buf, type);
	put32(r->buf + 4, (uint32_t)STUN_MAGIC_COOKIE);
	memset(r->buf + 8, txid_fill, STUN_TXID_SIZE);
	r->len = STUN_HEADER_SIZE;
	r->attrs = 0;
}

/* Append one TLV; alen is what goes in the attribute's length field (may lie
 * about vlen on purpose), the value area is padded with zeros to 4 bytes.
 */
static inline void raw_attr(struct raw_msg *r, uint16_t type, uint16_t alen, const void *val,
			    size_t vlen)
{
	size_t padded = (alen + 3U) & ~3U;

	zassert_true(r->len + 4U + padded <= sizeof(r->buf), "raw_msg overflow");
	zassert_true(vlen <= padded, "raw_attr value does not fit its attribute");
	put16(r->buf + r->len, type);
	put16(r->buf + r->len + 2, alen);
	if (vlen != 0U) {
		memcpy(r->buf + r->len + 4, val, vlen);
	}
	r->len += 4U + padded;
	r->attrs = r->len - STUN_HEADER_SIZE;
	put16(r->buf + 2, (uint16_t)r->attrs);
}

static inline void raw_u32(struct raw_msg *r, uint16_t type, uint16_t alen, uint32_t v)
{
	uint8_t b[4];

	put32(b, v);
	raw_attr(r, type, alen, b, sizeof(b));
}

static inline void raw_u64(struct raw_msg *r, uint16_t type, uint16_t alen, uint64_t v)
{
	uint8_t b[8];

	put32(b, (uint32_t)(v >> 32));
	put32(b + 4, (uint32_t)v);
	raw_attr(r, type, alen, b, sizeof(b));
}

/* Append a correct FINGERPRINT (RFC 8489 §14.7): CRC-32 of the message up to
 * it, with the header Length already counting it. Computed with Zephyr's CRC,
 * not with the library under test.
 */
static inline void raw_fingerprint(struct raw_msg *r)
{
	size_t at = r->len;

	raw_u32(r, STUN_ATTR_FINGERPRINT, 4, 0);
	put32(r->buf + at + 4, crc32_ieee(r->buf, at) ^ FINGERPRINT_XOR);
}


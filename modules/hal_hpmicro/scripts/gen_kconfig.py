"""Generate the hal_hpmicro Kconfig from the imported HPM SDK tree."""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KCONFIG = ROOT / "Kconfig"

# These modules have no source file in the SDK CMakeLists, but Zephyr drivers
# still select them to gate the corresponding HAL headers.
EXTRA_USE_MODULES = frozenset({"GPIOM", "MBX", "SYNT", "TRGM"})

# Zephyr-only capabilities that are not listed in soc_modules.list. XPI is
# provided by SoC support code and is used by the Zephyr flash driver.
EXTRA_CAPABILITIES = frozenset({"XPI"})

CAPABILITY_RE = re.compile(r"^HPMSOC_HAS_HPMSDK_([A-Za-z0-9_]+)=y$")
DRIVER_RE = re.compile(r"sdk_src_ifdef\(\s*HPMSOC_HAS_HPMSDK_([A-Za-z0-9_]+)")

HEADER = """\
# Copyright (c) 2026 Cody Gu <gujiaqi@iscas.ac.cn>
# SPDX-License-Identifier: Apache-2.0
#
# Auto-generated by modules/hal_hpmicro/scripts/gen_kconfig.py. Do not edit.

config ZEPHYR_HAL_HPMICRO_MODULE
\tbool

config NDEBUG_CONSOLE
\tbool "HPM SDK no console"

config HPM_SDK_BUILD_ALL_DRIVERS
\tbool "Build all HPM SDK HAL drivers"
\tdepends on SOC_FAMILY_HPMICRO
\thelp
\t  Compile every HPM SDK HAL driver supported by the selected SoC.
\t  This is intended for build-only integration testing and does not
\t  enable the corresponding Zephyr drivers.
"""

HAS_HEADER = """\
# Hardware capabilities exposed by the selected SoC. These symbols must only
# be selected by SoC Kconfig, not by individual drivers.
# Generated from the union of HPM SDK soc_modules.list files and Zephyr-only
# capabilities.
"""

USE_HEADER = """\
# Vendor HAL source selections. Zephyr drivers select these symbols when
# they wrap an SDK driver implementation. A selection requires the
# corresponding SoC capability and is translated to
# HPMSOC_HAS_HPMSDK_* by the module CMake.
"""


class GeneratorError(Exception):
    """Raised when the SDK tree cannot be mapped to Kconfig symbols."""


def _read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def default_sdk_dir() -> Path | None:
    """Return the SDK path from the Zephyr module environment, if available."""

    module_dir = os.environ.get("ZEPHYR_HAL_HPMICRO_MODULE_DIR")
    return Path(module_dir) / "hpm_sdk" if module_dir else None


def sdk_capabilities(sdk_dir: Path) -> set[str]:
    """Return the union of HPMSOC_HAS_HPMSDK_* entries from all SoCs."""

    module_lists = sorted(sdk_dir.glob("soc/*/*/soc_modules.list"))
    if not module_lists:
        raise GeneratorError(f"no soc_modules.list found under {sdk_dir}")

    capabilities: set[str] = set(EXTRA_CAPABILITIES)
    for path in module_lists:
        for line in _read_text(path).splitlines():
            match = CAPABILITY_RE.match(line.strip())
            if match:
                capabilities.add(match.group(1))

    return capabilities


def sdk_use_modules(sdk_dir: Path) -> set[str]:
    """Return HAL modules that Zephyr can select from the SDK build."""

    modules = set(EXTRA_USE_MODULES)
    for path in sorted(sdk_dir.rglob("CMakeLists.txt")):
        for line in _read_text(path).splitlines():
            if line.lstrip().startswith("#"):
                continue
            modules.update(DRIVER_RE.findall(line))

    return modules


def render(capabilities: set[str], use_modules: set[str]) -> str:
    """Render the generated Kconfig contents."""

    missing = use_modules - capabilities
    if missing:
        raise GeneratorError(
            "USE modules missing from the SDK capabilities: " + ", ".join(sorted(missing))
        )

    blocks = [HEADER.rstrip(), HAS_HEADER.rstrip()]
    blocks.extend(f"config HAS_HPMSDK_{name}\n\tbool" for name in sorted(capabilities))
    blocks.append(USE_HEADER.rstrip())
    blocks.extend(
        f"config USE_HPMSDK_{name}\n\tbool\n\tdepends on HAS_HPMSDK_{name}"
        for name in sorted(use_modules)
    )

    return "\n\n".join(blocks) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument(
        "--sdk",
        type=Path,
        help="path to the HPM SDK tree (default: ZEPHYR_HAL_HPMICRO_MODULE_DIR/hpm_sdk)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="check that Kconfig is up to date instead of writing it",
    )
    args = parser.parse_args()

    sdk_dir = args.sdk or default_sdk_dir()
    if sdk_dir is None:
        print(
            "error: set ZEPHYR_HAL_HPMICRO_MODULE_DIR or pass --sdk",
            file=sys.stderr,
        )
        return 1

    try:
        capabilities = sdk_capabilities(sdk_dir)
        use_modules = sdk_use_modules(sdk_dir)
        generated = render(capabilities, use_modules)
    except (GeneratorError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if not KCONFIG.is_file() or _read_text(KCONFIG) != generated:
            print("Kconfig is out of date; run scripts/gen_kconfig.py", file=sys.stderr)
            return 1
        return 0

    KCONFIG.write_text(generated, encoding="utf-8")
    print(
        f"wrote {KCONFIG.relative_to(ROOT)} "
        f"({len(capabilities)} HAS, {len(use_modules)} USE symbols)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

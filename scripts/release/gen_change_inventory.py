# Diff and RST rendering.


class Rst:
    def __init__(self):
        self.lines: list[str] = []

    def title(self, text: str, char: str = "#"):
        self.lines += [text, char * len(text), ""]

    def section(self, text: str, char: str = "*"):
        self.lines += [text, char * len(text), ""]

    def para(self, text: str):
        self.lines += [text, ""]

    def bullets(self, items: list[str], indent: int = 0):
        """A bullet list, or "None." when there is nothing to list."""
        if not items:
            if indent == 0:
                self.para("None.")
            return
        pad = " " * indent
        for item in items:
            self.lines.append(f"{pad}* {item}")
        self.lines.append("")

    def grouped(self, groups: dict[str, list[str]]):
        """Items grouped under a bullet per group, or "None." when empty."""
        if not groups:
            self.para("None.")
            return
        for group in sorted(groups, key=str.lower):
            self.lines.append(f"* {group}" if group else "* Other")
            self.lines.append("")
            self.bullets(sorted(groups[group], key=str.lower), indent=2)

    def write(self, path: Path):
        path.write_text("\n".join(self.lines).rstrip() + "\n", encoding="utf-8")


class Diff:
    """Keys added, removed, renamed and common to two snapshots."""

    def __init__(self, old: dict, new: dict, renames: list[tuple[str, str]] | None = None):
        self.renamed = list(renames or [])
        old_keys, new_keys = set(old), set(new)
        self.added = sorted(new_keys - old_keys - {n for _, n in self.renamed})
        self.removed = sorted(old_keys - new_keys - {o for o, _ in self.renamed})
        self.common = sorted(old_keys & new_keys)


# Per category: the paths whose history is searched for renames, and the
# snapshot field that holds where an item is defined.
RENAME_PATHS = {
    "boards": ["boards"],
    "shields": ["boards/shields"],
    "socs": ["soc"],
    "bindings": ["dts/bindings"],
    "kconfig": [":(glob)**/Kconfig*"],
    "api": ["include"],
    "samples": ["samples"],
}
LOCATION_FIELD = {"kconfig": "file", "api": "file"}
RENAME_SIMILARITY = 0.6


def rename_token(category: str, key: str) -> tuple[str, str] | None:
    """How a key appears in a diff: the identifier to look for and a kind
    both sides of a rename must share."""
    if category == "kconfig":
        prefix = "SB_CONFIG_" if key.startswith("SB_CONFIG_") else "CONFIG_"
        return key.removeprefix(prefix), prefix
    if category == "api":
        kind, _, name = key.partition(":")
        return name, kind
    if category == "samples" and key.startswith("path:"):
        return None
    return key, ""


TOKEN = re.compile(r"[A-Za-z0-9_](?:[A-Za-z0-9_,.-]*[A-Za-z0-9_])?")


@functools.cache
def exists_at(rev: str, path: str) -> bool:
    if rev == ".":
        return (ZEPHYR_BASE / path).exists()
    result = subprocess.run(
        ["git", "cat-file", "-e", f"{rev}:{path}"], cwd=ZEPHYR_BASE, capture_output=True
    )
    return result.returncode == 0


def detect_renames(
    start: str, end: str, category: str, old: dict, new: dict
) -> list[tuple[str, str]]:
    """Pair removed and added keys that one commit in ``start..end`` traded.

    A rename is a commit whose diff drops the old identifier and introduces
    the new one on a line that is otherwise the same, such as a declaration,
    a ``name:`` or a ``compatible:`` entry. The two identifiers must be
    similar and each other's best match within that commit, and the item
    must be defined in the same file before and after, or in a file that was
    renamed along with it. ``git diff -M`` is not used: it pairs unrelated
    boilerplate-heavy files such as board or binding definitions.
    """
    paths = RENAME_PATHS.get(category)
    diff = Diff(old, new)
    if not paths or not diff.added or not diff.removed:
        return []
    field = LOCATION_FIELD.get(category, "path")
    removed: dict[str, list[tuple[str, str]]] = defaultdict(list)
    added: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for keys, index in ((diff.removed, removed), (diff.added, added)):
        for key in keys:
            token = rename_token(category, key)
            if token:
                index[token[0]].append((key, token[1]))

    def same_definition(old_key: str, new_key: str) -> bool:
        old_loc, new_loc = old[old_key][field], new[new_key][field]
        if old_loc == new_loc:
            return True
        return not exists_at(end, old_loc) and not exists_at(start, new_loc)

    renames: list[tuple[str, str]] = []
    paired_old: set[str] = set()
    paired_new: set[str] = set()

    def pair(minus: dict[str, set[str]], plus: dict[str, set[str]]):
        candidates = []
        for masked, old_tokens in minus.items():
            for a in old_tokens:
                for b in plus.get(masked, ()):
                    ratio = difflib.SequenceMatcher(None, a, b).ratio()
                    if a != b and ratio >= RENAME_SIMILARITY:
                        candidates.append((ratio, a, b))
        best: dict[str, float] = defaultdict(float)
        for ratio, a, b in candidates:
            best[a] = max(best[a], ratio)
            best[b] = max(best[b], ratio)
        for ratio, a, b in sorted(candidates, reverse=True):
            if ratio < best[a] or ratio < best[b]:
                continue
            for old_key, old_kind in removed[a]:
                for new_key, new_kind in added[b]:
                    if old_kind != new_kind or old_key in paired_old or new_key in paired_new:
                        continue
                    if not same_definition(old_key, new_key):
                        continue
                    renames.append((old_key, new_key))
                    paired_old.add(old_key)
                    paired_new.add(new_key)

    def masked_lines(line: str, index: dict) -> Iterator[tuple[str, str]]:
        """The line with each known identifier blanked out, per identifier."""
        for token in set(TOKEN.findall(line)):
            if token in index:
                pattern = rf"(?<![A-Za-z0-9_,.-]){re.escape(token)}(?![A-Za-z0-9_,.-])"
                yield re.sub(pattern, "\0", line[1:]).strip(), token

    log(f"looking for renamed {category} in {start}..{end}")
    revisions = f"{start}..{'HEAD' if end == '.' else end}"
    proc = subprocess.Popen(
        ["git", "log", "-p", "--format=commit %H", revisions, "--", *paths],
        cwd=ZEPHYR_BASE,
        stdout=subprocess.PIPE,
        text=True,
        errors="replace",
    )
    minus: dict[str, set[str]] = defaultdict(set)
    plus: dict[str, set[str]] = defaultdict(set)
    for line in proc.stdout:
        if line.startswith("commit "):
            pair(minus, plus)
            minus, plus = defaultdict(set), defaultdict(set)
        elif line.startswith("-") and not line.startswith("--- "):
            for masked, token in masked_lines(line, removed):
                minus[masked].add(token)
        elif line.startswith("+") and not line.startswith("+++ "):
            for masked, token in masked_lines(line, added):
                plus[masked].add(token)
    pair(minus, plus)
    proc.wait()
    return sorted(renames)


def lit(name: str) -> str:
    return f"``{name}``"


def vendor_name(vendors: dict, prefix: str) -> str:
    return vendors.get(prefix, prefix or "Other")


def render_renamed(rst: Rst, what: str, d: Diff, ref: Callable[[str], str]):
    rst.section(f"Renamed {what}")
    rst.bullets([f"{lit(o)} -> {ref(n)}" for o, n in d.renamed])


def board_ref(name: str, b: dict) -> str:
    # The zephyr:board role only resolves for boards whose page carries the
    # zephyr:board directive; the others get the page's label if any.
    if b["directive"]:
        return f":zephyr:board:`{name}` ({lit(name)})"
    if b["label"]:
        return f":ref:`{b['full_name']} <{b['label']}>` ({lit(name)})"
    return f"{b['full_name']} ({lit(name)})"


def render_boards(old, new, vendors, rst: Rst, d: Diff) -> dict:
    rst.section("Added boards")
    groups = defaultdict(list)
    for name in d.added:
        groups[vendor_name(vendors, new[name]["vendor"])].append(board_ref(name, new[name]))
    rst.grouped(groups)
    rst.section("Removed boards")
    groups = defaultdict(list)
    for name in d.removed:
        groups[vendor_name(vendors, old[name]["vendor"])].append(
            f"{old[name]['full_name']} ({lit(name)})"
        )
    rst.grouped(groups)
    render_renamed(rst, "boards", d, lambda n: board_ref(n, new[n]))
    return {"added": len(d.added), "removed": len(d.removed), "renamed": len(d.renamed)}


def render_shields(old, new, vendors, rst: Rst, d: Diff) -> dict:
    rst.section("Added shields")
    # Variants of one shield share a documentation page: one bullet per page.
    pages: dict[str, list[str]] = defaultdict(list)
    for name in d.added:
        pages[new[name]["label"] or f"path:{new[name]['path']}"].append(name)
    items = []
    for names in [pages[label] for label in sorted(pages)]:
        first = new[names[0]]
        title = first["title"] if len(names) > 1 and first["title"] else first["full_name"]
        names_text = ", ".join(lit(n) for n in names)
        if first["label"]:
            items.append(f":ref:`{title} <{first['label']}>` ({names_text})")
        else:
            items.append(f"{title} ({names_text})")
    rst.bullets(sorted(items, key=str.lower))
    rst.section("Removed shields")
    rst.bullets([f"{old[n]['full_name']} ({lit(n)})" for n in d.removed])
    render_renamed(rst, "shields", d, lambda n: f"{new[n]['full_name']} ({lit(n)})")
    return {"added": len(d.added), "removed": len(d.removed), "renamed": len(d.renamed)}


def render_socs(old, new, vendors, rst: Rst, d: Diff) -> dict:
    for title, keys, snap in (("Added SoCs", d.added, new), ("Removed SoCs", d.removed, old)):
        rst.section(title)
        groups = defaultdict(list)
        for name in keys:
            s = snap[name]
            where = " / ".join(x for x in (s["family"], s["series"]) if x)
            groups[vendor_name(vendors, s["vendor"])].append(
                f"{lit(name)} ({where})" if where else lit(name)
            )
        rst.grouped(groups)
    render_renamed(rst, "SoCs", d, lit)
    return {"added": len(d.added), "removed": len(d.removed), "renamed": len(d.renamed)}


def buses_text(b: dict) -> str:
    buses = sorted(bus for bus in b["buses"] if bus)
    if not buses:
        return ""
    return f" (on {', '.join(lit(bus) for bus in buses)} bus)"


def binding_ref(b: dict) -> str:
    return f":dtcompatible:`{b['compatible']}`" + buses_text(b)


def property_changes(old_props: dict, new_props: dict) -> list[tuple[dict, str]]:
    """(property spec, note) pairs describing how the properties changed."""
    p = Diff(old_props, new_props)
    found = []
    for name in p.added:
        req = " (required)" if new_props[name]["required"] else ""
        found.append((new_props[name], f"added property {lit(name)}{req}"))
    for name in p.removed:
        found.append((old_props[name], f"removed property {lit(name)}"))
    for name in p.common:
        op, np = old_props[name], new_props[name]
        if np["deprecated"] and not op["deprecated"]:
            found.append((np, f"deprecated property {lit(name)}"))
        if op["type"] != np["type"]:
            found.append((np, f"property {lit(name)} type ``{op['type']}`` -> ``{np['type']}``"))
        if op["required"] != np["required"]:
            what = "now required" if np["required"] else "no longer required"
            found.append((np, f"property {lit(name)} {what}"))
    return found


def render_bindings(old, new, vendors, rst: Rst, d: Diff) -> dict:
    rst.section("Added bindings")
    groups = defaultdict(list)
    for key in d.added:
        groups[new[key]["class"] or "other"].append(binding_ref(new[key]))
    rst.grouped(groups)

    rst.section("Removed bindings")
    groups = defaultdict(list)
    for key in d.removed:
        groups[old[key]["class"] or "other"].append(lit(key) + buses_text(old[key]))
    rst.grouped(groups)

    render_renamed(rst, "bindings", d, lambda n: binding_ref(new[n]))

    rst.section("Changed bindings")
    rst.para("Bindings whose buses or own properties changed.")
    changed = 0
    groups = defaultdict(list)
    # Changes to properties a binding inherits from an included file show up in
    # every binding that includes it; report those once, by property.
    inherited: dict[str, set[str]] = defaultdict(set)
    for key in d.common:
        o, n = old[key], new[key]
        buses = Diff(o["buses"], n["buses"])
        notes = [f"now also on {lit(bus)} bus" for bus in buses.added if bus]
        notes += [f"no longer on {lit(bus)} bus" for bus in buses.removed if bus]
        several = len(set(o["buses"]) | set(n["buses"])) > 1
        for bus in buses.common:
            found = property_changes(o["buses"][bus]["properties"], n["buses"][bus]["properties"])
            own = []
            for spec, text in found:
                if spec.get("inherited"):
                    inherited[text].add(f"{key}@{bus}")
                else:
                    own.append(text)
            if own and several and bus:
                notes.append(f"on {lit(bus)} bus: " + ", ".join(own))
            else:
                notes += own
        if notes:
            changed += 1
            groups[n["class"] or "other"].append(
                f":dtcompatible:`{n['compatible']}`: " + "; ".join(notes)
            )
    rst.grouped(groups)

    rst.section("Changed inherited properties")
    rst.para(
        "Properties that changed in a common included binding, with the number of "
        "bindings that inherit the change."
    )
    items = [f"{text} ({len(keys)} bindings)" for text, keys in sorted(inherited.items())]
    rst.bullets(items)
    return {
        "added": len(d.added),
        "removed": len(d.removed),
        "renamed": len(d.renamed),
        "changed": changed,
    }


def kconfig_area(sym: dict) -> str:
    parts = sym["file"].split("/")
    if len(parts) <= 1:
        return "Kconfig (top level)"
    return "/".join(parts[:2]) if parts[0] in ("drivers", "subsys", "boards", "soc") else parts[0]


def kconfig_ref(name: str) -> str:
    return f":kconfig:option:`{name}`"


def render_kconfig(old, new, vendors, rst: Rst, d: Diff) -> dict:
    rst.section("Added options")
    groups = defaultdict(list)
    for name in d.added:
        groups[kconfig_area(new[name])].append(kconfig_ref(name))
    rst.grouped(groups)

    rst.section("Removed options")
    groups = defaultdict(list)
    for name in d.removed:
        groups[kconfig_area(old[name])].append(lit(name))
    rst.grouped(groups)

    render_renamed(rst, "options", d, kconfig_ref)

    rst.section("Deprecated options")
    groups = defaultdict(list)
    deprecated = 0
    for name in d.common:
        if new[name]["deprecated"] and not old[name]["deprecated"]:
            deprecated += 1
            item = kconfig_ref(name)
            if new[name]["help"]:
                item += f": {new[name]['help']}"
            groups[kconfig_area(new[name])].append(item)
    rst.grouped(groups)

    rst.section("Changed options")
    rst.para("Options whose type or default values changed.")
    groups = defaultdict(list)
    changed = 0
    for name in d.common:
        o, n = old[name], new[name]
        notes = []
        if o["type"] != n["type"]:
            notes.append(f"type ``{o['type']}`` -> ``{n['type']}``")
        # Compare the values only: a rewritten condition is not a new default.
        if o["default_values"] != n["default_values"]:
            fmt = lambda d: ", ".join(f"``{x}``" for x in d) or "none"  # noqa: E731
            notes.append(f"defaults {fmt(o['defaults'])} -> {fmt(n['defaults'])}")
        if notes:
            changed += 1
            groups[kconfig_area(n)].append(kconfig_ref(name) + ": " + "; ".join(notes))
    rst.grouped(groups)
    return {
        "added": len(d.added),
        "removed": len(d.removed),
        "renamed": len(d.renamed),
        "deprecated": deprecated,
        "changed": changed,
    }


API_ROLE = {
    "function": "c:func",
    "define": "c:macro",
    "typedef": "c:type",
    "enum": "c:enum",
    "struct": "c:struct",
    "union": "c:union",
    "variable": "c:var",
}


def api_ref(m: dict) -> str:
    name = m["name"]
    if m["kind"] == "function":
        return f":c:func:`{name}`"
    return f":{API_ROLE[m['kind']]}:`{name}`"


def api_group(m: dict) -> str:
    return m["group_title"] or m["group"] or f"``{m['file']}`` (no API group)"


def render_api(old, new, vendors, rst: Rst, d: Diff) -> dict:
    rst.section("Added APIs")
    groups = defaultdict(list)
    for key in d.added:
        groups[api_group(new[key])].append(api_ref(new[key]))
    rst.grouped(groups)

    rst.section("Removed APIs")
    groups = defaultdict(list)
    for key in d.removed:
        m = old[key]
        groups[api_group(m)].append(f"{lit(m['name'])} ({m['kind']}, was in ``{m['file']}``)")
    rst.grouped(groups)

    rst.section("Renamed APIs")
    groups = defaultdict(list)
    for o, n in d.renamed:
        groups[api_group(new[n])].append(f"{lit(old[o]['name'])} -> {api_ref(new[n])}")
    rst.grouped(groups)

    rst.section("Deprecated APIs")
    groups = defaultdict(list)
    deprecated = 0
    for key in d.common:
        if new[key]["deprecated"] and not old[key]["deprecated"]:
            deprecated += 1
            groups[api_group(new[key])].append(api_ref(new[key]))
    rst.grouped(groups)
    return {
        "added": len(d.added),
        "removed": len(d.removed),
        "renamed": len(d.renamed),
        "deprecated": deprecated,
    }


def render_samples(old, new, vendors, rst: Rst, d: Diff) -> dict:
    def ref(key, s):
        if key.startswith("path:"):
            return f"{s['name'] or key[5:]} (``{s['path']}``)"
        return f":zephyr:code-sample:`{key}`"

    # A sample whose page gained or lost the code-sample directive changes
    # key; its application directory tells that it is the same sample.
    old_paths = {s["path"] for s in old.values()}
    new_paths = {s["path"] for s in new.values()}
    added = [k for k in d.added if new[k]["path"] not in old_paths]
    removed = [k for k in d.removed if old[k]["path"] not in new_paths]

    rst.section("Added samples")
    rst.bullets([ref(k, new[k]) for k in added])
    rst.section("Removed samples")
    rst.bullets([f"{old[k]['name'] or k} (``{old[k]['path']}``)" for k in removed])
    render_renamed(rst, "samples", d, lambda n: ref(n, new[n]))
    return {"added": len(added), "removed": len(removed), "renamed": len(d.renamed)}


def module_link(m: dict, name: str) -> str:
    return f"`{name} <{m['url']}>`__" if m["url"].startswith("http") else lit(name)


def render_modules(old, new, vendors, rst: Rst, d: Diff) -> dict:
    rst.section("Added modules")
    rst.bullets([f"{module_link(new[k], k)} (``{new[k]['path']}``)" for k in d.added])
    rst.section("Removed modules")
    rst.bullets([f"{module_link(old[k], k)} (``{old[k]['path']}``)" for k in d.removed])
    rst.section("Updated modules")
    items = []
    for k in d.common:
        o, n = old[k]["revision"], new[k]["revision"]
        if o == n:
            continue
        item = f"{module_link(new[k], k)}: ``{o[:12]}`` -> ``{n[:12]}``"
        if "github.com/" in new[k]["url"] and all(re.fullmatch(r"[0-9a-f]{40}", r) for r in (o, n)):
            item += f" (`diff <{new[k]['url']}/compare/{o}...{n}>`__)"
        items.append(item)
    rst.bullets(items)
    return {"added": len(d.added), "removed": len(d.removed), "changed": len(items)}


CATEGORIES = {
    # name: (page title, renderer)
    "boards": ("Boards", render_boards),
    "shields": ("Shields", render_shields),
    "socs": ("SoCs", render_socs),
    "bindings": ("Devicetree bindings", render_bindings),
    "kconfig": ("Kconfig options", render_kconfig),
    "api": ("C APIs", render_api),
    "samples": ("Code samples", render_samples),
    "modules": ("Modules", render_modules),
}


def describe(rev: str) -> str:
    if rev == ".":
        return "working tree"
    return git("rev-parse", "--short=12", f"{rev}^{{commit}}")


def render(start: str, end: str, old: dict, new: dict, names: list[str], outdir: Path, title: str):
    outdir.mkdir(parents=True, exist_ok=True)
    vendors = new.get("vendors") or old.get("vendors") or {}
    header = [
        "..",
        f"  Generated by scripts/release/gen_change_inventory.py {start} {end}",
        f"  ({describe(start)} to {describe(end)}). Do not edit: regenerate instead.",
        "",
    ]
    summary = {}
    for name in names:
        page_title, renderer = CATEGORIES[name]
        rst = Rst()
        rst.lines += header
        rst.lines += [f".. _change_inventory_{name}:", ""]
        rst.title(page_title)
        renames = detect_renames(start, end, name, old[name], new[name])
        summary[name] = renderer(
            old[name], new[name], vendors, rst, Diff(old[name], new[name], renames)
        )
        rst.write(outdir / f"{name}.rst")

    rst = Rst()
    rst.lines += header
    rst.lines += [".. _change_inventory:", ""]
    rst.title(title)
    rst.para(
        f"Interfaces and configuration added, removed or changed between\n"
        f"``{start}`` and ``{end}``.\n"
        "The release notes describe the capabilities behind these changes and\n"
        "the migration guide describes the actions they require."
    )
    columns = ["added", "removed", "renamed", "deprecated", "changed"]
    rst.lines += [".. list-table::", "   :header-rows: 1", "", "   * - Category"] + [
        f"     - {c.capitalize()}" for c in columns
    ]
    for name in names:
        rst.lines.append(f"   * - :ref:`{CATEGORIES[name][0]} <change_inventory_{name}>`")
        for c in columns:
            v = summary[name].get(c)
            rst.lines.append(f"     - {v}" if v is not None else "     -")
    rst.lines.append("")
    rst.lines += [".. toctree::", "   :maxdepth: 1", ""] + [f"   {n}" for n in names] + [""]
    rst.write(outdir / "index.rst")
    return summary


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
        allow_abbrev=False,
    )
    parser.add_argument("--collect", choices=sorted(COLLECTORS), help=argparse.SUPPRESS)
    parser.add_argument("--zephyr-base", type=Path, help=argparse.SUPPRESS)
    parser.add_argument(
        "-c",
        "--category",
        action="append",
        choices=sorted(CATEGORIES),
        help="category to generate (default: all)",
    )
    parser.add_argument(
        "--cache-dir",
        type=Path,
        default=Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "zephyr-inventory",
        help="snapshot cache (default: %(default)s)",
    )
    parser.add_argument("--no-cache", action="store_true", help="do not read or write the cache")
    parser.add_argument("--title", default=None, help="title of the index page")
    parser.add_argument("start", nargs="?", metavar="START", help="start revision")
    parser.add_argument("end", nargs="?", metavar="END", help="end revision, '.' for the tree")
    parser.add_argument("outdir", nargs="?", type=Path, metavar="OUTDIR")
    args = parser.parse_args()

    if args.collect:
        json.dump(COLLECTORS[args.collect](args.zephyr_base.resolve()), sys.stdout)
        return

    if not (args.start and args.end and args.outdir):
        parser.error("START, END and OUTDIR are required")

    names = args.category or list(CATEGORIES)
    collectors = list(names) + ["vendors"]
    cache_dir = None if args.no_cache else args.cache_dir
    old = snapshot(args.start, collectors, cache_dir)
    new = snapshot(args.end, collectors, cache_dir)
    title = args.title or f"Change inventory: {args.start} to {args.end}"
    summary = render(args.start, args.end, old, new, names, args.outdir, title)
    for name, counts in summary.items():
        log(f"{name:10s} " + "  ".join(f"{k}={v}" for k, v in counts.items()))


if __name__ == "__main__":
    main()

"""Generate a change inventory between two Zephyr revisions.

The inventory lists the boards, shields, SoCs, devicetree bindings, Kconfig
options, C APIs, code samples and west modules that were added, removed,
renamed or changed between two git revisions. It is meant to be regenerated by
the release manager and published as an appendix to the release notes, so that
contributors never have to maintain those lists by hand.

For each revision a snapshot is collected per category by checking the revision
out in a temporary worktree and running the collector inside it, with that
revision's own ``scripts/`` directory on the Python path. Snapshots are cached
by commit SHA, so a release only has to collect the new side of the diff.

Usage::

    gen_change_inventory.py [-c CATEGORY ...] START END OUTDIR

``START`` and ``END`` are git revisions; ``.`` means the working tree. The RST
pages are written to ``OUTDIR`` with an ``index.rst`` that can be pulled into a
release notes toctree.
"""


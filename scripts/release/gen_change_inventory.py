HERE = Path(__file__).parent.resolve()
ZEPHYR_BASE = Path(os.environ.get("ZEPHYR_BASE", HERE.parent.parent)).resolve()

COLLECTORS: dict[str, str] = {}


def collector(name):
    def wrap(func):
        COLLECTORS[name] = func
        return func

    return wrap


def log(*args):
    print(*args, file=sys.stderr, flush=True)


def read_yaml(path: Path):
    import yaml

    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def relpath(path, base: Path) -> str:
    try:
        return Path(path).resolve().relative_to(base.resolve()).as_posix()
    except ValueError:
        return Path(path).as_posix()


def doc_page(path: Path) -> dict:
    """First internal label and title of a documentation page, and the boards
    its ``zephyr:board`` directives document."""
    info = {"label": "", "title": "", "boards": []}
    if not path.exists():
        return info
    text = path.read_text(encoding="utf-8", errors="replace").lstrip("﻿")
    # An internal target has no URL on the following, indented line.
    m = re.search(r"^\.\. _([^:\n]+):[ \t]*\n(?![ \t]+\S)", text, re.M)
    if m:
        info["label"] = m.group(1)
    m = re.search(r"^(\S.*)\n([#*=\-^\"~]{3,})\s*$", text, re.M)
    if m and len(m.group(2)) >= len(m.group(1).rstrip()):
        info["title"] = m.group(1).strip()
    info["boards"] = re.findall(r"^\.\. zephyr:board:: *(\S+)", text, re.M)
    return info



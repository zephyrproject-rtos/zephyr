# Snapshots: run a collector inside a checkout of a revision.


def git(*args, cwd=ZEPHYR_BASE) -> str:
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True
    ).stdout.strip()


@contextlib.contextmanager
def checkout(rev: str) -> Iterator[Path]:
    if rev == ".":
        yield ZEPHYR_BASE
        return
    with tempfile.TemporaryDirectory(prefix="inventory_worktree_") as td:
        log(f"checking out {rev} in {td}")
        git("worktree", "add", "--detach", "--quiet", td, rev)
        try:
            yield Path(td)
        finally:
            git("worktree", "remove", "--force", td)


def collect_in_subprocess(base: Path, name: str) -> dict:
    """Run one collector in a fresh interpreter rooted at ``base``.

    Collectors import that revision's own helper modules and mutate the
    environment, so each runs in its own process.
    """
    result = subprocess.run(
        [sys.executable, __file__, "--collect", name, "--zephyr-base", str(base)],
        capture_output=True,
        text=True,
    )
    if result.stderr:
        log(result.stderr.rstrip())
    if result.returncode != 0:
        sys.exit(f"collector {name} failed at {base}")
    return json.loads(result.stdout)


def cache_file(cache_dir: Path, sha: str, name: str) -> Path:
    """Cached snapshot of one collector, keyed by the revision and by the
    collector's own source so that a modified collector is run again."""
    source = inspect.getsource(COLLECTORS[name]).encode("utf-8")
    return cache_dir / sha / f"{name}-{hashlib.sha1(source).hexdigest()[:10]}.json"


def snapshot(rev: str, names: list[str], cache_dir: Path | None) -> dict[str, dict]:
    sha = None if rev == "." else git("rev-parse", f"{rev}^{{commit}}")
    out: dict[str, dict] = {}
    missing = []
    for name in names:
        cached = cache_file(cache_dir, sha, name) if (cache_dir and sha) else None
        if cached and cached.exists():
            out[name] = json.loads(cached.read_text())
        else:
            missing.append(name)
    if not missing:
        return out
    with checkout(rev) as base:
        for name in missing:
            log(f"collecting {name} at {rev}")
            out[name] = collect_in_subprocess(base, name)
            if cache_dir and sha:
                path = cache_file(cache_dir, sha, name)
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(json.dumps(out[name], indent=1, sort_keys=True))
    return out



"""Generate a change inventory between two Zephyr revisions.

The inventory lists the boards, shields, SoCs, devicetree bindings, Kconfig
options, C APIs, code samples and west modules that were added, removed or
changed between two git revisions. It is meant to be regenerated by the release
manager and published as an appendix to the release notes, so that contributors
never have to maintain those lists by hand.

For each revision a snapshot is collected per category by checking the revision
out in a temporary worktree and running the collector inside it, with that
revision's own ``scripts/`` directory on the Python path. Snapshots are cached
by commit SHA, so a release only has to collect the new side of the diff.

Usage::

    gen_change_inventory.py [-c CATEGORY ...] START END OUTDIR

``START`` and ``END`` are git revisions; ``.`` means the working tree. The RST
pages are written to ``OUTDIR`` with an ``index.rst`` that can be pulled into a
release notes toctree.
"""

from __future__ import annotations

import argparse
import contextlib
import functools
import json
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from collections.abc import Iterator
from pathlib import Path

HERE = Path(__file__).parent.resolve()
ZEPHYR_BASE = Path(os.environ.get("ZEPHYR_BASE", HERE.parent.parent)).resolve()

COLLECTORS: dict[str, str] = {}


def collector(name):
    def wrap(func):
        COLLECTORS[name] = func
        return func

    return wrap


def log(*args):
    print(*args, file=sys.stderr, flush=True)


def read_yaml(path: Path):
    import yaml

    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def relpath(path, base: Path) -> str:
    try:
        return Path(path).resolve().relative_to(base.resolve()).as_posix()
    except ValueError:
        return Path(path).as_posix()


# -----------------------------------------------------------------------------
# Collectors. Each one runs inside the revision it collects, with ``base``
# pointing at that checkout, and returns a JSON-serializable dict keyed by a
# stable identifier.


@collector("vendors")
def collect_vendors(base: Path) -> dict:
    vendors = {}
    with open(base / "dts" / "bindings" / "vendor-prefixes.txt", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            prefix, _, name = line.partition("\t")
            vendors[prefix.strip()] = name.strip()
    return vendors


@collector("boards")
def collect_boards(base: Path) -> dict:
    boards = {}
    for yml in sorted((base / "boards").rglob("board.yml")):
        data = read_yaml(yml) or {}
        entries = data.get("boards", [])
        if "board" in data:
            entries = [data["board"]]
        for board in entries:
            # Board extensions only add SoC qualifiers to a board defined elsewhere.
            if "extend" in board:
                continue
            boards[board["name"]] = {
                "vendor": board.get("vendor", ""),
                "full_name": board.get("full_name", board["name"]),
                "socs": sorted(s["name"] for s in board.get("socs", [])),
                "path": relpath(yml.parent, base),
            }
    return boards


@collector("shields")
def collect_shields(base: Path) -> dict:
    shields = {}
    for yml in sorted((base / "boards" / "shields").rglob("shield.yml")):
        data = read_yaml(yml) or {}
        entries = data.get("shields", [])
        if "shield" in data:
            entries = [data["shield"]]
        label = ""
        doc = yml.parent / "doc" / "index.rst"
        if doc.exists():
            m = re.search(r"^\.\. _([^:\n]+):\s*$", doc.read_text(encoding="utf-8"), re.M)
            if m:
                label = m.group(1)
        for shield in entries:
            shields[shield["name"]] = {
                "vendor": shield.get("vendor", ""),
                "full_name": shield.get("full_name", shield["name"]),
                "label": label,
                "path": relpath(yml.parent, base),
            }
    return shields


@collector("socs")
def collect_socs(base: Path) -> dict:
    socs = {}

    def add(soc, family, series, path):
        socs[soc["name"]] = {
            "family": family,
            "series": series,
            "vendor": path.split("/")[1] if path.count("/") >= 1 else "",
            "path": path,
        }

    for yml in sorted((base / "soc").rglob("soc.yml")):
        data = read_yaml(yml) or {}
        path = relpath(yml.parent, base)
        add_soc = functools.partial(add, path=path)

        for family in data.get("family", []):
            for series in family.get("series", []):
                for soc in series.get("socs", []):
                    add_soc(soc, family["name"], series["name"])
            for soc in family.get("socs", []):
                add_soc(soc, family["name"], "")
        for series in data.get("series", []):
            for soc in series.get("socs", []):
                add_soc(soc, "", series["name"])
        for soc in data.get("socs", []):
            add_soc(soc, "", "")
    return socs


@collector("bindings")
def collect_bindings(base: Path) -> dict:
    sys.path.insert(0, str(base / "scripts" / "dts" / "python-devicetree" / "src"))
    import yaml
    from devicetree import edtlib

    class Loader(yaml.SafeLoader):
        pass

    # Binding files only use plain YAML, but be tolerant of custom tags.
    Loader.add_multi_constructor("!", lambda loader, suffix, node: None)

    def own_properties(path: str) -> set[str]:
        """Properties the binding file declares itself, as opposed to included ones."""
        try:
            with open(path, encoding="utf-8") as f:
                raw = yaml.load(f, Loader=Loader) or {}
        except (OSError, yaml.YAMLError):
            return set()
        return set((raw.get("properties") or {}).keys())

    paths = [str(p) for p in sorted((base / "dts" / "bindings").rglob("*.yaml"))]
    bindings = {}
    for binding in edtlib.bindings_from_paths(paths, ignore_errors=True):
        if not binding.compatible:
            continue
        key = binding.compatible if not binding.on_bus else f"{binding.compatible}@{binding.on_bus}"
        path = relpath(binding.path, base)
        parts = path.split("/")
        # dts/bindings/<class>/<file>.yaml
        klass = parts[2] if len(parts) > 3 else ""
        own = own_properties(binding.path)
        props = {}
        for name, spec in binding.prop2specs.items():
            props[name] = {
                "type": spec.type,
                "required": bool(spec.required),
                "deprecated": bool(spec.deprecated),
                "inherited": name not in own,
            }
        bindings[key] = {
            "compatible": binding.compatible,
            "on_bus": binding.on_bus,
            "class": klass,
            "path": path,
            "description": (binding.description or "").strip().split("\n")[0],
            "properties": props,
        }
    return bindings


@collector("kconfig")
def collect_kconfig(base: Path) -> dict:
    """Load the whole tree Kconfig the way the documentation build does.

    Every board, SoC and architecture is sourced so that all symbols are
    visible; module Kconfig files are not loaded, the inventory covers the
    Zephyr tree only.
    """
    sys.path.insert(0, str(base / "scripts"))
    sys.path.insert(0, str(base / "scripts" / "kconfig"))
    import kconfiglib
    import list_boards
    import list_hardware

    with tempfile.TemporaryDirectory() as td_str:
        td = Path(td_str)
        for name in ("Kconfig.modules", "Kconfig.sysbuild.modules", "Kconfig.dts"):
            (td / name).write_text("")

        (td / "soc").mkdir()
        (td / "soc" / "Kconfig.defconfig").write_text("")
        root_args = argparse.Namespace(soc_roots=[base])
        soc_folders = {soc.folder[0] for soc in list_hardware.find_v2_systems(root_args).get_socs()}
        with open(td / "soc" / "Kconfig.soc", "w") as f:
            for folder in sorted(soc_folders):
                f.write(f'source "{(Path(folder) / "Kconfig.soc").as_posix()}"\n')
        with open(td / "soc" / "Kconfig", "w") as f:
            for folder in sorted(soc_folders):
                f.write(f'osource "{(Path(folder) / "Kconfig").as_posix()}"\n')

        (td / "arch").mkdir()
        root_args = argparse.Namespace(arch_roots=[base], arch=None)
        with open(td / "arch" / "Kconfig", "w") as f:
            for arch in list_hardware.find_v2_archs(root_args)["archs"]:
                f.write(f'source "{(Path(arch["path"]) / "Kconfig").as_posix()}"\n')

        (td / "boards").mkdir()
        root_args = argparse.Namespace(
            board_roots=[base], soc_roots=[base], board=None, board_dir=[]
        )
        with open(td / "boards" / "Kconfig.boards", "w") as f:
            for board in list_boards.find_v2_boards(root_args).values():
                names = [board.name] + list(list_boards.board_v2_qualifiers(board))
                for name in names:
                    f.write(f"config BOARD_{re.sub(r'[^a-zA-Z0-9_]', '_', name).upper()}\n")
                    f.write("\tbool\n")
                f.write(f'source "{(board.dir / f"Kconfig.{board.name}").as_posix()}"\n\n')

        os.environ["ZEPHYR_BASE"] = str(base)
        os.environ["srctree"] = str(base)  # noqa: SIM112
        os.environ["KCONFIG_DOC_MODE"] = "1"
        os.environ["KCONFIG_BINARY_DIR"] = str(td)
        os.environ["ARCH_DIR"] = "arch"
        os.environ["ARCH"] = "[!v][!2]*"
        os.environ["HWM_SCHEME"] = "v2"
        os.environ["BOARD"] = "boards"
        os.environ["KCONFIG_BOARD_DIR"] = str(td / "boards")

        os.environ["CONFIG_"] = "SB_CONFIG_"
        sysbuild = kconfiglib.Kconfig(str(base / "share" / "sysbuild" / "Kconfig"))
        os.environ["CONFIG_"] = "CONFIG_"
        kconf = kconfiglib.Kconfig(str(base / "Kconfig"))

    symbols = {}
    for kconfig_obj, prefix in ((kconf, "CONFIG_"), (sysbuild, "SB_CONFIG_")):
        for sym in kconfig_obj.unique_defined_syms:
            if not sym.name or not sym.nodes:
                continue
            node = sym.nodes[0]
            filename = node.filename
            if not os.path.isabs(filename):
                filename = os.path.join(base, filename)
            filename = relpath(filename, base)
            if os.path.isabs(filename):
                # Generated in the temporary directory, such as BOARD_* symbols.
                continue
            help_text = ""
            for n in sym.nodes:
                if n.help:
                    help_text = " ".join(n.help.strip().split("\n")[0].split())
                    break
            # Only the defaults at the symbol's definition: board and SoC
            # Kconfig.defconfig files add conditional defaults to shared
            # symbols all the time, and those are not changes to the option.
            defaults = []
            default_values = []
            for value, cond, *_ in node.defaults:
                text = " ".join(kconfiglib.expr_str(value).split())
                default_values.append(text)
                if cond is not kconfig_obj.y:
                    text += f" if {kconfiglib.expr_str(cond)}"
                defaults.append(text)
            symbols[prefix + sym.name] = {
                "type": kconfiglib.TYPE_TO_STR[sym.type],
                "prompts": sorted({" ".join(n.prompt[0].split()) for n in sym.nodes if n.prompt}),
                "defaults": defaults,
                "default_values": default_values,
                "deprecated": any(sel[0].name == "DEPRECATED" for sel in sym.selects),
                "help": help_text,
                "file": filename,
            }
    return symbols


@collector("samples")
def collect_samples(base: Path) -> dict:
    samples = {}
    with_directive = set()
    for readme in sorted((base / "samples").rglob("README.rst")):
        text = readme.read_text(encoding="utf-8", errors="replace")
        directive = r"^\.\. zephyr:code-sample:: (\S+)\s*\n((?:[ \t]+:.*\n)*)"
        for m in re.finditer(directive, text, re.M):
            name = ""
            nm = re.search(r":name:\s*(.+)", m.group(2))
            if nm:
                name = nm.group(1).strip()
            samples[m.group(1)] = {"name": name, "path": relpath(readme.parent, base)}
            with_directive.add(readme.parent)
    for tests in sorted((base / "samples").rglob("tests.yaml")):
        if tests.parent in with_directive:
            continue
        data = read_yaml(tests) or {}
        sample = data.get("sample") or {}
        samples[f"path:{relpath(tests.parent, base)}"] = {
            "name": sample.get("name", ""),
            "path": relpath(tests.parent, base),
        }
    return samples


@collector("modules")
def collect_modules(base: Path) -> dict:
    data = read_yaml(base / "west.yml") or {}
    modules = {}
    for project in data.get("manifest", {}).get("projects", []):
        modules[project["name"]] = {
            "revision": str(project.get("revision", "")),
            "path": project.get("path", project["name"]),
        }
    return modules


def run_doxygen(base: Path, outdir: Path, doxyfile_in: Path) -> Path:
    """Run Doxygen on ``base`` with the XML output in ``outdir``.

    The doxyfile template comes from the tree the script runs in, not from
    the revision being collected, so that a change to the documentation
    configuration (an excluded directory, for instance) does not show up as
    an API change.
    """
    template = doxyfile_in.read_text(encoding="utf-8")
    req_input = outdir / "req"
    req_input.mkdir(parents=True, exist_ok=True)
    doxyfile = (
        template.replace("@ZEPHYR_BASE@", str(base))
        .replace("@DOXY_OUT@", str(outdir))
        .replace("@DOXY_REQ_INPUT@", str(req_input))
        .replace("@INCLUDE_CUSTOM_FILE@", "")
        .replace("@ZEPHYR_VERSION@", "inventory")
    )
    doxyfile += "\n".join(
        [
            "",
            "GENERATE_HTML = NO",
            "GENERATE_LATEX = NO",
            "GENERATE_XML = YES",
            "GENERATE_TAGFILE =",
            "XML_PROGRAMLISTING = NO",
            "HAVE_DOT = NO",
            "SOURCE_BROWSER = NO",
            "QUIET = YES",
            "WARNINGS = NO",
            "WARN_IF_UNDOCUMENTED = NO",
            "WARN_IF_DOC_ERROR = NO",
            "WARN_IF_INCOMPLETE_DOC = NO",
            "WARN_AS_ERROR = NO",
            "",
        ]
    )
    # Doxygen occasionally overflows the stack of a parser thread on macOS,
    # depending on address space layout; retry a few times, the last ones
    # single-threaded, before giving up.
    for extra in ("", "NUM_PROC_THREADS = 1\n", "NUM_PROC_THREADS = 1\n", "NUM_PROC_THREADS = 1\n"):
        result = subprocess.run(
            ["doxygen", "-"],
            input=doxyfile + extra,
            text=True,
            cwd=base,
            stdout=subprocess.DEVNULL,
        )
        if result.returncode == 0 and (outdir / "xml" / "index.xml").exists():
            return outdir / "xml"
        log(f"doxygen failed with status {result.returncode}, retrying")
    sys.exit("doxygen failed")


def find_deprecated_declarations(base: Path, names: set[str]) -> set[str]:
    """Find identifiers marked with ``__deprecated`` or ``__DEPRECATED_MACRO``.

    Doxygen drops the attribute, so scan the headers. For a function the
    declared name is the first identifier followed by a parenthesis; for a
    typedef or a variable it is the last identifier of the declaration.
    """
    found = set()
    ident = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
    for header in (base / "include").rglob("*.h"):
        if "toolchain" in header.parts:
            continue
        try:
            lines = header.read_text(encoding="utf-8", errors="replace").split("\n")
        except OSError:
            continue
        for i, line in enumerate(lines):
            if "__DEPRECATED_MACRO" in line:
                # Walk back to the #define that owns this (possibly continued) line.
                j = i
                while j > 0 and not lines[j].lstrip().startswith("#define"):
                    j -= 1
                m = re.match(r"\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)", lines[j])
                if m and m.group(1) in names:
                    found.add(m.group(1))
                continue
            if "__deprecated" not in line or "#define" in line:
                continue
            # Collect the whole declaration around the marker, up to a
            # statement end in either direction.
            start = i
            while start > 0 and not re.search(r"[;{}]\s*$", lines[start - 1]) and i - start < 6:
                start -= 1
            end = i
            while end < len(lines) - 1 and not re.search(r"[;{]", lines[end]) and end - i < 6:
                end += 1
            text = "\n".join(lines[start : end + 1])
            text = re.sub(r"__deprecated(_version\s*\([^)]*\))?", " ", text)
            text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
            called = [
                t for t in re.findall(r"\b([A-Za-z_]\w*)\s*\(", text) if not t.startswith("__")
            ]
            declared = [t for t in called if t in names]
            if not declared:
                tokens = [t for t in ident.findall(text.split(";")[0]) if not t.startswith("__")]
                declared = [t for t in tokens[-1:] if t in names]
            found.update(declared[:1])
    return found


@collector("api")
def collect_api(base: Path) -> dict:
    """Collect the public C API from the Doxygen XML output."""
    with tempfile.TemporaryDirectory(prefix="inventory_doxygen_") as td:
        xml_dir = run_doxygen(base, Path(td), ZEPHYR_BASE / "doc" / "zephyr.doxyfile.in")
        index = ET.parse(xml_dir / "index.xml").getroot()
        members: dict[str, dict] = {}
        class2group: dict[str, str] = {}
        member_kinds = {"function", "define", "typedef", "enum", "variable"}

        def text(elem, path):
            node = elem.find(path)
            return (node.text or "").strip() if node is not None else ""

        def location(elem) -> str:
            """Path of the declaring file relative to the tree.

            STRIP_FROM_PATH in the doxyfile makes Doxygen report files under
            ``include/`` relative to that directory.
            """
            loc = elem.find("location")
            if loc is None:
                return ""
            file = loc.get("file", "")
            if os.path.isabs(file):
                return relpath(file, base)
            if (base / "include" / file).exists() and not (base / file).exists():
                return f"include/{file}"
            return file

        def is_deprecated(elem) -> bool:
            # Only the element's own description: a deprecated struct member
            # or enumerator does not deprecate its parent.
            for part in ("briefdescription", "detaileddescription", "inbodydescription"):
                desc = elem.find(part)
                if desc is None:
                    continue
                for xref in desc.iter("xrefsect"):
                    if xref.get("id", "").startswith("deprecated_"):
                        return True
            return False

        def add_members(compounddef, group_title: str, group_name: str):
            for memberdef in compounddef.iter("memberdef"):
                kind = memberdef.get("kind")
                if kind not in member_kinds:
                    continue
                name = text(memberdef, "name")
                if not name or name.startswith("_"):
                    continue
                key = f"{kind}:{name}"
                if key in members and members[key]["group"]:
                    continue
                members[key] = {
                    "kind": kind,
                    "name": name,
                    "group": group_name,
                    "group_title": group_title,
                    "file": location(memberdef),
                    "deprecated": is_deprecated(memberdef),
                }

        group_files = []
        other_files = []
        for compound in index.findall("compound"):
            kind = compound.get("kind")
            refid = compound.get("refid")
            if kind == "group":
                group_files.append(refid)
            elif kind in ("struct", "union", "file"):
                other_files.append((kind, refid))

        for refid in group_files:
            root = ET.parse(xml_dir / f"{refid}.xml").getroot()
            compounddef = root.find("compounddef")
            title = text(compounddef, "title")
            name = text(compounddef, "compoundname")
            for innerclass in compounddef.findall("innerclass"):
                class2group[innerclass.get("refid")] = name
            add_members(compounddef, title, name)

        for kind, refid in other_files:
            root = ET.parse(xml_dir / f"{refid}.xml").getroot()
            compounddef = root.find("compounddef")
            if kind == "file":
                add_members(compounddef, "", "")
                continue
            name = text(compounddef, "compoundname")
            if not name or name.startswith("_") or "::" in name or "." in name:
                continue
            file = location(compounddef)
            if not file.startswith("include/"):
                continue
            members[f"{kind}:{name}"] = {
                "kind": kind,
                "name": name,
                "group": class2group.get(refid, ""),
                "group_title": "",
                "file": file,
                "deprecated": is_deprecated(compounddef),
            }

    # Only the API declared in the public headers belongs in the inventory;
    # devicetree binding constants are not API.
    members = {
        k: v
        for k, v in members.items()
        if v["file"].startswith("include/") and "/dt-bindings/" not in v["file"]
    }
    names = {v["name"] for v in members.values()}
    for name in find_deprecated_declarations(base, names):
        for kind in member_kinds | {"struct", "union"}:
            key = f"{kind}:{name}"
            if key in members:
                members[key]["deprecated"] = True

    # Resolve group titles for members that only know their group name.
    titles = {v["group"]: v["group_title"] for v in members.values() if v["group_title"]}
    for v in members.values():
        if not v["group_title"]:
            v["group_title"] = titles.get(v["group"], "")
    return members



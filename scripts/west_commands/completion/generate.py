# --check ignores these lines so a new date/commit is not a stale-script failure.
STAMP_LINE_PREFIX = "# Generated on "
STAMP_BY_PREFIX = "# by scripts/west_commands/completion/generate.py"


def git_commit() -> str:
    try:
        return (
            subprocess.check_output(
                ["git", "describe", "--always", "--dirty", "--abbrev=12"],
                cwd=ZEPHYR_BASE,
                text=True,
                stderr=subprocess.DEVNULL,
            ).strip()
            or "unknown"
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def generation_header() -> str:
    when = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    return (
        f"{STAMP_LINE_PREFIX}{when} from commit {git_commit()}\n"
        f"{STAMP_BY_PREFIX}. Do not edit by hand.\n"
        "#\n"
    )


def without_generation_stamp(text: str) -> str:
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines):
        if lines[i].startswith(STAMP_LINE_PREFIX):
            i += 1
            if i < len(lines) and lines[i].startswith(STAMP_BY_PREFIX):
                i += 1
            if i < len(lines) and lines[i] == "#":
                i += 1
            continue
        out.append(lines[i])
        i += 1
    text_out = "\n".join(out)
    if text.endswith("\n"):
        text_out += "\n"
    return text_out


def attach_generation_header(shell: str, body: str) -> str:
    stamp = generation_header()
    if shell == "zsh":
        first, sep, rest = body.partition("\n")
        if not sep:
            return stamp + body
        return first + "\n" + stamp + rest.lstrip("\n")
    return stamp + body.lstrip("\n")


def _ensure_import_path():
    for path in (os.fspath(Path(__file__).resolve().parents[1]), os.fspath(ZEPHYR_SCRIPTS)):
        if path not in sys.path:
            sys.path.insert(0, path)


def first_line(text: str | None) -> str:
    if not text:
        return ""
    text = re.sub(r"%\([^)]*\)[sd]", "", text)
    text = " ".join(text.split())
    if len(text) > 100:
        return text[:97].rstrip() + "..."
    return text


def nargs_to_json(nargs: Any) -> Any:
    if nargs is None:
        return None
    if isinstance(nargs, int):
        return nargs
    return str(nargs)


def is_suppressed(action: argparse.Action) -> bool:
    return action.help is argparse.SUPPRESS


def is_subparsers(action: argparse.Action) -> bool:
    return isinstance(action, argparse._SubParsersAction)


def is_boolean_optional(action: argparse.Action) -> bool:
    return type(action).__name__ == "BooleanOptionalAction"


def takes_value(action: argparse.Action) -> bool:
    if is_subparsers(action) or is_boolean_optional(action):
        return False
    if isinstance(
        action,
        (
            argparse._StoreTrueAction,
            argparse._StoreFalseAction,
            argparse._StoreConstAction,
            argparse._CountAction,
            argparse._HelpAction,
            argparse._VersionAction,
            argparse._AppendConstAction,
        ),
    ):
        return False
    return action.nargs != 0


def static_choices(action: argparse.Action) -> list[str] | None:
    if not action.choices:
        return None
    try:
        values = [str(c) for c in action.choices]
    except TypeError:
        return None
    if not values or len(values) > MAX_STATIC_CHOICES:
        return None
    return values


def dest_kind_from_dest(dest: str) -> str | None:
    if not dest:
        return None
    if dest in DEST_HINTS:
        return DEST_HINTS[dest]
    if dest.endswith("_platform"):
        return "board"
    if dest.endswith(("_project", "_projects", "_module", "_modules")):
        return "project"
    return None


def dest_path_hint(action: argparse.Action) -> str | None:
    '''Return file/dir only when dest or metavar clearly means a path.

    Do not scan help text: "directory" in a sentence is not a path option
    (``--allow-regex``, ``--flash-command``). ``type=Path`` alone is not
    enough (``--gcov-tool``).
    '''
    dest = action.dest or ""
    meta = action.metavar if isinstance(action.metavar, str) else ""
    meta_u = meta.upper()
    if dest.endswith(("_dir", "_dirs", "_root", "_roots", "_folder", "_directory")):
        return "dir"
    if dest.endswith(("_file", "_files")):
        return "file"
    if dest.endswith(("_path", "_paths")):
        if meta_u in {"DIR", "DIRECTORY"}:
            return "dir"
        return "file"
    if meta_u in {"DIR", "DIRECTORY"}:
        return "dir"
    if meta_u in {"FILE", "FILENAME"} or meta_u.endswith("_FILE"):
        return "file"
    if isinstance(action.type, argparse.FileType):
        return "file"
    return None


def resolve_hint(command: str, action: argparse.Action) -> str | None:
    keys = [action.dest, *action.option_strings]
    for key in keys:
        hint = HINTS.get((command, key))
        if hint:
            return hint
    kind = dest_kind_from_dest(action.dest or "")
    if kind:
        return kind
    return dest_path_hint(action)


def resolve_positional_hint(command: str, action: argparse.Action, index: int) -> str | None:
    if static_choices(action):
        return None
    if index == 0 and command in POSITIONAL_HINTS:
        return POSITIONAL_HINTS[command]
    return resolve_hint(command, action)


def walk_parser(
    parser: argparse.ArgumentParser, hint_command: str, skip_help=True
) -> dict[str, Any]:
    flags: list[dict[str, Any]] = []
    positionals: list[dict[str, Any]] = []
    subcommands: dict[str, Any] = {}
    pos_index = 0

    for action in parser._get_optional_actions() + parser._get_positional_actions():
        if is_suppressed(action):
            continue
        if is_subparsers(action):
            choice_help = {ca.dest: ca.help or "" for ca in getattr(action, "_choices_actions", [])}
            for subname, subparser in action.choices.items():
                nested = walk_parser(subparser, hint_command)
                nested["help"] = first_line(
                    choice_help.get(subname) or getattr(subparser, "description", None)
                )
                subcommands[subname] = nested
            continue
        if skip_help and action.option_strings and action.dest == "help":
            continue
        if not action.option_strings:
            pos: dict[str, Any] = {
                "dest": action.dest,
                "nargs": nargs_to_json(action.nargs),
            }
            help_text = first_line(action.help)
            if help_text:
                pos["help"] = help_text
            choices = static_choices(action)
            if choices:
                pos["choices"] = choices
            hint = resolve_positional_hint(hint_command, action, pos_index)
            if hint:
                pos["hint"] = hint
            positionals.append(pos)
            pos_index += 1
            continue

        flag: dict[str, Any] = {
            "opts": list(action.option_strings),
            "takes_value": takes_value(action),
        }
        help_text = first_line(action.help)
        if help_text:
            flag["help"] = help_text
        if isinstance(action, argparse._AppendAction) and not isinstance(
            action, argparse._AppendConstAction
        ):
            flag["repeatable"] = True
        if takes_value(action):
            choices = static_choices(action)
            if choices:
                flag["choices"] = choices
            else:
                hint = resolve_hint(hint_command, action)
                if hint:
                    flag["hint"] = hint
        flags.append(flag)

    result: dict[str, Any] = {"flags": flags}
    if positionals:
        result["positionals"] = positionals
    if subcommands:
        result["subcommands"] = subcommands
    return result


def apply_runner_choices(ir: dict[str, Any]) -> None:
    try:
        from runners.core import ZephyrBinaryRunner

        names = sorted(cls.name() for cls in ZephyrBinaryRunner.get_runners())
    except Exception:
        return
    if not names or len(names) > MAX_STATIC_CHOICES:
        return

    def _fill(node: dict[str, Any]) -> None:
        for flag in node.get("flags", []):
            if flag.get("hint") == "runner" and not flag.get("choices"):
                flag["choices"] = names
                del flag["hint"]
        for sub in (node.get("subcommands") or {}).values():
            _fill(sub)

    for spec in ir.get("commands", {}).values():
        _fill(spec)


# Third-party imports some extensions use at runtime, not to build argparse.
_OPTIONAL_EXTENSION_MODULES = (
    "patoolib",
    "tqdm",
    "requests",
    "semver",
)


def stub_missing_modules():
    for name in _OPTIONAL_EXTENSION_MODULES:
        if name in sys.modules:
            continue
        try:
            importlib.import_module(name)
        except ImportError:
            sys.modules[name] = types.ModuleType(name)


def parser_for_command(cmd: Any) -> argparse.ArgumentParser:
    parent = argparse.ArgumentParser(add_help=False, allow_abbrev=False)
    sub = parent.add_subparsers()
    return cmd.add_parser(sub)


def load_extension_class(rel_file: str, class_name: str) -> Any:
    path = (ZEPHYR_BASE / rel_file).resolve()
    key = os.fspath(path)
    module = _EXTENSION_MODULES.get(key)
    if module is None:
        spec = importlib.util.spec_from_file_location(f"west_completion_ext_{path.stem}", path)
        if spec is None or spec.loader is None:
            raise ImportError(f"cannot load {path}")
        module = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = module
        spec.loader.exec_module(module)
        _EXTENSION_MODULES[key] = module
    return getattr(module, class_name)


def collect_global_flags() -> list[dict[str, Any]]:
    # Upstream West does not yet provide a public command/flag introspection API
    # (see https://github.com/zephyrproject-rtos/west/issues). Attempt introspection
    # via WestApp if available, falling back to standard West global flags.
    try:
        from west.app.main import WestApp

        app = WestApp()
        parser, _sub = app.make_parsers()
        walked = walk_parser(parser, "", skip_help=False)
        return walked.get("flags", [])
    except (ImportError, AttributeError, Exception):
        return [
            {
                "opts": ["-h", "--help"],
                "takes_value": False,
                "help": "show help message and exit",
            },
            {
                "opts": ["-z", "--zephyr-base"],
                "takes_value": True,
                "hint": "dir",
                "help": "path to the Zephyr repository",
            },
            {"opts": ["-v", "--verbose"], "takes_value": False, "help": "increase verbosity"},
            {"opts": ["-q", "--quiet"], "takes_value": False, "help": "decrease verbosity"},
            {
                "opts": ["-V", "--version"],
                "takes_value": False,
                "help": "print west version and exit",
            },
        ]


def collect_builtins() -> tuple[dict[str, Any], list[str]]:
    # Upstream West does not yet provide a public command introspection API
    # (see https://github.com/zephyrproject-rtos/west/issues). Introspect via
    # BUILTIN_COMMAND_GROUPS if available, with fallback to importing command classes.
    commands: dict[str, Any] = {}
    errors: list[str] = []
    builtin_classes = []

    try:
        from west.app.main import BUILTIN_COMMAND_GROUPS

        for group, classes in BUILTIN_COMMAND_GROUPS.items():
            if group is None:
                continue
            builtin_classes.extend(classes)
    except (ImportError, AttributeError):
        try:
            from west.app.config import Config
            from west.app.main import Help
            from west.app.project import (
                Compare,
                Diff,
                ForAll,
                Grep,
                Init,
                List,
                Status,
                Topdir,
                Update,
            )

            builtin_classes = [
                Init,
                Update,
                List,
                Compare,
                Diff,
                Status,
                ForAll,
                Grep,
                Topdir,
                Config,
                Help,
            ]
        except (ImportError, AttributeError) as exc:
            errors.append(f"west builtins unavailable: {exc}")
            return commands, errors

    for cls in builtin_classes:
        try:
            cmd = cls()
            parser = parser_for_command(cmd)
        except Exception as exc:
            errors.append(f"builtin {cls.__name__}: {exc}")
            traceback.print_exc(file=sys.stderr)
            continue
        spec = walk_parser(parser, cmd.name)
        spec["help"] = first_line(cmd.help) or first_line(cmd.description)
        spec["source"] = "builtin"
        spec["requires_workspace"] = bool(getattr(cmd, "requires_workspace", True))
        add_synthetic_positionals(cmd.name, spec)
        commands[cmd.name] = spec
    return commands, errors


def collect_extensions() -> tuple[dict[str, Any], list[str]]:
    with open(WEST_COMMANDS_YML, encoding="utf-8") as f:
        data = yaml.safe_load(f)
    commands: dict[str, Any] = {}
    errors: list[str] = []
    for entry in data.get("west-commands", []):
        rel_file = entry["file"]
        for cmd_entry in entry.get("commands", []):
            name = cmd_entry["name"]
            class_name = cmd_entry["class"]
            yml_help = cmd_entry.get("help") or ""
            try:
                cls = load_extension_class(rel_file, class_name)
                cmd = cls()
                parser = parser_for_command(cmd)
            except Exception as exc:
                errors.append(f"extension {name}: {exc}")
                traceback.print_exc(file=sys.stderr)
                continue
            spec = walk_parser(parser, name)
            spec["help"] = (
                first_line(yml_help) or first_line(cmd.help) or first_line(cmd.description)
            )
            spec["source"] = "zephyr"
            spec["requires_workspace"] = bool(getattr(cmd, "requires_workspace", True))
            add_synthetic_positionals(name, spec)
            commands[name] = spec
    return commands, errors


def add_synthetic_positionals(name: str, spec: dict[str, Any]) -> None:
    if spec.get("positionals") or spec.get("subcommands"):
        return
    if name in POSITIONAL_HINTS:
        spec["positionals"] = [
            {"dest": "arg", "hint": POSITIONAL_HINTS[name], "nargs": "?"},
        ]


def collect_ir() -> tuple[dict[str, Any], list[str]]:
    _ensure_import_path()
    stub_missing_modules()
    errors: list[str] = []
    global_flags = collect_global_flags()
    builtins, b_err = collect_builtins()
    extensions, e_err = collect_extensions()
    errors.extend(b_err)
    errors.extend(e_err)
    # Preserve west --help order: builtins (group order) then west-commands.yml.
    commands = {**builtins, **extensions}
    ir = {"global_flags": global_flags, "commands": commands}
    apply_runner_choices(ir)
    return ir, errors


def zsh_escape_help(text: str) -> str:
    text = first_line(text)
    for src, dst in (("\\", " "), ("[", "("), ("]", ")"), (":", " -"), ("'", ""), ('"', "")):
        text = text.replace(src, dst)
    return text


def fish_escape(text: str) -> str:
    return first_line(text).replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def fish_opt_args(opts: list[str]) -> str:
    parts = []
    for opt in opts:
        if opt.startswith("--"):
            parts.append(f"-l {opt[2:]}")
        elif opt.startswith("-") and len(opt) == 2:
            parts.append(f"-s {opt[1:]}")
        elif opt.startswith("-"):
            parts.append(f"-o {opt.lstrip('-')}")
    return " ".join(parts)


def fish_value_args(flag: dict[str, Any]) -> str:
    if not flag.get("takes_value"):
        return ""
    if flag.get("choices"):
        return '-xa "' + " ".join(flag["choices"]) + '"'
    hint = flag.get("hint")
    if hint == "board":
        return '-xa "(__zephyr_west_complete_board)"'
    if hint == "shield":
        return '-xa "(__zephyr_west_complete_shield)"'
    if hint == "snippet":
        return '-xa "(__zephyr_west_complete_snippets)"'
    if hint == "project":
        return '-xa "(__zephyr_west_complete_projects)"'
    if hint == "command":
        return '-xa "(__zephyr_west_complete_help)"'
    if hint == "dir":
        return '-xa "(__zephyr_west_complete_directories)"'
    if hint == "file":
        return "-rF"
    return "-r"


def zsh_value_spec(flag: dict[str, Any]) -> str:
    if not flag.get("takes_value"):
        return ""
    if flag.get("choices"):
        return ":value:(" + " ".join(flag["choices"]) + ")"
    hint = flag.get("hint")
    if hint == "board":
        return ":board:_get_west_boards"
    if hint == "shield":
        return ":shield:_get_west_shields"
    if hint == "snippet":
        return ":snippet:_get_west_snippets"
    if hint == "project":
        return ":project:_get_west_projs"
    if hint == "command":
        return ":command:_west_cmds"
    if hint == "dir":
        return ":dir:_directories"
    if hint == "file":
        return ":file:_files"
    return ":value:"


def zsh_flag_spec(flag: dict[str, Any]) -> str:
    # _arguments: exclusion list, then optional *, then the option.
    # '*(-o --opt)-o[...]' is parsed as a rest argument and is invalid.
    opts = flag["opts"]
    help_text = zsh_escape_help(flag.get("help", ""))
    value = zsh_value_spec(flag)
    star = "*" if flag.get("repeatable") else ""
    if len(opts) == 1:
        return f"'{star}{opts[0]}[{help_text}]{value}'"
    grouped = " ".join(opts)
    brace = ",".join(opts)
    return f"'({grouped}){star}'{{{brace}}}'[{help_text}]{value}'"


def classify_flag_opts(flags: list[dict[str, Any]]) -> dict[str, list[str]]:
    groups = {
        "bool": [],
        "file": [],
        "dir": [],
        "board": [],
        "shield": [],
        "snippet": [],
        "project": [],
        "command": [],
        "other": [],
    }
    for flag in flags:
        opts = flag["opts"]
        if not flag.get("takes_value"):
            groups["bool"].extend(opts)
            continue
        if flag.get("choices"):
            continue
        hint = flag.get("hint")
        if hint in groups:
            groups[hint].extend(opts)
        else:
            groups["other"].extend(opts)
    return groups


def bash_hint_call(hint: str | None) -> str | None:
    return {
        "project": "__set_comp_west_projs",
        "board": "__set_comp_west_boards",
        "shield": "__set_comp_west_shields",
        "snippet": "__set_comp_west_snippets",
        "dir": "__set_comp_dirs",
        "file": "__set_comp_files",
        "command": "__set_comp ${cmds[*]}",
    }.get(hint or "")


def emit_bash_command(name: str, spec: dict[str, Any]) -> str:
    ident = name.replace("-", "_")
    chunks = []
    subcommands = spec.get("subcommands") or {}
    for subname, subspec in subcommands.items():
        chunks.append(emit_bash_command(f"{name}_{subname}", subspec))
    chunks.append(_emit_bash_cmd_body(ident, spec, list(subcommands)))
    return "\n\n".join(chunks)


def _emit_bash_cmd_body(ident: str, spec: dict[str, Any], subcommands: list[str]) -> str:
    flags = spec.get("flags", [])
    groups = classify_flag_opts(flags)
    first_choices: list[str] = []
    first_hint = None
    later_hint = None
    for i, pos in enumerate(spec.get("positionals") or []):
        if pos.get("choices"):
            if i == 0:
                first_choices.extend(pos["choices"])
        elif pos.get("hint"):
            if i == 0:
                first_hint = pos["hint"]
            else:
                later_hint = pos["hint"]

    lines = [f"__comp_west_{ident}()", "{"]
    if subcommands:
        lines.append('\tlocal subcmd=""')
        lines.append("\tlocal i")
        lines.append("\tfor ((i=command_pos+1; i<cword; i++)); do")
        lines.append('\t\tcase "${words[$i]}" in')
        lines.append("\t\t\t" + "|".join(subcommands) + ")")
        lines.append('\t\t\t\tsubcmd="${words[$i]}"')
        lines.append("\t\t\t\tbreak")
        lines.append("\t\t\t\t;;")
        lines.append("\t\tesac")
        lines.append("\tdone")
        lines.append('\tcase "$subcmd" in')
        for subname in subcommands:
            sub_ident = subname.replace("-", "_")
            lines.append(f"\t\t{subname})")
            lines.append(f"\t\t\t__comp_west_{ident}_{sub_ident}")
            lines.append("\t\t\treturn")
            lines.append("\t\t\t;;")
        lines.append("\tesac")

    assignments = [
        ("bool_opts", groups["bool"]),
        ("file_opts", groups["file"]),
        ("dir_opts", groups["dir"]),
        ("board_opts", groups["board"]),
        ("shield_opts", groups["shield"]),
        ("snippet_opts", groups["snippet"]),
        ("project_opts", groups["project"]),
        ("other_opts", groups["other"]),
    ]
    present = []
    for var, opts in assignments:
        if opts:
            lines.append(f'\tlocal {var}="{" ".join(opts)}"')
            present.append(var)
    choice_flags = [f for f in flags if f.get("choices")]
    choice_opts = []
    for flag in choice_flags:
        choice_opts.extend(flag["opts"])
    if choice_opts:
        lines.append(f'\tlocal choice_opts="{" ".join(choice_opts)}"')
        present.append("choice_opts")
    if present:
        lines.append('\tlocal all_opts="' + " ".join(f"${{{p}}}" for p in present) + '"')
    else:
        lines.append('\tlocal all_opts=""')

    for i, flag in enumerate(choice_flags):
        lines.append(f'\tlocal _ch_{i}="{" ".join(flag["opts"])}"')

    lines.append('\tcase "$prev" in')
    for i, flag in enumerate(choice_flags):
        lines.append(f'\t\t$(__west_to_extglob "${{_ch_{i}}}") )')
        lines.append(f'\t\t\t__set_comp {" ".join(flag["choices"])}')
        lines.append("\t\t\treturn")
        lines.append("\t\t\t;;")
    hint_cases = [
        ("dir_opts", groups["dir"], "__set_comp_dirs"),
        ("file_opts", groups["file"], "__set_comp_files"),
        ("board_opts", groups["board"], "__set_comp_west_boards"),
        ("shield_opts", groups["shield"], "__set_comp_west_shields"),
        ("snippet_opts", groups["snippet"], "__set_comp_west_snippets"),
        ("project_opts", groups["project"], "__set_comp_west_projs"),
        ("other_opts", groups["other"], None),
    ]
    for var, opts, helper in hint_cases:
        if not opts:
            continue
        lines.append(f'\t\t$(__west_to_extglob "${{{var}}}") )')
        if helper:
            lines.append(f"\t\t\t{helper}")
        lines.append("\t\t\treturn")
        lines.append("\t\t\t;;")
    lines.append("\tesac")

    words: list[str] = []
    words.extend(subcommands)
    words.extend(first_choices)

    lines.append('\tcase "$cur" in')
    lines.append("\t\t-*)")
    lines.append("\t\t\t__set_comp $all_opts")
    lines.append("\t\t\t;;")
    lines.append("\t\t*)")
    later_call = bash_hint_call(later_hint)
    first_call = bash_hint_call(first_hint)
    if first_choices and later_call:
        value_vars = [
            name
            for name, opts in (
                ("file_opts", groups["file"]),
                ("dir_opts", groups["dir"]),
                ("board_opts", groups["board"]),
                ("shield_opts", groups["shield"]),
                ("snippet_opts", groups["snippet"]),
                ("project_opts", groups["project"]),
                ("other_opts", groups["other"]),
                ("choice_opts", choice_opts),
            )
            if opts
        ]
        joined = " ".join(f"${{{v}}}" for v in value_vars)
        lines.append(f'\t\t\tlocal _pos_flags="{joined}"')
        lines.append(
            '\t\t\tlocal _pos=$(__west_pos_first_nonflag "$(__west_to_extglob "$_pos_flags")")'
        )
        lines.append('\t\t\tif [ "$cword" -eq "$_pos" ]; then')
        lines.append(f'\t\t\t\t__set_comp {" ".join(first_choices)}')
        lines.append("\t\t\telse")
        lines.append(f"\t\t\t\t{later_call}")
        lines.append("\t\t\tfi")
    elif words:
        lines.append(f'\t\t\t__set_comp {" ".join(words)}')
    elif first_call:
        lines.append(f"\t\t\t{first_call}")
    lines.append("\t\t\t;;")
    lines.append("\tesac")
    lines.append("}")
    return "\n".join(lines)


def emit_bash(ir: dict[str, Any]) -> str:
    builtins = [n for n, s in ir["commands"].items() if s.get("source") == "builtin"]
    exts = [n for n, s in ir["commands"].items() if s.get("source") != "builtin"]
    global_bool = []
    global_args = []
    for flag in ir["global_flags"]:
        if flag.get("takes_value"):
            global_args.extend(flag["opts"])
        else:
            global_bool.extend(flag["opts"])

    parts = [GENERATED_BANNER]
    for name, spec in ir["commands"].items():
        parts.append(emit_bash_command(name, spec))
        parts.append("")

    builtin_cmds_str = "\n".join(f"\t\t{n}" for n in builtins)
    zephyr_ext_cmds_str = "\n".join(f"\t\t{n}" for n in exts)
    global_bool_str = " ".join(global_bool)
    global_args_str = " ".join(global_args)

    template = f"""\
__comp_west_west()
{{
\tcase "$prev" in
\t\t--zephyr-base|-z)
\t\t\t__set_comp_dirs
\t\t\treturn
\t\t\t;;
\t\t$(__west_to_extglob "$global_args_opts") )
\t\t\treturn
\t\t\t;;
\tesac
\tcase "$cur" in
\t\t-*)
\t\t\t__set_comp $global_bool_opts $global_args_opts
\t\t\t;;
\t\t*)
\t\t\tlocal counter=$( __west_pos_first_nonflag "$(__west_to_extglob "$global_args_opts")" )
\t\t\tif [ "$cword" -eq "$counter" ]; then
\t\t\t\t__set_comp ${{cmds[*]}}
\t\t\tfi
\t\t\t;;
\tesac
}}

__comp_west()
{{
\tlocal previous_extglob_setting=$(shopt -p extglob)
\tshopt -s extglob
\tlocal IFS=$' \\t\\n'
\tlocal builtin_cmds=(
{builtin_cmds_str}
\t)
\tlocal zephyr_ext_cmds=(
{zephyr_ext_cmds_str}
\t)
\tlocal cmds=(${{builtin_cmds[*]}} ${{zephyr_ext_cmds[*]}})
\tlocal global_bool_opts="{global_bool_str}"
\tlocal global_args_opts="{global_args_str}"
\tCOMPREPLY=()
\tlocal cur words cword prev
\t_get_comp_words_by_ref -n : cur words cword prev
\tlocal command='west' command_pos=0
\tlocal counter=1
\twhile [ "$counter" -lt "$cword" ]; do
\t\tcase "${{words[$counter]}}" in
\t\t\twest)
\t\t\t\treturn 0
\t\t\t\t;;
\t\t\t$(__west_to_extglob "$global_args_opts") )
\t\t\t\t(( counter++ ))
\t\t\t\t;;
\t\t\t-*)
\t\t\t\t;;
\t\t\t=)
\t\t\t\t(( counter++ ))
\t\t\t\t;;
\t\t\t*)
\t\t\t\tcommand="${{words[$counter]}}"
\t\t\t\tcommand_pos=$counter
\t\t\t\tbreak
\t\t\t\t;;
\t\tesac
\t\t(( counter++ ))
\tdone
\tlocal completions_func=__comp_west_${{command//-/_}}
\tdeclare -F $completions_func >/dev/null && $completions_func
\teval "$previous_extglob_setting"
\treturn 0
}}

eval "$__west_previous_extglob_setting"
unset __west_previous_extglob_setting

complete -F __comp_west west
"""
    parts.append(template)
    return "\n".join(parts)


def emit_zsh_command(name: str, spec: dict[str, Any]) -> str:
    func = f"_west_{name}"
    flags = spec.get("flags", [])
    subcommands = spec.get("subcommands") or {}
    lines = [f"{func}() {{"]
    if subcommands:
        lines.append("  local -a _subs=(")
        for subname, subspec in subcommands.items():
            help_text = zsh_escape_help(subspec.get("help") or subname)
            lines.append(f"  '{subname}[{help_text}]'")
        lines.append("  )")
        lines.append("  local line state")
        lines.append("  _arguments -S -C \\")
        for flag in flags:
            lines.append(f"    {zsh_flag_spec(flag)} \\")
        lines.append('          "1: :->cmds" \\')
        lines.append('          "*::arg:->args"')
        lines.append('  case "$state" in')
        lines.append("  cmds)")
        lines.append('    _values "subcommand" $_subs')
        lines.append("    ;;")
        lines.append("  args)")
        lines.append("    case $line[1] in")
        for subname in subcommands:
            lines.append(f"    {subname})")
            lines.append(f"      _west_{name}_{subname.replace('-', '_')} ;;")
        lines.append("    esac")
        lines.append("    ;;")
        lines.append("  esac")
        lines.append("}")
        nested = []
        for subname, subspec in subcommands.items():
            nested.append(emit_zsh_command(f"{name}_{subname.replace('-', '_')}", subspec))
        return "\n".join(lines) + "\n\n" + "\n\n".join(nested)

    lines.append("  local -a opts=(")
    for flag in flags:
        lines.append(f"  {zsh_flag_spec(flag)}")
    lines.append("  )")
    pos_specs = []
    idx = 1
    for pos in spec.get("positionals") or []:
        if pos.get("choices"):
            pos_specs.append(f'"{idx}:value:({" ".join(pos["choices"])})"')
        elif pos.get("hint") == "project":
            pos_specs.append(f'"{idx}:west proj:_get_west_projs"')
        elif pos.get("hint") == "board":
            pos_specs.append(f'"{idx}:board:_get_west_boards"')
        elif pos.get("hint") == "dir":
            pos_specs.append(f'"{idx}:directory:_directories"')
        elif pos.get("hint") == "file":
            pos_specs.append(f'"{idx}:file:_files"')
        elif pos.get("hint") == "command":
            pos_specs.append(f'"{idx}:command:_west_cmds"')
        idx += 1
    if pos_specs:
        lines.append("  _arguments -S $opts \\")
        lines.append("      " + " \\\n      ".join(pos_specs))
    else:
        lines.append("  _arguments -S $opts")
    lines.append("}")
    return "\n".join(lines)


def emit_zsh(ir: dict[str, Any]) -> str:
    builtins = [(n, s) for n, s in ir["commands"].items() if s.get("source") == "builtin"]
    exts = [(n, s) for n, s in ir["commands"].items() if s.get("source") != "builtin"]

    builtin_cmds_str = "\n".join(
        f"  '{name}[{zsh_escape_help(spec.get('help', ''))}]'" for name, spec in builtins
    )
    zephyr_ext_cmds_str = "\n".join(
        f"  '{name}[{zsh_escape_help(spec.get('help', ''))}]'" for name, spec in exts
    )
    global_opts_str = "\n".join(f"  {zsh_flag_spec(flag)}" for flag in ir["global_flags"])

    header = f"""\
{GENERATED_BANNER}
_west_cmds() {{
  local -a builtin_cmds=(
{builtin_cmds_str}
  )
  local -a zephyr_ext_cmds=(
{zephyr_ext_cmds_str}
  )
  local -a all_cmds=(${{builtin_cmds}} ${{zephyr_ext_cmds}})
  if [[ -v WEST_COMP_CHECK_WORKSPACE ]]; then
    west topdir &>/dev/null
    if [ $? -eq 0 ]; then
      _values "west command" $all_cmds
    else
      _values "west command" $builtin_cmds
    fi
  else
      _values "west command" $all_cmds
  fi
}}

_west() {{
  local -a global_opts=(
{global_opts_str}
  )
  typeset -A opt_args
  local curcontext="$curcontext" context state state_descr line
  local -a orig_words
  orig_words=( ${{words[@]}} )
  _arguments -S -C \\
    $global_opts \\
          "1: :->cmds" \\
          "*::arg:->args"
  case "$state" in
  cmds)
    _west_cmds
    ;;
  args)
    _opt_args=( ${{(@kv)opt_args}} )
    _call_function ret _west_$line[1]
    ;;
  esac
}}
"""
    cmd_parts = [emit_zsh_command(name, spec) for name, spec in ir["commands"].items()]
    return header + "\n" + "\n\n".join(cmd_parts) + "\n"


def subcommand_parents(ir: dict[str, Any]) -> dict[str, list[str]]:
    parents: dict[str, list[str]] = {}
    for name, spec in ir["commands"].items():
        for sub in spec.get("subcommands") or {}:
            parents.setdefault(sub, []).append(name)
        for pos in spec.get("positionals") or []:
            for choice in pos.get("choices") or []:
                parents.setdefault(choice, []).append(name)
    return parents


def fish_seen_condition(name: str, ir: dict[str, Any], extra: str = "") -> str:
    parents = subcommand_parents(ir)
    cond = f'__zephyr_west_seen_subcommand_from {name}'
    collisions = [p for p in parents.get(name, []) if p != name]
    for parent in collisions:
        cond += f"; and not __fish_seen_subcommand_from {parent}"
    if extra:
        cond += "; and " + extra
    return cond


def emit_fish_flags(name: str, spec: dict[str, Any], ir: dict[str, Any], seen: str) -> list[str]:
    lines = []
    for flag in spec.get("flags", []):
        opt = fish_opt_args(flag["opts"])
        val = fish_value_args(flag)
        help_text = fish_escape(flag.get("help", ""))
        bits = [f'complete -c west -n "{seen}"']
        if opt:
            bits.append(opt)
        if val:
            bits.append(val)
        if help_text:
            bits.append(f'-d "{help_text}"')
        lines.append(" ".join(bits))
    subcommands = spec.get("subcommands") or {}
    if subcommands:
        names = " ".join(subcommands)
        items = []
        for subname, subspec in subcommands.items():
            help_text = fish_escape(subspec.get("help") or subname)
            items.append(f"{subname}\\t'{help_text}'")
        lines.append(
            f'complete -c west -n "{seen}; and not __fish_seen_subcommand_from {names}" '
            f'-ra "{" ".join(items)}"'
        )
        for subname, subspec in subcommands.items():
            sub_seen = f"{seen}; and __fish_seen_subcommand_from {subname}"
            lines.extend(emit_fish_flags(subname, subspec, ir, sub_seen))
    for pos in spec.get("positionals") or []:
        if pos.get("choices"):
            names = " ".join(pos["choices"])
            lines.append(
                f'complete -c west -n "{seen}; and not __fish_seen_subcommand_from {names}" '
                f'-ra "{names}"'
            )
            continue
        hint = pos.get("hint")
        if hint == "project":
            lines.append(f'complete -c west -n "{seen}" -ra "(__zephyr_west_complete_projects)"')
        elif hint == "dir":
            lines.append(f'complete -c west -n "{seen}" -ra "(__zephyr_west_complete_directories)"')
        elif hint == "command":
            lines.append(f'complete -c west -n "{seen}" -ra "(__zephyr_west_complete_help)"')
        elif hint == "board":
            lines.append(f'complete -c west -n "{seen}" -ra "(__zephyr_west_complete_board)"')
        elif hint == "file":
            lines.append(f'complete -c west -n "{seen}" -rF')
    return lines


def emit_fish(ir: dict[str, Any]) -> str:
    builtins = [(n, s) for n, s in ir["commands"].items() if s.get("source") == "builtin"]
    exts = [(n, s) for n, s in ir["commands"].items() if s.get("source") != "builtin"]
    banner_lines = "\n".join(
        "# " + line if line else "#" for line in GENERATED_BANNER.strip().splitlines()
    )

    def emit_pairs(var: str, items: list[tuple[str, dict[str, Any]]]) -> list[str]:
        out = [f"    set -l {var} \\"]
        for i, (name, spec) in enumerate(items):
            help_text = fish_escape(spec.get("help", ""))
            tail = " \\" if i < len(items) - 1 else ""
            out.append(f'                    "{name}" "{help_text}"{tail}')
        return out

    builtin_pairs = "\n".join(emit_pairs("builtin_cmds", builtins))
    ext_pairs = "\n".join(emit_pairs("ext_cmds", exts))

    global_flags_lines = []
    for flag in ir["global_flags"]:
        opt = fish_opt_args(flag["opts"])
        val = fish_value_args(flag)
        help_text = fish_escape(flag.get("help", ""))
        bits = ["complete -c west"]
        if opt:
            bits.append(opt)
        if val:
            bits.append(val)
        if help_text:
            bits.append(f'-d "{help_text}"')
        global_flags_lines.append(" ".join(bits))
    global_flags_str = "\n".join(global_flags_lines)

    header = f"""\
{banner_lines}

function __zephyr_west_complete_help
{builtin_pairs}
    set -l nb_builtin_cmds (count $builtin_cmds)
{ext_pairs}
    set -l nb_ext_cmds (count $ext_cmds)
    if __zephyr_west_check_if_in_workspace
        for idx in (seq 1 2 $nb_ext_cmds)
            set -l desc_idx (math $idx + 1)
            printf "%s\\n" $ext_cmds[$idx]\\t"$ext_cmds[$desc_idx]"
        end
    end
    for idx in (seq 1 2 $nb_builtin_cmds)
        set -l desc_idx (math $idx + 1)
        printf "%s\\n" $builtin_cmds[$idx]\\t"$builtin_cmds[$desc_idx]"
    end
end

# disable file completion, if an option need it, it should use '--force-files'
complete -c west -f

# global options
{global_flags_str}
"""
    cmd_parts = []
    for name, spec in ir["commands"].items():
        help_text = fish_escape(spec.get("help", ""))
        if spec.get("requires_workspace"):
            cond = "__zephyr_west_use_subcommand; and __zephyr_west_check_if_in_workspace"
        else:
            cond = "__zephyr_west_use_subcommand"
        lines = [f'complete -c west -n "{cond}" -ra {name} -d "{help_text}"']
        seen = fish_seen_condition(name, ir)
        lines.extend(emit_fish_flags(name, spec, ir, seen))
        cmd_parts.append("\n".join(lines))

    return header + "\n" + "\n\n".join(cmd_parts) + "\n"


def render(ir: dict[str, Any]) -> dict[str, str]:
    bash = (RUNTIME_DIR / "west-runtime.bash").read_text(encoding="utf-8").rstrip() + "\n\n"
    zsh = (RUNTIME_DIR / "west-runtime.zsh").read_text(encoding="utf-8").rstrip() + "\n\n"
    fish = (RUNTIME_DIR / "west-runtime.fish").read_text(encoding="utf-8").rstrip() + "\n\n"
    return {
        "bash": attach_generation_header("bash", (bash + emit_bash(ir)).rstrip() + "\n"),
        "zsh": attach_generation_header("zsh", (zsh + emit_zsh(ir)).rstrip() + "\n"),
        "fish": attach_generation_header("fish", (fish + emit_fish(ir)).rstrip() + "\n"),
    }


def dump_json(ir: dict[str, Any]) -> str:
    return json.dumps(ir, indent=2, sort_keys=True) + "\n"


def write_scripts(rendered: dict[str, str]) -> None:
    for shell, text in rendered.items():
        SHELL_OUTPUT[shell].write_text(text, encoding="utf-8", newline="\n")


def check_scripts(rendered: dict[str, str]) -> list[str]:
    stale = []
    for shell, text in rendered.items():
        path = SHELL_OUTPUT[shell]
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if without_generation_stamp(current) != without_generation_stamp(text):
            stale.append(str(path.relative_to(ZEPHYR_BASE)))
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if committed scripts would change",
    )
    parser.add_argument(
        "--dump-json",
        action="store_true",
        help="print the completion IR as JSON on stdout",
    )
    args = parser.parse_args(argv)

    ir, errors = collect_ir()
    if args.dump_json:
        sys.stdout.write(dump_json(ir))
        return 1 if errors else 0

    rendered = render(ir)
    if args.check:
        if errors:
            sys.stderr.write("west completion generator failed to import in-tree parser(s):\n")
            for err in errors:
                sys.stderr.write(f"  {err}\n")
            return 1
        stale = check_scripts(rendered)
        if stale:
            sys.stderr.write(
                "West completion scripts are stale. Regenerate with:\n"
                "  python3 scripts/west_commands/completion/generate.py\n"
                "Out of date:\n"
            )
            for path in stale:
                sys.stderr.write(f"  {path}\n")
            return 1
        return 0

    for err in errors:
        sys.stderr.write(f"warning: {err}\n")
    write_scripts(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main())

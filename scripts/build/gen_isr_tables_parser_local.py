"""Generate relocatable ISR data and explicit input-section placement."""

import struct
from dataclasses import replace

from isr_table_layout import InputSection, Table

METADATA_VERSION = 3
METADATA_FIELDS = (
    "version",
    "header_size",
    "table_size",
    "offset",
    "entry_size",
    "entry_alignment",
    "arg_offset",
    "arg_size",
    "isr_offset",
    "isr_size",
    "shared_size",
    "shared_alignment",
    "shared_count_offset",
    "shared_count_size",
    "shared_count_alignment",
    "vector_size",
    "vector_alignment",
)
RECORD_ALIGNMENT = 4


class gen_isr_parser:
    source_header = """/* Auto-generated by gen_isr_tables.py. */
#include <stddef.h>
#include <stdint.h>
#include <zephyr/sw_isr_table.h>
#if !defined(CONFIG_NUM_IRQS) || defined(CONFIG_IRQ_VECTOR_TABLE_JUMP_BY_CODE)
#include <zephyr/arch/cpu.h>
#endif

"""

    def __init__(self, intlist_data, config, log):
        self.config = config
        self.c_symbol_prefix = getattr(config, "c_symbol_prefix", "")
        self.log = log
        self.vector_cmake_placement = None
        self.header, records = self.read_metadata(intlist_data)
        self.count = self.header["table_size"]
        self.swt = [[] for _ in range(self.count)] if config.args.sw_isr_table else None
        self.vt = [None for _ in range(self.count)] if config.args.vector_table else None
        self.switch = config.check_sym("CONFIG_GEN_SW_ISR_TABLE_SWITCH")
        seen = set()
        for irq, flags, section in records:
            if section in seen:
                raise ValueError(f"Repeated ISR registration section: {section}")
            seen.add(section)
            if flags & 1:
                index = irq - self.header["offset"]
                if self.vt is None:
                    raise ValueError("Direct ISR registered without an IRQ vector table")
                if not 0 <= index < self.count:
                    raise ValueError(f"Direct IRQ {irq} is outside the vector table")
                if self.vt[index] is not None:
                    raise ValueError(f"Multiple direct ISRs for IRQ {irq}")
                self.vt[index] = section
            else:
                if self.swt is None:
                    raise ValueError("ISR registered without a software table")
                index = config.get_swt_table_index(self.header["offset"], irq)
                if not 0 <= index < self.count:
                    raise ValueError(f"IRQ {irq} is outside the software table")
                entries = self.swt[index]
                limit = (
                    config.get_sym("CONFIG_SHARED_IRQ_MAX_NUM_CLIENTS")
                    if config.check_shared_interrupts()
                    else 1
                )
                if len(entries) >= limit:
                    raise ValueError(f"Too many handlers for IRQ {irq}: maximum {limit}")
                entries.append(section)
        self.tables = self.make_layouts()

    def read_metadata(self, data):
        view = memoryview(data)
        prefix = self.config.endian_prefix()
        fmt = prefix + "I" * len(METADATA_FIELDS)
        minimum = struct.calcsize(fmt)
        if len(data) < minimum:
            raise ValueError("Truncated ISR metadata header")
        header = dict(zip(METADATA_FIELDS, struct.unpack_from(fmt, data), strict=True))
        if header["version"] != METADATA_VERSION:
            raise ValueError(f"Unsupported ISR metadata version: {header['version']}")
        offset = header["header_size"]
        if offset < minimum or offset > len(data) or offset % RECORD_ALIGNMENT:
            raise ValueError("Invalid ISR metadata header size")
        if header["table_size"] == 0:
            raise ValueError("Invalid ISR table entry count")
        alignments = ["entry_alignment"]
        if self.config.check_shared_interrupts():
            alignments.extend(("shared_alignment", "shared_count_alignment"))
        if self.config.args.vector_table:
            alignments.append("vector_alignment")
        for name in alignments:
            value = header[name]
            if value <= 0 or value & (value - 1):
                raise ValueError(f"Invalid ISR metadata {name}")
        entry_size = header["entry_size"]
        if entry_size <= 0 or entry_size % header["entry_alignment"]:
            raise ValueError("ISR entry size is not a positive multiple of its alignment")
        for field in ("arg", "isr"):
            if header[f"{field}_size"] <= 0:
                raise ValueError(f"Invalid ISR {field} field size")
            if header[f"{field}_offset"] + header[f"{field}_size"] > entry_size:
                raise ValueError(f"ISR {field} exceeds the entry")
        if (
            header["arg_offset"] < header["isr_offset"] + header["isr_size"]
            and header["isr_offset"] < header["arg_offset"] + header["arg_size"]
        ):
            raise ValueError("ISR argument and function fields overlap")
        if self.config.check_shared_interrupts():
            shared_size = header["shared_size"]
            count_offset = header["shared_count_offset"]
            count_size = header["shared_count_size"]
            count_alignment = header["shared_count_alignment"]
            if shared_size <= 0 or shared_size % header["shared_alignment"]:
                raise ValueError("Invalid shared ISR structure size")
            if header["shared_alignment"] < max(header["entry_alignment"], count_alignment):
                raise ValueError("Shared ISR alignment is smaller than its fields")
            if count_size <= 0 or count_size % count_alignment or count_offset % count_alignment:
                raise ValueError("Invalid shared ISR count field layout")
            clients_size = self.config.get_sym("CONFIG_SHARED_IRQ_MAX_NUM_CLIENTS") * entry_size
            if count_offset < clients_size or count_offset + count_size > shared_size:
                raise ValueError("Shared ISR count field overlaps clients or exceeds the structure")
        if self.config.args.vector_table and (
            header["vector_size"] <= 0 or header["vector_size"] % header["vector_alignment"]
        ):
            raise ValueError("Invalid ISR vector size")
        records = []
        record_fmt = prefix + "IiII"
        record_header = struct.calcsize(record_fmt)
        while offset < len(data):
            if not any(view[offset:]):
                break
            if len(data) - offset < record_header:
                raise ValueError("Truncated ISR registration prefix")
            size, irq, flags, name_size = struct.unpack_from(record_fmt, data, offset)
            if size < record_header + name_size or size % RECORD_ALIGNMENT:
                raise ValueError("Invalid ISR registration size")
            if size > len(data) - offset or name_size <= 1:
                raise ValueError("Truncated ISR registration name")
            name = data[offset + record_header : offset + record_header + name_size]
            if name[-1] != 0 or 0 in name[:-1]:
                raise ValueError("Invalid ISR registration section name")
            records.append((irq, flags, name[:-1].decode("utf-8")))
            offset += size
        return header, records

    @staticmethod
    def generated_section(index):
        return f".isr_generated.0x{index:x}"

    @staticmethod
    def shared_section(index, client):
        return f".isr_shared.0x{index:x}_0x{client:x}"

    @staticmethod
    def count_section(index):
        return f".isr_shared.0x{index:x}_count"

    @staticmethod
    def padding_section(index, part):
        return f".isr_shared.0x{index:x}_pad_{part}"

    def software_section(self, index):
        entries = self.swt[index]
        return entries[0] if len(entries) == 1 else self.generated_section(index)

    def make_layouts(self):
        h = self.header
        tables = {}
        if self.swt is not None:
            indices = (
                [i for i, entries in enumerate(self.swt) if entries]
                if self.switch
                else range(self.count)
            )
            inputs = [
                InputSection(
                    self.software_section(i),
                    position * h["entry_size"],
                    h["entry_size"],
                    h["entry_alignment"],
                    f"z_isr_entry_0x{i:x}",
                )
                for position, i in enumerate(indices)
            ]
            tables["entries" if self.switch else "swi"] = Table(
                "isr_entries" if self.switch else "sw_isr_table",
                "__isr_entries_start" if self.switch else self.config.sw_isr_array_name,
                max(h["entry_alignment"], self.config.get_sym("CONFIG_ARCH_SW_ISR_TABLE_ALIGN")),
                len(inputs) * h["entry_size"],
                inputs,
            )
        if self.config.check_shared_interrupts():
            maximum = self.config.get_sym("CONFIG_SHARED_IRQ_MAX_NUM_CLIENTS")
            before_count = h["shared_count_offset"] - maximum * h["entry_size"]
            after_count = h["shared_size"] - h["shared_count_offset"] - h["shared_count_size"]
            if before_count < 0 or after_count < 0:
                raise ValueError("Invalid shared ISR structure layout")
            inputs = []
            for i, entries in enumerate(self.swt):
                base = i * h["shared_size"]
                for j in range(maximum):
                    section = (
                        entries[j]
                        if len(entries) > 1 and j < len(entries)
                        else self.shared_section(i, j)
                    )
                    inputs.append(
                        InputSection(
                            section,
                            base + j * h["entry_size"],
                            h["entry_size"],
                            h["entry_alignment"],
                            f"z_isr_shared_0x{i:x}_0x{j:x}",
                        )
                    )
                if before_count:
                    inputs.append(
                        InputSection(
                            self.padding_section(i, "before"),
                            base + maximum * h["entry_size"],
                            before_count,
                            1,
                            f"z_isr_shared_pad_before_0x{i:x}",
                        )
                    )
                inputs.append(
                    InputSection(
                        self.count_section(i),
                        base + h["shared_count_offset"],
                        h["shared_count_size"],
                        h["shared_count_alignment"],
                        f"z_isr_shared_count_0x{i:x}",
                    )
                )
                if after_count:
                    inputs.append(
                        InputSection(
                            self.padding_section(i, "after"),
                            base + h["shared_count_offset"] + h["shared_count_size"],
                            after_count,
                            1,
                            f"z_isr_shared_pad_after_0x{i:x}",
                        )
                    )
            tables["shared"] = Table(
                "shared_sw_isr_table",
                self.config.shared_array_name,
                h["shared_alignment"],
                self.count * h["shared_size"],
                inputs,
            )
        if self.vt is not None:
            inputs = [
                InputSection(
                    section or f".irq_spurious.0x{i:x}",
                    i * h["vector_size"],
                    h["vector_size"],
                    h["vector_alignment"],
                    f"z_irq_vector_0x{i:x}",
                )
                for i, section in enumerate(self.vt)
            ]
            tables["vt"] = Table(
                "irq_vector_table",
                self.config.irq_vector_array_name,
                max(
                    h["vector_alignment"], self.config.get_sym("CONFIG_ARCH_IRQ_VECTOR_TABLE_ALIGN")
                ),
                self.count * h["vector_size"],
                inputs,
            )
        for table in tables.values():
            table.symbol = self.c_symbol_prefix + table.symbol
            table.inputs = [
                replace(item, symbol=self.c_symbol_prefix + item.symbol) for item in table.inputs
            ]
            table.validate()
        return tables

    def write_entry(self, fp, name, section, arg, handler):
        fp.write(
            "static Z_DECL_ALIGN(struct _isr_table_entry) Z_ISR_TABLE_STORAGE\n"
            f'Z_GENERIC_SECTION_LITERAL("{section}") __used __noasan {name} = {{\n'
            f"\t.arg = {arg},\n\t.isr = {handler},\n}};\n"
        )

    def write_source(self, fp):
        fp.write(self.source_header)
        for name, table in self.tables.items():
            table.write_alignment_source(
                fp, writable=name != "vt" and self.config.check_sym("CONFIG_SRAM_SW_ISR_TABLE")
            )
        if self.vt is not None:
            for i, section in enumerate(self.vt):
                if section is None:
                    fp.write(
                        f'_Z_ISR_DIRECT_TABLE_DEFAULT({self.config.vt_default_handler}, '
                        f'".irq_spurious.0x{i:x}");\n'
                    )
        if self.swt is not None:
            for i, entries in enumerate(self.swt):
                if not entries and not self.switch:
                    self.write_entry(
                        fp,
                        f"z_isr_default_{i}",
                        self.generated_section(i),
                        "NULL",
                        self.config.swt_spurious_handler,
                    )
                elif len(entries) > 1:
                    self.write_entry(
                        fp,
                        f"z_isr_dispatch_{i}",
                        self.generated_section(i),
                        f"&{self.config.shared_array_name}[{i}]",
                        self.config.swt_shared_handler,
                    )
        if self.config.check_shared_interrupts():
            h = self.header
            maximum = self.config.get_sym("CONFIG_SHARED_IRQ_MAX_NUM_CLIENTS")
            before = h["shared_count_offset"] - maximum * h["entry_size"]
            after = h["shared_size"] - h["shared_count_offset"] - h["shared_count_size"]
            for i, entries in enumerate(self.swt):
                for j in range(maximum):
                    if len(entries) <= 1 or j >= len(entries):
                        self.write_entry(
                            fp, f"z_isr_empty_{i}_{j}", self.shared_section(i, j), "NULL", "NULL"
                        )
                count = len(entries) if len(entries) > 1 else 0
                fp.write(
                    "static Z_DECL_ALIGN(size_t) Z_ISR_TABLE_STORAGE\n"
                    f'Z_GENERIC_SECTION_LITERAL("{self.count_section(i)}") '
                    f"__used __noasan z_isr_count_{i} = {count};\n"
                )
                for part, size in (("before", before), ("after", after)):
                    if size:
                        fp.write(
                            f"static Z_ISR_TABLE_STORAGE uint8_t z_isr_pad_{part}_{i}[{size}]\n"
                            f'Z_GENERIC_SECTION_LITERAL("{self.padding_section(i, part)}") '
                            "__used __noasan = {0};\n"
                        )
        if self.switch:
            self.write_switch(fp)

    def write_switch(self, fp):
        for i, entries in enumerate(self.swt):
            if entries:
                fp.write(
                    f"extern Z_ISR_TABLE_STORAGE struct _isr_table_entry z_isr_entry_0x{i:x};\n"
                )
        fp.write(
            "void get_isr_entry(int irq_index, struct _isr_table_entry *entry)\n"
            "{\n\tswitch (irq_index) {\n"
        )
        for i, entries in enumerate(self.swt):
            if entries:
                fp.write(f"\tcase {i}:\n\t\t*entry = z_isr_entry_0x{i:x};\n\t\tbreak;\n")
        fp.write(
            "\tdefault:\n\t\tentry->arg = NULL;\n"
            f"\t\tentry->isr = {self.config.swt_spurious_handler};\n"
            "\t\tbreak;\n\t}\n}\n"
        )

    def write_linker_vt(self, fp):
        if "vt" in self.tables:
            self.tables["vt"].write_ld(fp)

    def write_linker_swi(self, fp):
        if "swi" in self.tables:
            self.tables["swi"].write_ld(fp)

    def write_linker_shared(self, fp):
        if "shared" in self.tables:
            self.tables["shared"].write_ld(fp)

    def write_linker_entries(self, fp):
        if "entries" in self.tables:
            self.tables["entries"].write_ld(fp)

    def write_cmake(self, fp):
        for name, table in self.tables.items():
            if name == "vt" and self.vector_cmake_placement is not None:
                section, offset = self.vector_cmake_placement
                table.write_cmake(
                    fp, section_override=section, base_offset=offset, priority_base=100
                )
            else:
                table.write_cmake(fp)

    def layout_manifest(self):
        from dataclasses import asdict

        return {
            "version": 1,
            "metadata_policy": "nonallocated"
            if getattr(self.config, "metadata_nonallocated", False)
            else "absent",
            "byte_order": "big" if self.config.args.big_endian else "little",
            "metadata": self.header,
            "tables": [
                asdict(table)
                | {
                    "end_symbol": table.end_symbol,
                    "writable": name != "vt" and self.config.check_sym("CONFIG_SRAM_SW_ISR_TABLE"),
                }
                for name, table in self.tables.items()
            ],
        }

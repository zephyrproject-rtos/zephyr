"""
Script to generate __secure_call crossing stubs for ARMv8-M TrustZone

Reads the JSON produced by parse_secure_calls.py and generates two sets
of files depending on --target:

  --target ns  Per-header inline wrapper files in <base-output>/<header>.h
               Each wrapper packs typed arguments into uintptr_t values and
               calls the z_secure_mrsh_* veneer via libentryveneers.a.
               Also writes the secure_call_list.h ID header.

  --target s   A single secure_call_entries.c containing the S-side entry
               functions decorated with __attribute__((cmse_nonsecure_entry)).
               Each entry unpacks uintptr_t args back to typed values and
               calls the hand-written z_secure_vrfy_* validator.

Phase 1 limitation: at most 4 uintptr_t-sized arguments per function.
Functions exceeding this limit will produce a #error at build time (NS side)
or a Python exception at code-gen time (S side) to fail loudly.
"""

import argparse
import json
import os
import re
import sys

typename_regex = re.compile(r'(.*?)([A-Za-z0-9_]+)$')

MAX_ARGS = 4  # r0-r3 only cross the CMSE boundary safely


class SecureCallParseException(Exception):
    pass


def typename_split(item):
    if "[" in item:
        raise SecureCallParseException(
            f"Please pass arrays to secure calls as pointers, cannot process '{item}'"
        )
    if "(" in item:
        raise SecureCallParseException("Please use typedefs for function pointers")

    mo = typename_regex.match(item)
    if not mo:
        raise SecureCallParseException("Malformed secure call declaration")

    m = mo.groups()
    return (m[0].strip(), m[1])


def union_decl(ctype):
    return f"union {{ uintptr_t x; {ctype} val; }}"


ns_file_template = """\
/* auto-generated by gen_secure_calls.py, don't edit */

{include_guard}

#ifndef _ASMLANGUAGE

#include <stdint.h>
#include <zephyr/toolchain.h>
#include <zephyr/secure_call_list.h>
#include <zephyr/secure_call.h>

#ifdef __cplusplus
extern "C" {{
#endif

{invocations}

#ifdef __cplusplus
}}
#endif

#endif /* _ASMLANGUAGE */
#endif /* include guard */
"""

secure_call_list_template = """\
/* auto-generated by gen_secure_calls.py, don't edit */

#ifndef ZEPHYR_SECURE_CALL_LIST_H
#define ZEPHYR_SECURE_CALL_LIST_H

{defines}

#endif /* ZEPHYR_SECURE_CALL_LIST_H */
"""


def wrapper_defs_ns(func_name, func_type, args):
    """Generate the NS-side static inline wrapper for one secure call."""
    nargs = len(args)
    mrsh_name = f"z_secure_mrsh_{func_name}"
    impl_name = f"z_secure_impl_{func_name}"

    decl_arglist = ", ".join([" ".join(a) for a in args]) or "void"
    mrsh_decl_args = ", ".join([f"uintptr_t arg{i}" for i in range(nargs)]) or "void"

    wrap = f"extern {func_type} {mrsh_name}({mrsh_decl_args});\n"
    wrap += f"extern {func_type} {impl_name}({decl_arglist});\n"
    wrap += "\n"
    wrap += f"static inline {func_type} {func_name}({decl_arglist})\n"
    wrap += "{\n"
    wrap += "#if defined(CONFIG_TRUSTED_EXECUTION_NONSECURE)\n"

    if nargs > MAX_ARGS:
        wrap += (
            f'\t#error "__secure_call {func_name}: {nargs} arguments exceeds '
            f'Phase 1 limit of {MAX_ARGS} (r0-r3 only cross the CMSE boundary)"\n'
        )
    else:
        for i, (argtype, argname) in enumerate(args):
            decl = union_decl(argtype)
            wrap += f"\t{decl} p{i} = {{ .val = {argname} }};\n"

        invoke_args = ", ".join([f"p{i}.x" for i in range(nargs)])

        if func_type == "void":
            wrap += "\tz_secure_call_lock();\n"
            wrap += f"\t{mrsh_name}({invoke_args});\n"
            wrap += "\tz_secure_call_unlock();\n"
        else:
            wrap += f"\t{func_type} _ret;\n"
            wrap += "\tz_secure_call_lock();\n"
            wrap += f"\t_ret = ({func_type}){mrsh_name}({invoke_args});\n"
            wrap += "\tz_secure_call_unlock();\n"
            wrap += "\treturn _ret;\n"

    impl_arglist = ", ".join([a[1] for a in args])
    ret = "return " if func_type != "void" else ""
    wrap += "#else\n"
    wrap += "\tcompiler_barrier();\n"
    wrap += f"\t{ret}{impl_name}({impl_arglist});\n"
    wrap += "#endif\n"
    wrap += "}\n"

    return wrap


s_file_header = """\
/* auto-generated by gen_secure_calls.py, don't edit */

#if defined(CONFIG_ARM_SECURE_FIRMWARE)

#include <stdint.h>
#include <zephyr/internal/secure_call_handler.h>

/*
 * When NSC veneers are placed at an NS-alias VMA (CONFIG_ARM_NSC_REGION_IN_NS_ALIAS),
 * the cmse_nonsecure_entry functions must also be at NS-alias VMA so the CMSE
 * toolchain's B.W offset fits (±16 MB limit).  The named section .cmse_entry_thunks
 * is placed at NS-alias VMA by secure_entry_functions.ld in that configuration.
 */
#if defined(CONFIG_ARM_NSC_REGION_IN_NS_ALIAS)
#define Z_CMSE_ENTRY_ATTR \\
	__attribute__((cmse_nonsecure_entry, section(".cmse_entry_thunks")))
#else
#define Z_CMSE_ENTRY_ATTR \\
	__attribute__((cmse_nonsecure_entry))
#endif

"""

s_file_footer = """\

#endif /* CONFIG_ARM_SECURE_FIRMWARE */
"""


def entry_defs_s(func_name, func_type, args):
    """Generate the S-side cmse_nonsecure_entry function for one secure call."""
    nargs = len(args)
    if nargs > MAX_ARGS:
        raise SecureCallParseException(
            f"__secure_call {func_name}: {nargs} arguments exceeds "
            f"Phase 1 limit of {MAX_ARGS} (r0-r3 only cross the CMSE boundary)"
        )

    mrsh_name = f"z_secure_mrsh_{func_name}"
    vrfy_name = f"z_secure_vrfy_{func_name}"

    decl_arglist = ", ".join([" ".join(a) for a in args]) or "void"
    mrsh_decl_args = ", ".join([f"uintptr_t arg{i}" for i in range(nargs)]) or "void"

    entry = f"extern {func_type} {vrfy_name}({decl_arglist});\n"
    entry += "\n"
    entry += "Z_CMSE_ENTRY_ATTR\n"
    entry += f"{func_type} {mrsh_name}({mrsh_decl_args})\n"
    entry += "{\n"

    for i, (argtype, _) in enumerate(args):
        decl = union_decl(argtype)
        entry += f"\t{decl} p{i};\n"
        entry += f"\tp{i}.x = arg{i};\n"

    out_args = ", ".join([f"p{i}.val" for i in range(nargs)])
    ret = "return " if func_type != "void" else ""
    entry += f"\t{ret}{vrfy_name}({out_args});\n"
    entry += "}\n"

    return entry


def analyze_fn(match_group, fn):
    func, raw_args = match_group

    try:
        if raw_args.strip() == "void" or raw_args.strip() == "":
            args = []
        else:
            args = [typename_split(a.strip()) for a in raw_args.split(",")]

        func_type, func_name = typename_split(func)
    except SecureCallParseException:
        sys.stderr.write(f"In declaration of {func}\n")
        raise

    sys_id = "K_SECURE_CALL_" + func_name.upper()
    return func_name, func_type, args, sys_id


def parse_args():
    global args
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
        allow_abbrev=False,
    )
    parser.add_argument(
        "-i", "--json-file", required=True,
        help="Read secure call information from JSON file (output of parse_secure_calls.py)",
    )
    parser.add_argument(
        "--target", required=True, choices=["ns", "s"],
        help="Which side to generate: 'ns' for Non-Secure wrappers, 's' for Secure entries",
    )
    parser.add_argument(
        "-o", "--base-output", required=True,
        help="Base output directory for per-header .h files (ns) or secure_call_entries.c (s)",
    )
    parser.add_argument(
        "-l", "--secure-call-list", required=False,
        help="Output path for secure_call_list.h (written by --target ns only)",
    )
    args = parser.parse_args()


def main():
    parse_args()

    with open(args.json_file) as fd:
        secure_calls = json.load(fd)

    os.makedirs(args.base_output, exist_ok=True)

    if args.target == "ns":
        # Per-header invocation wrappers + secure_call_list.h
        # invocations: fn → {func_name → wrapper_string}  (dict preserves insertion order,
        # inner dict deduplicates functions that appear in multiple files with the same basename)
        invocations = {}
        ids_emit = []
        ids_not_emit = []

        for match_group, fn, to_emit in secure_calls:
            func_name, func_type, fn_args, sys_id = analyze_fn(match_group, fn)

            if fn not in invocations:
                invocations[fn] = {}
            if func_name not in invocations[fn]:
                invocations[fn][func_name] = wrapper_defs_ns(func_name, func_type, fn_args)

            if to_emit:
                if sys_id not in ids_emit:
                    ids_emit.append(sys_id)
            else:
                if sys_id not in ids_not_emit:
                    ids_not_emit.append(sys_id)

        # Emit per-header files
        for fn, invo_dict in invocations.items():
            out_path = os.path.join(args.base_output, fn)
            ig = re.sub("[^a-zA-Z0-9]", "_", "Z_INCLUDE_SECURE_CALLS_" + fn).upper()
            include_guard = f"#ifndef {ig}\n#define {ig}"
            content = ns_file_template.format(
                include_guard=include_guard,
                invocations="\n\n".join(invo_dict.values()),
            )
            with open(out_path, "w") as fp:
                fp.write(content)

        # Emit secure_call_list.h
        if args.secure_call_list:
            ids_emit.sort()
            defines = ""
            for i, item in enumerate(ids_emit):
                defines += f"#define {item} {i}\n"
            if ids_emit:
                defines += f"#define K_SECURE_CALL_LIMIT {len(ids_emit)}\n"
            if ids_not_emit:
                defines += "\n/* Secure calls not emitted in this image */\n"
                ids_not_emit.sort()
                for i, item in enumerate(ids_not_emit):
                    defines += f"#define {item} {i + len(ids_emit)}\n"

            content = secure_call_list_template.format(defines=defines)
            os.makedirs(os.path.dirname(args.secure_call_list), exist_ok=True)
            with open(args.secure_call_list, "w") as fp:
                fp.write(content)

    elif args.target == "s":
        # Single secure_call_entries.c with all cmse_nonsecure_entry functions.
        # entries dict deduplicates functions that appear in multiple headers sharing a basename.
        entries = {}

        for match_group, fn, to_emit in secure_calls:
            if not to_emit:
                continue
            func_name, func_type, fn_args, _ = analyze_fn(match_group, fn)
            if func_name not in entries:
                entries[func_name] = entry_defs_s(func_name, func_type, fn_args)

        out_path = os.path.join(args.base_output, "secure_call_entries.c")
        with open(out_path, "w") as fp:
            fp.write(s_file_header)
            fp.write("\n".join(entries.values()))
            fp.write(s_file_footer)


if __name__ == "__main__":
    main()

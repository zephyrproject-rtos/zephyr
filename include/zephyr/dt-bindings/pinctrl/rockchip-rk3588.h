#ifndef ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_ROCKCHIP_RK3588_H_
#define ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_ROCKCHIP_RK3588_H_

/*
 * RK3588 pinmux cell:
 *
 *   15..12  reserved
 *   11..9   GPIO bank (0-4)
 *    8..4   pin within bank (0-31)
 *    3..0   mux function (0-15)
 */
#define RK3588_PINMUX(bank, pin, function)                                                         \
	((((bank) & 0x7U) << 9U) | (((pin) & 0x1fU) << 4U) | ((function) & 0xfU))

#define RK3588_PINMUX_BANK(pinmux)     (((pinmux) >> 9U) & 0x7U)
#define RK3588_PINMUX_PIN(pinmux)      (((pinmux) >> 4U) & 0x1fU)
#define RK3588_PINMUX_FUNCTION(pinmux) ((pinmux) & 0xfU)

/* ROCK 5B UART functions used by the board. */
#define RK3588_PIN_UART2_TX_M0 RK3588_PINMUX(0, 13, 10)
#define RK3588_PIN_UART2_RX_M0 RK3588_PINMUX(0, 14, 10)
#define RK3588_PIN_UART2_TX_M2 RK3588_PINMUX(3, 9, 10)
#define RK3588_PIN_UART2_RX_M2 RK3588_PINMUX(3, 10, 10)

#define RK3588_PIN_UART3_TX_M1 RK3588_PINMUX(3, 13, 10)
#define RK3588_PIN_UART3_RX_M1 RK3588_PINMUX(3, 14, 10)

#define RK3588_PIN_UART4_TX_M2 RK3588_PINMUX(1, 11, 10)
#define RK3588_PIN_UART4_RX_M2 RK3588_PINMUX(1, 10, 10)

#define RK3588_PIN_UART7_TX_M2 RK3588_PINMUX(1, 13, 10)
#define RK3588_PIN_UART7_RX_M2 RK3588_PINMUX(1, 12, 10)

/* ROCK 5B I2C functions. */
#define RK3588_PIN_I2C0_SCL_M1 RK3588_PINMUX(4, 21, 9)
#define RK3588_PIN_I2C0_SDA_M1 RK3588_PINMUX(4, 22, 9)
#define RK3588_PIN_I2C6_SCL_M0 RK3588_PINMUX(0, 24, 9)
#define RK3588_PIN_I2C6_SDA_M0 RK3588_PINMUX(0, 23, 9)

/* ROCK 5B SPI functions. */
#define RK3588_PIN_SPI0_MISO_M2 RK3588_PINMUX(1, 9, 8)
#define RK3588_PIN_SPI0_MOSI_M2 RK3588_PINMUX(1, 10, 8)
#define RK3588_PIN_SPI0_CLK_M2  RK3588_PINMUX(1, 11, 8)
#define RK3588_PIN_SPI0_CS0_M2  RK3588_PINMUX(1, 12, 8)
#define RK3588_PIN_SPI0_CS1_M2  RK3588_PINMUX(1, 13, 8)

#define RK3588_PIN_SPI1_MISO_M1 RK3588_PINMUX(3, 16, 8)
#define RK3588_PIN_SPI1_MOSI_M1 RK3588_PINMUX(3, 15, 8)
#define RK3588_PIN_SPI1_CLK_M1  RK3588_PINMUX(3, 17, 8)
#define RK3588_PIN_SPI1_CS0_M1  RK3588_PINMUX(3, 18, 8)
#define RK3588_PIN_SPI1_CS1_M1  RK3588_PINMUX(3, 19, 8)

#define RK3588_PIN_SPI3_MISO_M0 RK3588_PINMUX(4, 20, 8)
#define RK3588_PIN_SPI3_MOSI_M0 RK3588_PINMUX(4, 21, 8)
#define RK3588_PIN_SPI3_CLK_M0  RK3588_PINMUX(4, 22, 8)

/* ROCK 5B PWM alternatives. */
#define RK3588_PIN_PWM2_M1    RK3588_PINMUX(3, 9, 11)
#define RK3588_PIN_PWM5_M2    RK3588_PINMUX(4, 20, 11)
#define RK3588_PIN_PWM6_M2    RK3588_PINMUX(4, 21, 11)
#define RK3588_PIN_PWM7_IR_M3 RK3588_PINMUX(4, 22, 11)
#define RK3588_PIN_PWM8_M0    RK3588_PINMUX(3, 7, 11)
#define RK3588_PIN_PWM12_M0   RK3588_PINMUX(3, 13, 11)
#define RK3588_PIN_PWM13_M0   RK3588_PINMUX(3, 14, 11)

#endif /* ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_ROCKCHIP_RK3588_H_ */

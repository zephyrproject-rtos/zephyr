#ifndef ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_HPMICRO_PINCTRL_COMMON_H_
#define ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_HPMICRO_PINCTRL_COMMON_H_

#define HPMICRO_PIN_NUM_MASK  0x3FFU
#define HPMICRO_PIN_NUM_SHIFT 0U

#define HPMICRO_PIN_ANALOG_MASK  0x1U
#define HPMICRO_PIN_ANALOG_SHIFT 10U

#define HPMICRO_PIN_ALT_MASK  0x1FU
#define HPMICRO_PIN_ALT_SHIFT 11U

#define HPMICRO_PIN_IOC_MASK  0x3U
#define HPMICRO_PIN_IOC_SHIFT 30U

#define HPMICRO_PORTA 0U
#define HPMICRO_PORTB 32U
#define HPMICRO_PORTC 64U
#define HPMICRO_PORTD 96U
#define HPMICRO_PORTE 128U
#define HPMICRO_PORTF 160U
#define HPMICRO_PORTX 416U
#define HPMICRO_PORTY 448U
#define HPMICRO_PORTZ 480U

#define IOC_TYPE_IOC  0U
#define IOC_TYPE_BIOC 1U
#define IOC_TYPE_PIOC 2U

#define HPMICRO_PIN(_port, _pin) ((_port) + (_pin))

#define HPMICRO_PINMUX(_pin, _ioc, _analog, _alt)                                                  \
	((((_pin) & HPMICRO_PIN_NUM_MASK) << HPMICRO_PIN_NUM_SHIFT) |                              \
	 (((_analog) & HPMICRO_PIN_ANALOG_MASK) << HPMICRO_PIN_ANALOG_SHIFT) |                     \
	 (((_alt) & HPMICRO_PIN_ALT_MASK) << HPMICRO_PIN_ALT_SHIFT) |                              \
	 (((_ioc) & HPMICRO_PIN_IOC_MASK) << HPMICRO_PIN_IOC_SHIFT))

#define HPMICRO_OPEN_DRAIN_MASK  0x1U
#define HPMICRO_OPEN_DRAIN_SHIFT 0U

#define HPMICRO_NO_PULL_MASK  0x1U
#define HPMICRO_NO_PULL_SHIFT 1U

#define HPMICRO_PULL_DOWN_MASK  0x1U
#define HPMICRO_PULL_DOWN_SHIFT 2U

#define HPMICRO_PULL_UP_MASK  0x1U
#define HPMICRO_PULL_UP_SHIFT 3U

#define HPMICRO_FORCE_INPUT_MASK  0x1U
#define HPMICRO_FORCE_INPUT_SHIFT 4U

#define HPMICRO_DRIVER_STRENGTH_MASK  0x7U
#define HPMICRO_DRIVER_STRENGTH_SHIFT 5U

#define HPMICRO_SLEW_PD_MASK  0x3U
#define HPMICRO_SLEW_PD_SHIFT 8U

#define HPMICRO_PULL_STRENGTH_MASK  0x3U
#define HPMICRO_PULL_STRENGTH_SHIFT 10U

#define HPMICRO_SCHMITT_ENABLE_MASK  0x1U
#define HPMICRO_SCHMITT_ENABLE_SHIFT 12U

#define HPMICRO_SLEW_RATE_MASK  0x1U
#define HPMICRO_SLEW_RATE_SHIFT 13U

#define HPMICRO_KEEPER_DISABLE_MASK  0x1U
#define HPMICRO_KEEPER_DISABLE_SHIFT 14U

#endif /* ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_HPMICRO_PINCTRL_COMMON_H_ */

/*
 * The whole TI CC35XX pin configuration information is encoded in a 32-bit
 * bitfield organized as follows:
 *
 * - 31..22: Reserved.
 * - 21..16: Pin.
 * - 15..11: Reserved.
 * - 11..10: Pin direction.
 * - 9:      Pull-down flag.
 * - 8:      Pull-up flag.
 * - 7..5:   Drive strength.
 * - 4:      Enable open-drain flag.
 * - 3..0:   Configuration mode.
 */

/**
 * @name TI CC35XX pin configuration bit field positions and masks.
 * @{
 */

#define TI_CC35XX_PIN_MSK     0x3f
#define TI_CC35XX_PIN_POS     16
#define TI_CC35XX_OUT_OVR_MSK 0x03
#define TI_CC35XX_OUT_OVR_POS 12
#define TI_CC35XX_DIR_MSK     0x03
#define TI_CC35XX_DIR_POS     10
#define TI_CC35XX_PU_PD_MSK   0x03
#define TI_CC35XX_PU_PD_POS   8
#define TI_CC35XX_MUX_MSK     0x0f
#define TI_CC35XX_MUX_POS     0

/** @} */

#define TI_CC35XX_PINCTRL_DIR_BI       (TI_CC35XX_PINCTRL_DIR_IN | TI_CC35XX_PINCTRL_DIR_OUT)
#define TI_CC35XX_PINCTRL_DIR_IN       (2 << TI_CC35XX_DIR_POS)
#define TI_CC35XX_PINCTRL_DIR_OUT      (1 << TI_CC35XX_DIR_POS)
#define TI_CC35XX_PINCTRL_PULL_UP      (1 << TI_CC35XX_PU_PD_POS)
#define TI_CC35XX_PINCTRL_PULL_DOWN    (2 << TI_CC35XX_PU_PD_POS)
#define TI_CC35XX_PINCTRL_PULL_DISABLE (3 << TI_CC35XX_PU_PD_POS)

#define TI_CC35XX_PINCTRL_PIN(PCFG) (((PCFG) >> TI_CC35XX_PIN_POS) & TI_CC35XX_PIN_MSK)
#define TI_CC35XX_PINCTRL_MUX(PCFG) (((PCFG) >> TI_CC35XX_MUX_POS) & TI_CC35XX_MUX_MSK)

#define TI_CC35XX_PINCTRL_OVR_SET_VAL(en, val) (((en << 1) | val) << TI_CC35XX_OUT_OVR_POS)
#define TI_CC35XX_PINCTRL_OVR_VAL(PCTL) (((PCTL) >> TI_CC35XX_OUT_OVR_POS) & TI_CC35XX_OUT_OVR_MSK)

#define TI_CC35XX_PINCTRL_OVR_NO_CHANGE   TI_CC35XX_PINCTRL_OVR_SET_VAL(0, 0)
#define TI_CC35XX_PINCTRL_OVR_DISABLE     TI_CC35XX_PINCTRL_OVR_SET_VAL(0, 1)
#define TI_CC35XX_PINCTRL_OVR_ENABLE_LOW  TI_CC35XX_PINCTRL_OVR_SET_VAL(1, 0)
#define TI_CC35XX_PINCTRL_OVR_ENABLE_HIGH TI_CC35XX_PINCTRL_OVR_SET_VAL(1, 1)

/**
 * @brief Utility macro to build TI CC35XX pinmux property entry.
 *
 * @param pin Pin
 * @param mux Multiplexer choice
 */
#define TI_CC35XX_PINMUX(pin, mux)                                                                 \
	((((pin) & TI_CC35XX_PIN_MSK) << TI_CC35XX_PIN_POS) |                                      \
	 (((mux) & TI_CC35XX_MUX_MSK) << TI_CC35XX_MUX_POS))

#define TI_CC35XX_ANALOG_MUX 0x0d
#define TI_CC35XX_ANALOG(pin)                                                                      \
	(TI_CC35XX_PINMUX(pin, TI_CC35XX_ANALOG_MUX) | TI_CC35XX_PINCTRL_DIR_IN)


/**
 * @file
 * @brief i.MX RT266x clock identifiers for the nxp,imx-ccm-rev3 controller.
 *
 * Three independent identifier spaces:
 *
 *  - @c IMX_CCM_LPCG_* -- peripheral clock gates. The RT266x clock tree spans
 *    seven CCM instances (SYSCON, CMPT, MAIN, WAKE, COMM, AUDIO, MEDIA); a gate
 *    identifier names both the owning instance and the slice within it, which
 *    the HAL resolves at run time.
 *  - @c IMX_CCM_ROOT_* -- clock roots, likewise spanning all seven instances.
 *    A root is what carries a mux and dividers, so it is what determines a
 *    peripheral's frequency.
 *  - @c IMX_CCM_MUX_<root>_<source> -- the per-root mux selector values. Each
 *    root has its own source list, so these are namespaced by root.
 *
 * Peripheral nodes combine a gate and a root with @c IMX_CCM_CLK();
 * clock-root child nodes of the controller take a root identifier in @c reg
 * and a mux value in @c clock-mux.
 *
 * Generated from fsl_clock.h (clock_lpcg_t, clock_root_t,
 * clock_root_mux_source_t) by
 * modules/hal_nxp/scripts/clock/gen_ccm_rev3_ids.py, so the values cannot drift from
 * the HAL enumerations the driver passes them to. Do not edit by hand;
 * regenerate against a newer device release instead. The _START/_END range
 * markers and the invalid sentinels are intentionally not exported -- use
 * @c IMX_CCM_GATE_NONE / @c IMX_CCM_ROOT_NONE from
 * <zephyr/dt-bindings/clock/imx_ccm_rev3.h> instead.
 *
 * FSL clock driver version: 1.1.0
 * Source: hal_nxp 45f49e6ef / RT2660 MIMXRT2663 public SDK
 */


#define CH32V00X_CLOCK_AFIO   CH32_CLOCK(PB2, 0)
#define CH32V00X_CLOCK_IOPA   CH32_CLOCK(PB2, 2)
#define CH32V00X_CLOCK_IOPB   CH32_CLOCK(PB2, 3)
#define CH32V00X_CLOCK_IOPC   CH32_CLOCK(PB2, 4)
#define CH32V00X_CLOCK_IOPD   CH32_CLOCK(PB2, 5)
#define CH32V00X_CLOCK_ADC1   CH32_CLOCK(PB2, 9)
#define CH32V00X_CLOCK_TIM1   CH32_CLOCK(PB2, 11)
#define CH32V00X_CLOCK_SPI1   CH32_CLOCK(PB2, 12)
#define CH32V00X_CLOCK_USART2 CH32_CLOCK(PB2, 13)
#define CH32V00X_CLOCK_USART1 CH32_CLOCK(PB2, 14)

#define CH32V00X_CLOCK_TIM2 CH32_CLOCK(PB1, 0)

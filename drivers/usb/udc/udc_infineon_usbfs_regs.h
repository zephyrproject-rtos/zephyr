#ifndef ZEPHYR_DRIVERS_USB_UDC_UDC_INFINEON_USBFS_REGS_H_
#define ZEPHYR_DRIVERS_USB_UDC_UDC_INFINEON_USBFS_REGS_H_

#include <zephyr/sys/util.h>

/* EP0_DR0..EP0_DR7, one byte each */
#define IFX_USBFS_EP0_DR(i)			(0x000U + 4U * (i))

/* CR0 */
#define IFX_USBFS_CR0				0x020U
#define IFX_USBFS_CR0_DEVICE_ADDRESS		GENMASK(6, 0)
#define IFX_USBFS_CR0_USB_ENABLE		BIT(7)

/* CR1 (§20.1.3) */
#define IFX_USBFS_CR1				0x024U
#define IFX_USBFS_CR1_REG_ENABLE		BIT(0)
#define IFX_USBFS_CR1_ENABLE_LOCK		BIT(1)
#define IFX_USBFS_CR1_BUS_ACTIVITY		BIT(2)
#define IFX_USBFS_CR1_RESERVED_3		BIT(3)

/* SIE_EP_INT_EN, SIE_EP_INT_SR: bit n - 1 for data endpoint n */
#define IFX_USBFS_SIE_EP_INT_EN			0x028U
#define IFX_USBFS_SIE_EP_INT_SR			0x02CU

/* SIE_EPn_CNT0, SIE_EPn_CNT1, SIE_EPn_CR0 for data endpoint n = 1..8 */
#define IFX_USBFS_SIE_EP_CNT0(n)		(0x030U + 0x40U * ((n) - 1U))
#define IFX_USBFS_SIE_EP_CNT1(n)		(0x034U + 0x40U * ((n) - 1U))
#define IFX_USBFS_SIE_EP_CR0(n)			(0x038U + 0x40U * ((n) - 1U))
#define IFX_USBFS_SIE_EP_CNT0_DATA_COUNT_MSB	GENMASK(2, 0)
#define IFX_USBFS_SIE_EP_CNT0_DATA_VALID	BIT(6)
#define IFX_USBFS_SIE_EP_CNT0_DATA_TOGGLE	BIT(7)
#define IFX_USBFS_SIE_EP_CNT1_DATA_COUNT	GENMASK(7, 0)
#define IFX_USBFS_SIE_EP_CR0_MODE		GENMASK(3, 0)
#define IFX_USBFS_SIE_EP_CR0_ACKED_TXN		BIT(4)
#define IFX_USBFS_SIE_EP_CR0_NAK_INT_EN		BIT(5)
#define IFX_USBFS_SIE_EP_CR0_ERR_IN_TXN		BIT(6)
#define IFX_USBFS_SIE_EP_CR0_STALL		BIT(7)

/* MODE encodings of SIE_EPn_CR0 and EP0_CR */
#define IFX_USBFS_MODE_DISABLE			0x0U
#define IFX_USBFS_MODE_NAK_INOUT		0x1U
#define IFX_USBFS_MODE_STATUS_OUT_ONLY		0x2U
#define IFX_USBFS_MODE_STALL_INOUT		0x3U
#define IFX_USBFS_MODE_ISO_OUT			0x5U
#define IFX_USBFS_MODE_STATUS_IN_ONLY		0x6U
#define IFX_USBFS_MODE_ISO_IN			0x7U
#define IFX_USBFS_MODE_NAK_OUT			0x8U
#define IFX_USBFS_MODE_ACK_OUT			0x9U
#define IFX_USBFS_MODE_ACK_OUT_STATUS_IN	0xBU
#define IFX_USBFS_MODE_NAK_IN			0xCU
#define IFX_USBFS_MODE_ACK_IN			0xDU
#define IFX_USBFS_MODE_ACK_IN_STATUS_OUT	0xFU

/* USBIO_CR0, USBIO_CR2, USBIO_CR1 */
#define IFX_USBFS_USBIO_CR0			0x040U
#define IFX_USBFS_USBIO_CR0_RD			BIT(0)
#define IFX_USBFS_USBIO_CR0_TD			BIT(5)
#define IFX_USBFS_USBIO_CR0_TSE0		BIT(6)
#define IFX_USBFS_USBIO_CR0_TEN			BIT(7)
#define IFX_USBFS_USBIO_CR2			0x044U
#define IFX_USBFS_USBIO_CR2_TEST_PKT		BIT(6)
#define IFX_USBFS_USBIO_CR2_RESERVED_7		BIT(7)
#define IFX_USBFS_USBIO_CR1			0x048U
#define IFX_USBFS_USBIO_CR1_DMO			BIT(0)
#define IFX_USBFS_USBIO_CR1_DPO			BIT(1)
#define IFX_USBFS_USBIO_CR1_RESERVED_2		BIT(2)
#define IFX_USBFS_USBIO_CR1_IOMODE		BIT(5)

/* DYN_RECONFIG; EPNO is the data endpoint number minus one */
#define IFX_USBFS_DYN_RECONFIG			0x050U
#define IFX_USBFS_DYN_RECONFIG_EN		BIT(0)
#define IFX_USBFS_DYN_RECONFIG_EPNO		GENMASK(3, 1)
#define IFX_USBFS_DYN_RECONFIG_RDY_STS		BIT(4)

/* EP0_CR*/
#define IFX_USBFS_EP0_CR			0x0A0U
#define IFX_USBFS_EP0_CR_MODE			GENMASK(3, 0)
#define IFX_USBFS_EP0_CR_ACKED_TXN		BIT(4)
#define IFX_USBFS_EP0_CR_OUT_RCVD		BIT(5)
#define IFX_USBFS_EP0_CR_IN_RCVD		BIT(6)
#define IFX_USBFS_EP0_CR_SETUP_RCVD		BIT(7)

/* EP0_CNT (§20.1.18) */
#define IFX_USBFS_EP0_CNT			0x0A4U
#define IFX_USBFS_EP0_CNT_BYTE_COUNT		GENMASK(3, 0)
#define IFX_USBFS_EP0_CNT_DATA_VALID		BIT(6)
#define IFX_USBFS_EP0_CNT_DATA_TOGGLE		BIT(7)

/* Arbiter registers for data endpoint n = 1..8 */
#define IFX_USBFS_ARB_EP_CFG(n)			(0x200U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_EP_INT_EN(n)		(0x204U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_EP_SR(n)			(0x208U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_RW_WA(n)			(0x210U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_RW_WA_MSB(n)		(0x214U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_RW_RA(n)			(0x218U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_RW_RA_MSB(n)		(0x21CU + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_RW_DR(n)			(0x220U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_EP_CFG_IN_DATA_RDY	BIT(0)
#define IFX_USBFS_ARB_EP_CFG_DMA_REQ		BIT(1)
#define IFX_USBFS_ARB_EP_CFG_CRC_BYPASS		BIT(2)
#define IFX_USBFS_ARB_EP_CFG_RESET_PTR		BIT(3)
/* Shared by ARB_EPn_INT_EN and ARB_EPn_SR - the SR has no ERR_INT bit. */
#define IFX_USBFS_ARB_EP_IN_BUF_FULL		BIT(0)
#define IFX_USBFS_ARB_EP_DMA_GNT		BIT(1)
#define IFX_USBFS_ARB_EP_BUF_OVER		BIT(2)
#define IFX_USBFS_ARB_EP_BUF_UNDER		BIT(3)
#define IFX_USBFS_ARB_EP_ERR_INT		BIT(4)
#define IFX_USBFS_ARB_EP_DMA_TERMIN		BIT(5)

/* BUF_SIZE */
#define IFX_USBFS_BUF_SIZE			0x230U
#define IFX_USBFS_BUF_SIZE_IN_BUF		GENMASK(3, 0)
#define IFX_USBFS_BUF_SIZE_OUT_BUF		GENMASK(7, 4)

/* EP_ACTIVE, EP_TYPE: bit n - 1 for data endpoint n - EP_TYPE 1 is OUT */
#define IFX_USBFS_EP_ACTIVE			0x238U
#define IFX_USBFS_EP_TYPE			0x23CU

/* ARB_CFG */
#define IFX_USBFS_ARB_CFG			0x270U
#define IFX_USBFS_ARB_CFG_AUTO_MEM		BIT(4)
#define IFX_USBFS_ARB_CFG_DMA_CFG		GENMASK(6, 5)
#define IFX_USBFS_ARB_CFG_CFG_CMP		BIT(7)
#define IFX_USBFS_ARB_CFG_DMA_CFG_NONE		0x0U
#define IFX_USBFS_ARB_CFG_DMA_CFG_MANUAL	0x1U
#define IFX_USBFS_ARB_CFG_DMA_CFG_AUTO		0x2U

/* USB_CLK_EN */
#define IFX_USBFS_USB_CLK_EN			0x274U
#define IFX_USBFS_USB_CLK_EN_CSR_CLK_EN		BIT(0)

/* ARB_INT_EN, ARB_INT_SR: bit n - 1 for data endpoint n */
#define IFX_USBFS_ARB_INT_EN			0x278U
#define IFX_USBFS_ARB_INT_SR			0x27CU

/* CWA, CWA_MSB */
#define IFX_USBFS_CWA				0x2B0U
#define IFX_USBFS_CWA_MSB			0x2B4U

/* DMA_THRES, DMA_THRES_MSB */
#define IFX_USBFS_DMA_THRES			0x2F0U
#define IFX_USBFS_DMA_THRES_MSB			0x2F4U

/* BUS_RST_CNT */
#define IFX_USBFS_BUS_RST_CNT			0x330U
#define IFX_USBFS_BUS_RST_CNT_COUNT		GENMASK(3, 0)

/* 9 bit views of the arbiter pointers and DMA threshold */
#define IFX_USBFS_ARB_RW_WA16(n)		(0x1210U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_RW_RA16(n)		(0x1218U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_RW_DR16(n)		(0x1220U + 0x40U * ((n) - 1U))
#define IFX_USBFS_ARB_RW_PTR16			GENMASK(8, 0)
#define IFX_USBFS_CWA16				0x12B0U
#define IFX_USBFS_DMA_THRES16			0x12F0U

/* USBLPM POWER_CTL */
#define IFX_USBFS_POWER_CTL			0x2000U
#define IFX_USBFS_POWER_CTL_SUSPEND		BIT(2)
#define IFX_USBFS_POWER_CTL_DP_UP_EN		BIT(16)
#define IFX_USBFS_POWER_CTL_DP_BIG		BIT(17)
#define IFX_USBFS_POWER_CTL_DP_DOWN_EN		BIT(18)
#define IFX_USBFS_POWER_CTL_DM_UP_EN		BIT(19)
#define IFX_USBFS_POWER_CTL_DM_BIG		BIT(20)
#define IFX_USBFS_POWER_CTL_DM_DOWN_EN		BIT(21)
#define IFX_USBFS_POWER_CTL_ENABLE_DPO		BIT(28)
#define IFX_USBFS_POWER_CTL_ENABLE_DMO		BIT(29)

/* USBLPM USBIO_CTL, FLOW_CTL, LPM_CTL */
#define IFX_USBFS_USBIO_CTL			0x2008U
#define IFX_USBFS_FLOW_CTL			0x200CU
#define IFX_USBFS_LPM_CTL			0x2010U
#define IFX_USBFS_LPM_CTL_LPM_EN		BIT(0)
#define IFX_USBFS_LPM_CTL_LPM_ACK_RESP		BIT(1)
#define IFX_USBFS_LPM_CTL_NYET_EN		BIT(2)
#define IFX_USBFS_LPM_CTL_SUB_RESP		BIT(4)

/* USBLPM INTR_SIE, _SET, _MASK, _MASKED share one bit layout */
#define IFX_USBFS_INTR_SIE			0x2020U
#define IFX_USBFS_INTR_SIE_SET			0x2024U
#define IFX_USBFS_INTR_SIE_MASK			0x2028U
#define IFX_USBFS_INTR_SIE_MASKED		0x202CU
#define IFX_USBFS_INTR_SIE_SOF			BIT(0)
#define IFX_USBFS_INTR_SIE_BUS_RESET		BIT(1)
#define IFX_USBFS_INTR_SIE_EP0			BIT(2)
#define IFX_USBFS_INTR_SIE_LPM			BIT(3)
#define IFX_USBFS_INTR_SIE_RESUME		BIT(4)

/* USBLPM INTR_LVL_SEL: a 2 bit level per source, 0 routes it to the HIGH
 * line, 1 to MEDIUM and 2 to LOW
 */
#define IFX_USBFS_INTR_LVL_SEL			0x2030U
#define IFX_USBFS_INTR_LVL_SEL_SOF		GENMASK(1, 0)
#define IFX_USBFS_INTR_LVL_SEL_BUS_RESET	GENMASK(3, 2)
#define IFX_USBFS_INTR_LVL_SEL_EP0		GENMASK(5, 4)
#define IFX_USBFS_INTR_LVL_SEL_LPM		GENMASK(7, 6)
#define IFX_USBFS_INTR_LVL_SEL_RESUME		GENMASK(9, 8)
#define IFX_USBFS_INTR_LVL_SEL_ARB_EP		GENMASK(15, 14)
#define IFX_USBFS_INTR_LVL_SEL_EP(n)		(GENMASK(17, 16) << (2U * ((n) - 1U)))
#define IFX_USBFS_INTR_LVL_HI			0x0U
#define IFX_USBFS_INTR_LVL_MED			0x1U
#define IFX_USBFS_INTR_LVL_LO			0x2U

/* USBLPM INTR_CAUSE_HI, _MED, _LO share one bit layout */
#define IFX_USBFS_INTR_CAUSE_HI			0x2034U
#define IFX_USBFS_INTR_CAUSE_MED		0x2038U
#define IFX_USBFS_INTR_CAUSE_LO			0x203CU
#define IFX_USBFS_INTR_CAUSE_SOF		BIT(0)
#define IFX_USBFS_INTR_CAUSE_BUS_RESET		BIT(1)
#define IFX_USBFS_INTR_CAUSE_EP0		BIT(2)
#define IFX_USBFS_INTR_CAUSE_LPM		BIT(3)
#define IFX_USBFS_INTR_CAUSE_RESUME		BIT(4)
#define IFX_USBFS_INTR_CAUSE_ARB_EP		BIT(7)
#define IFX_USBFS_INTR_CAUSE_EP(n)		BIT(8U + ((n) - 1U))

#endif /* ZEPHYR_DRIVERS_USB_UDC_UDC_INFINEON_USBFS_REGS_H_ */

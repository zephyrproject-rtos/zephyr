#ifndef ZEPHYR_DRIVERS_USB_UDC_SAM0_H
#define ZEPHYR_DRIVERS_USB_UDC_SAM0_H

#include <zephyr/sys/util_macro.h>

/* Common registers */
#define UDC_SAM0_CTRLA				0x00U
#define UDC_SAM0_SYNCBUSY			0x02U
#define UDC_SAM0_QOSCTRL			0x03U

/* Device registers */
#define UDC_SAM0_DEVICE_CTRLB			0x08U
#define UDC_SAM0_DEVICE_DADD			0x0AU
#define UDC_SAM0_DEVICE_INTENSET		0x18U
#define UDC_SAM0_DEVICE_INTFLAG			0x1CU
#define UDC_SAM0_DEVICE_EPINTSMRY		0x20U
#define UDC_SAM0_DESCADD			0x24U
#define UDC_SAM0_PADCAL				0x28U

/* Device endpoint registers, one block of 0x20 bytes per endpoint */
#define UDC_SAM0_DEVICE_ENDPOINT(n)		(0x100U + ((n) * 0x20U))
#define UDC_SAM0_DEVICE_EPCFG(n)		(UDC_SAM0_DEVICE_ENDPOINT(n) + 0x00U)
#define UDC_SAM0_DEVICE_EPSTATUSCLR(n)		(UDC_SAM0_DEVICE_ENDPOINT(n) + 0x04U)
#define UDC_SAM0_DEVICE_EPSTATUSSET(n)		(UDC_SAM0_DEVICE_ENDPOINT(n) + 0x05U)
#define UDC_SAM0_DEVICE_EPSTATUS(n)		(UDC_SAM0_DEVICE_ENDPOINT(n) + 0x06U)
#define UDC_SAM0_DEVICE_EPINTFLAG(n)		(UDC_SAM0_DEVICE_ENDPOINT(n) + 0x07U)
#define UDC_SAM0_DEVICE_EPINTENCLR(n)		(UDC_SAM0_DEVICE_ENDPOINT(n) + 0x08U)
#define UDC_SAM0_DEVICE_EPINTENSET(n)		(UDC_SAM0_DEVICE_ENDPOINT(n) + 0x09U)

/* CTRLA */
#define UDC_SAM0_CTRLA_SWRST			BIT(0)
#define UDC_SAM0_CTRLA_ENABLE			BIT(1)
#define UDC_SAM0_CTRLA_RUNSTDBY			BIT(2)
#define UDC_SAM0_CTRLA_MODE_Msk			BIT(7)
#define UDC_SAM0_CTRLA_MODE_DEVICE		0U

/* SYNCBUSY */
#define UDC_SAM0_SYNCBUSY_SWRST			BIT(0)
#define UDC_SAM0_SYNCBUSY_ENABLE		BIT(1)

/* QOSCTRL */
#define UDC_SAM0_QOSCTRL_CQOS_Msk		GENMASK(1, 0)
#define UDC_SAM0_QOSCTRL_DQOS_Msk		GENMASK(3, 2)

/* DEVICE_CTRLB */
#define UDC_SAM0_DEVICE_CTRLB_DETACH		BIT(0)
#define UDC_SAM0_DEVICE_CTRLB_UPRSM		BIT(1)
#define UDC_SAM0_DEVICE_CTRLB_SPDCONF_Msk	GENMASK(3, 2)
#define UDC_SAM0_DEVICE_CTRLB_SPDCONF_FS	0U

/* DEVICE_DADD */
#define UDC_SAM0_DEVICE_DADD_DADD_Msk		GENMASK(6, 0)
#define UDC_SAM0_DEVICE_DADD_ADDEN		BIT(7)

/* DEVICE_INTFLAG, shared with DEVICE_INTENSET */
#define UDC_SAM0_DEVICE_INTFLAG_SUSPEND		BIT(0)
#define UDC_SAM0_DEVICE_INTFLAG_SOF		BIT(2)
#define UDC_SAM0_DEVICE_INTFLAG_EORST		BIT(3)
#define UDC_SAM0_DEVICE_INTFLAG_EORSM		BIT(5)
#define UDC_SAM0_DEVICE_INTFLAG_RAMACER		BIT(7)

/* PADCAL */
#define UDC_SAM0_PADCAL_TRANSP_Msk		GENMASK(4, 0)
#define UDC_SAM0_PADCAL_TRANSN_Msk		GENMASK(10, 6)
#define UDC_SAM0_PADCAL_TRIM_Msk		GENMASK(14, 12)

/* DEVICE_EPCFG */
#define UDC_SAM0_DEVICE_EPCFG_EPTYPE0_Msk	GENMASK(2, 0)
#define UDC_SAM0_DEVICE_EPCFG_EPTYPE1_Msk	GENMASK(6, 4)

/* DEVICE_EPSTATUS, shared with DEVICE_EPSTATUSSET and DEVICE_EPSTATUSCLR */
#define UDC_SAM0_DEVICE_EPSTATUS_DTGLOUT	BIT(0)
#define UDC_SAM0_DEVICE_EPSTATUS_DTGLIN		BIT(1)
#define UDC_SAM0_DEVICE_EPSTATUS_STALLRQ0	BIT(4)
#define UDC_SAM0_DEVICE_EPSTATUS_STALLRQ1	BIT(5)
#define UDC_SAM0_DEVICE_EPSTATUS_BK0RDY		BIT(6)
#define UDC_SAM0_DEVICE_EPSTATUS_BK1RDY		BIT(7)

/* DEVICE_EPINTFLAG, shared with DEVICE_EPINTENSET and DEVICE_EPINTENCLR */
#define UDC_SAM0_DEVICE_EPINTFLAG_TRCPT0	BIT(0)
#define UDC_SAM0_DEVICE_EPINTFLAG_TRCPT1	BIT(1)
#define UDC_SAM0_DEVICE_EPINTFLAG_RXSTP		BIT(4)

#endif /* ZEPHYR_DRIVERS_USB_UDC_SAM0_H */

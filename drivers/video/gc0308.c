static int gc0308_set_subsampling(const struct device *dev, uint8_t ratio)
{
	const struct gc0308_config *cfg = dev->config;
	const struct video_reg regs[] = {
		{GC0308_REG8(GC0308_REG_PAGE_SELECT), GC0308_PAGE1},
		{GC0308_REG8(GC0308_REG_BAYER_MODE), GC0308_BAYER_MODE_SUB_GATE},
		{GC0308_REG8(GC0308_REG_SUB_MODE), GC0308_SUB_MODE_EXTEND_CLK},
		{GC0308_REG8(GC0308_REG_SUBSAMPLE), (ratio << GC0308_SUBSAMPLE_ROW_SHIFT) | ratio},
		{GC0308_REG8(GC0308_REG_SUB_ROW_N1), 0},
		{GC0308_REG8(GC0308_REG_SUB_ROW_N2), 0},
		{GC0308_REG8(GC0308_REG_SUB_COL_N1), 0},
		{GC0308_REG8(GC0308_REG_SUB_COL_N2), 0},
		{GC0308_REG8(GC0308_REG_PAGE_SELECT), GC0308_PAGE0},
	};

	return video_write_cci_multiregs(&cfg->bus, regs, ARRAY_SIZE(regs));
}

/* Program the read out window, in pixel array coordinates */
static int gc0308_set_window(const struct device *dev, const struct video_rect *rect)
{
	const struct gc0308_config *cfg = dev->config;
	const struct video_reg regs[] = {
		{GC0308_REG8(GC0308_REG_PAGE_SELECT), GC0308_PAGE0},
		{GC0308_REG16(GC0308_REG_ROWSTART), rect->top},
		{GC0308_REG16(GC0308_REG_COL_START), rect->left},
		{GC0308_REG16(GC0308_REG_WIN_HEIGHT), rect->height + GC0308_WIN_BLANKING},
		{GC0308_REG16(GC0308_REG_WIN_WIDTH), rect->width + GC0308_WIN_BLANKING},
	};
	uint32_t line = GC0308_HB_DEFAULT + rect->width + GC0308_WIN_BLANKING;
	const struct video_reg exposure[] = {
		{GC0308_REG16(GC0308_REG_ANTI_FLICKER_STEP_HI),
		 GC0308_ANTI_FLICKER_STEP_DEFAULT * GC0308_LINE_DEFAULT / line},
		{GC0308_REG16(GC0308_REG_EXP_LEVEL_1_HI),
		 GC0308_EXP_LEVEL_1_DEFAULT * GC0308_LINE_DEFAULT / line},
		{GC0308_REG16(GC0308_REG_EXP_LEVEL_2_HI),
		 GC0308_EXP_LEVEL_2_DEFAULT * GC0308_LINE_DEFAULT / line},
	};
	int ret;

	ret = video_write_cci_multiregs(&cfg->bus, regs, ARRAY_SIZE(regs));
	if (ret < 0) {
		return ret;
	}

	/* A no-op at the full width the vendor values were calibrated for */
	return video_write_cci_multiregs(&cfg->bus, exposure, ARRAY_SIZE(exposure));
}

/*
 * Used when the application does not drive the crop itself: pick the
 * largest window that subsamples down to the requested size, which set_fmt()
 * has already checked against the format caps.
 */
static int gc0308_set_resolution(const struct device *dev, uint16_t w, uint16_t h)
{
	struct gc0308_data *drv_data = dev->data;
	struct video_rect win;
	uint8_t ratio;
	int ret;

	ratio = CLAMP(MIN(RESOLUTION_MAX_W / w, RESOLUTION_MAX_H / h), 1,
		      GC0308_SUBSAMPLE_RATIO_MAX);

	win.width = w * ratio;
	win.height = h * ratio;
	win.left = (RESOLUTION_MAX_W - win.width) / 2;
	win.top = (RESOLUTION_MAX_H - win.height) / 2;

	ret = gc0308_set_window(dev, &win);
	if (ret < 0) {
		return ret;
	}

	ret = gc0308_set_subsampling(dev, ratio);
	if (ret < 0) {
		return ret;
	}

	drv_data->crop = win;

	/*
	 * Galaxy Core does not document why, but their reference code allows the
	 * sensor DSP some time to apply a window change before the next access.
	 */
	k_sleep(K_MSEC(GC0308_SETTLE_TIME));

	return 0;
}

static int gc0308_set_output_format(const struct device *dev, int output_format)
{
	const struct gc0308_config *cfg = dev->config;
	int ret;

	ret = video_write_cci_reg(&cfg->bus, GC0308_REG8(GC0308_REG_PAGE_SELECT), GC0308_PAGE0);
	if (ret < 0) {
		return ret;
	}

	if (output_format == VIDEO_PIX_FMT_RGB565X) {
		output_format = GC0308_OUTPUT_FORMAT_RGB565;
	} else if (output_format == VIDEO_PIX_FMT_YUYV) {
		output_format = GC0308_OUTPUT_FORMAT_YCBYCR;
	} else {
		LOG_ERR("Image format not supported");
		return -ENOTSUP;
	}

	ret = video_modify_cci_reg(&cfg->bus, GC0308_REG8(GC0308_REG_OUTPUT_FORMAT),
				   GC0308_OUTPUT_FORMAT_MASK, output_format);
	if (ret < 0) {
		return ret;
	}

	k_msleep(GC0308_SETTLE_TIME);

	return 0;
}

static int gc0308_set_fmt(const struct device *dev, struct video_format *fmt)
{
	struct gc0308_data *drv_data = dev->data;
	size_t idx;
	bool resize;
	int ret;

	if (memcmp(&drv_data->fmt, fmt, sizeof(drv_data->fmt)) == 0) {
		return 0;
	}

	resize = fmt->width != drv_data->crop.width || fmt->height != drv_data->crop.height;

	/* A size that came from video_set_selection() is applied already, and not in the caps */
	if (resize) {
		ret = video_format_caps_index(fmts, fmt, &idx);
		if (ret < 0) {
			LOG_ERR("Image format not supported");
			return ret;
		}
	}

	ret = gc0308_set_output_format(dev, fmt->pixelformat);
	if (ret < 0) {
		LOG_ERR("Failed to set the output format");
		return ret;
	}

	if (resize) {
		ret = gc0308_set_resolution(dev, fmt->width, fmt->height);
		if (ret < 0) {
			LOG_ERR("Failed to set the resolution");
			return ret;
		}
	}

	ret = video_estimate_fmt_size(fmt);
	if (ret < 0) {
		return ret;
	}

	drv_data->fmt = *fmt;
	return 0;
}

static int gc0308_get_fmt(const struct device *dev, struct video_format *fmt)
{
	struct gc0308_data *drv_data = dev->data;

	*fmt = drv_data->fmt;
	return 0;
}

static int gc0308_set_crop(const struct device *dev, struct video_selection *sel)
{
	struct gc0308_data *drv_data = dev->data;
	int ret;

	if (sel->rect.width < RESOLUTION_MIN_W || sel->rect.height < RESOLUTION_MIN_H ||
	    sel->rect.left + sel->rect.width > RESOLUTION_MAX_W ||
	    sel->rect.top + sel->rect.height > RESOLUTION_MAX_H) {
		LOG_ERR("Invalid crop rectangle (%u,%u) %ux%u", sel->rect.left, sel->rect.top,
			sel->rect.width, sel->rect.height);
		return -EINVAL;
	}

	if (memcmp(&drv_data->crop, &sel->rect, sizeof(drv_data->crop)) == 0) {
		return 0;
	}

	ret = gc0308_set_window(dev, &sel->rect);
	if (ret < 0) {
		return ret;
	}

	ret = gc0308_set_subsampling(dev, 1);
	if (ret < 0) {
		return ret;
	}

	k_sleep(K_MSEC(GC0308_SETTLE_TIME));

	drv_data->crop = sel->rect;
	drv_data->fmt.width = sel->rect.width;
	drv_data->fmt.height = sel->rect.height;

	return video_estimate_fmt_size(&drv_data->fmt);
}

static int gc0308_set_selection(const struct device *dev, struct video_selection *sel)
{
	if (sel->type != VIDEO_BUF_TYPE_OUTPUT) {
		return -EINVAL;
	}

	switch (sel->target) {
	case VIDEO_SEL_TGT_CROP:
		return gc0308_set_crop(dev, sel);
	default:
		return -EINVAL;
	}
}

static int gc0308_get_selection(const struct device *dev, struct video_selection *sel)
{
	struct gc0308_data *drv_data = dev->data;

	if (sel->type != VIDEO_BUF_TYPE_OUTPUT) {
		return -EINVAL;
	}

	switch (sel->target) {
	case VIDEO_SEL_TGT_CROP:
		sel->rect = drv_data->crop;
		break;
	case VIDEO_SEL_TGT_CROP_BOUND:
	case VIDEO_SEL_TGT_NATIVE_SIZE:
		sel->rect.left = 0;
		sel->rect.top = 0;
		sel->rect.width = RESOLUTION_MAX_W;
		sel->rect.height = RESOLUTION_MAX_H;
		break;
	default:
		return -EINVAL;
	}

	return 0;
}


static int gc0308_set_ctrl(const struct device *dev, uint32_t id)
{
	const struct gc0308_config *cfg = dev->config;
	struct gc0308_data *drv_data = dev->data;

	uint32_t bit;
	bool set;
	int ret;

	switch (id) {
	case VIDEO_CID_HFLIP:
	case VIDEO_CID_VFLIP:
		if (id == VIDEO_CID_HFLIP) {
			bit = GC0308_CISCTL_MODE_1_MIRROR;
			set = drv_data->ctrls.hflip.val;
		} else {
			bit = GC0308_CISCTL_MODE_1_UPDOWN;
			set = drv_data->ctrls.vflip.val;
		}

		ret = video_write_cci_reg(&cfg->bus, GC0308_REG8(GC0308_REG_PAGE_SELECT),
					  GC0308_PAGE0);
		if (ret < 0) {
			return ret;
		}

		return video_modify_cci_reg(&cfg->bus, GC0308_REG8(GC0308_REG_CISCTL_MODE_1), bit,
					    set ? bit : 0);
	case VIDEO_CID_EXPOSURE_AUTO:
		if (drv_data->ctrls.exposure_auto.val != VIDEO_EXPOSURE_AUTO &&
		    drv_data->ctrls.exposure_auto.val != VIDEO_EXPOSURE_MANUAL) {
			return -ENOTSUP;
		}

		ret = video_write_cci_reg(&cfg->bus, GC0308_REG8(GC0308_REG_PAGE_SELECT),
					  GC0308_PAGE0);
		if (ret < 0) {
			return ret;
		}

		/* Leave the rest of the register, the vendor sequence sets more of it */
		return video_modify_cci_reg(&cfg->bus, GC0308_REG8(GC0308_REG_AEC_MODE3),
					    GC0308_AEC_MODE3_AEC_EN,
					    drv_data->ctrls.exposure_auto.val == VIDEO_EXPOSURE_AUTO
						    ? GC0308_AEC_MODE3_AEC_EN
						    : 0);
	case VIDEO_CID_EXPOSURE: {
		const struct video_reg regs[] = {
			{GC0308_REG8(GC0308_REG_PAGE_SELECT), GC0308_PAGE0},
			{GC0308_REG16(GC0308_REG_EXPOSURE), drv_data->ctrls.exposure.val},
		};

		return video_write_cci_multiregs(&cfg->bus, regs, ARRAY_SIZE(regs));
	}
	case VIDEO_CID_GAIN:
		ret = video_write_cci_reg(&cfg->bus, GC0308_REG8(GC0308_REG_PAGE_SELECT),
					  GC0308_PAGE0);
		if (ret < 0) {
			return ret;
		}

		return video_modify_cci_reg(
			&cfg->bus, GC0308_REG8(GC0308_REG_GLOBAL_GAIN), GC0308_GLOBAL_GAIN_VAL,
			FIELD_PREP(GC0308_GLOBAL_GAIN_VAL, drv_data->ctrls.gain.val));
	default:
		return -ENOTSUP;
	}
}

static int gc0308_init_controls(const struct device *dev)
{
	int ret;
	struct gc0308_data *drv_data = dev->data;
	struct gc0308_ctrls *ctrls = &drv_data->ctrls;

	ret = video_init_ctrl(&ctrls->hflip, dev, VIDEO_CID_HFLIP,
			      (struct video_ctrl_range){.min = 0, .max = 1, .step = 1, .def = 0});
	if (ret) {
		return ret;
	}

	ret = video_init_ctrl(&ctrls->vflip, dev, VIDEO_CID_VFLIP,
			      (struct video_ctrl_range){.min = 0, .max = 1, .step = 1, .def = 0});
	if (ret < 0) {
		return ret;
	}

	/* Only the first two menu entries, the sensor has no priority modes */
	ret = video_init_menu_ctrl(&ctrls->exposure_auto, dev, VIDEO_CID_EXPOSURE_AUTO,
				   VIDEO_EXPOSURE_AUTO, NULL);
	if (ret < 0) {
		return ret;
	}

	ret = video_init_ctrl(
		&ctrls->exposure, dev, VIDEO_CID_EXPOSURE,
		(struct video_ctrl_range){
			.min = 0, .max = GC0308_EXPOSURE_MAX, .step = 1, .def = 0x96});
	if (ret < 0) {
		return ret;
	}

	return video_init_ctrl(
		&ctrls->gain, dev, VIDEO_CID_GAIN,
		(struct video_ctrl_range){.min = 0, .max = 63, .step = 1, .def = 0x14});
}

static int gc0308_init(const struct device *dev)
{
	const struct gc0308_config *config = dev->config;
	int ret;

	struct video_format fmt = {
		.type = VIDEO_BUF_TYPE_OUTPUT,
		.pixelformat = fmts[0].pixelformat,
		.width = fmts[0].width_min,
		.height = fmts[0].height_min,
	};

	if (!i2c_is_ready_dt(&config->bus)) {
		return -ENODEV;
	}

#if DT_ANY_INST_HAS_PROP_STATUS_OKAY(pwdn_gpios)
	if (config->pwdn.port != NULL) {
		if (!gpio_is_ready_dt(&config->pwdn)) {
			return -ENODEV;
		}
		ret = gpio_pin_configure_dt(&config->pwdn, GPIO_OUTPUT_ACTIVE);
		if (ret < 0) {
			LOG_ERR("Could not clear power down pin: %d", ret);
			return ret;
		}
	}
#endif
#if DT_ANY_INST_HAS_PROP_STATUS_OKAY(reset_gpios)
	if (config->reset.port != NULL) {
		if (!gpio_is_ready_dt(&config->reset)) {
			return -ENODEV;
		}
		ret = gpio_pin_configure_dt(&config->reset, GPIO_OUTPUT_ACTIVE);
		if (ret < 0) {
			LOG_ERR("Could not set reset pin: %d", ret);
			return ret;
		}
		ret = gpio_pin_set_dt(&config->reset, 0);
		if (ret < 0) {
			LOG_ERR("Error setting GPIO: %d\n", ret);
			return ret;
		}
		k_msleep(1);
	}
#endif

	uint32_t pid = 0x0000;

	k_msleep(GC0308_WAKE_UP_TIME);

	ret = video_read_cci_reg(&config->bus, GC0308_REG8(GC0308_REG_CHIP_ID), &pid);
	if (ret < 0) {
		LOG_ERR("Could not detect camera");
		return ret;
	}

	if (pid != GC0308_PROD_ID) {
		LOG_ERR("Incorrect product ID: 0x%02X", pid);
		return -ENODEV;
	}
	LOG_DBG("Product ID is: %x", pid);

	ret = video_write_cci_reg(&config->bus, GC0308_REG8(GC0308_REG_PAGE_SELECT),
				  GC0308_SOFT_RESET);
	if (ret < 0) {
		LOG_ERR("Could not write reset: %d", ret);
		return ret;
	}
	k_msleep(80);

	ret = video_write_cci_multiregs8(&config->bus, gc0308_default_regs,
					 ARRAY_SIZE(gc0308_default_regs));
	if (ret < 0) {
		LOG_ERR("Failed to set default registers");
		return ret;
	}

	ret = gc0308_set_fmt(dev, &fmt);
	if (ret < 0) {
		LOG_ERR("ERROR: Unable to set format");
		return ret;
	}

	return gc0308_init_controls(dev);
}


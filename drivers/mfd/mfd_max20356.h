/* One device-level init register write. A field contributes to @mask only when
 * its devicetree property is present, so entries with mask == 0 are skipped and
 * the chip's OTP defaults are preserved.
 */
struct mfd_max20356_init_reg {
	uint8_t reg;
	uint8_t mask;
	uint8_t val;
};

/* Number of MPC-routed hardware interrupt sources with an optional host GPIO
 * watch line, indexed by enum max20356_mpc_int_source.
 */
#define MAX20356_MPC_INT_COUNT 4U

struct mfd_max20356_config {
	struct i2c_dt_spec i2c;
	enum max20356_variant variant;
	const struct mfd_max20356_init_reg *init_regs;
	uint8_t num_init_regs;
#ifdef CONFIG_SPI
	/* SPI controller wired to MPC0/1/2 for SPI DVS (Mode 2); a spec with a
	 * NULL bus is unused. Shared by every buck selecting adi,dvs-mode = "spi".
	 */
	struct spi_dt_spec dvs_spi;
#endif
#ifdef CONFIG_MFD_MAX20356_TRIGGER
	struct gpio_dt_spec int_gpio;
	/* Optional host GPIO lines watching MPC pins that a buck-PGOOD or USBOK
	 * source is routed to; a line with a NULL port is unused.
	 */
	struct gpio_dt_spec mpc_int_gpio[MAX20356_MPC_INT_COUNT];
#endif
};

#ifdef CONFIG_MFD_MAX20356_TRIGGER
/* Per-line context for an MPC-routed interrupt: one embedded gpio_callback and
 * work item per line, recovered with CONTAINER_OF so a single shared handler
 * pair serves every line and src identifies which one fired.
 */
struct max20356_mpc_int_ctx {
	struct gpio_callback cb;
	struct k_work work;
	const struct device *dev;
	uint8_t src;
};
#endif

struct mfd_max20356_data {
#ifdef CONFIG_MFD_MAX20356_TRIGGER
	const struct device *dev;
	struct gpio_callback gpio_cb;
	struct k_mutex cb_lock;
	max20356_cb_t cb[MAX20356_EVT_MAX];
	void *cb_user[MAX20356_EVT_MAX];
	struct max20356_mpc_int_ctx mpc_int[MAX20356_MPC_INT_COUNT];
	/* Set while the watchdog owns INTB exclusively */
	bool wdt_active;
#if defined(CONFIG_MAX20356_TRIGGER_OWN_THREAD)
	K_KERNEL_STACK_MEMBER(thread_stack, CONFIG_MAX20356_THREAD_STACK_SIZE);
	struct k_thread thread;
	struct k_sem sem;
#else
	struct k_work work;
#endif
#endif
};

